# missing-natives artifact
# ---------------------------------------------------------------------------

def _native_key(entry):
    """Ratchet identity of a native blocker.

    Deliberately excludes `invocations`: an uninvoked stub is still a stub, so
    a newly appearing entry with `invocations: 0` must fail the ratchet exactly
    like an invoked one.
    """
    return (entry['category'], entry['class'], entry['name'],
            entry['descriptor'])


def _merge(entries, entry):
    key = _native_key(entry)
    existing = entries.get(key)
    if existing is None:
        entries[key] = entry
        return
    for source in entry['sources']:
        if source not in existing['sources']:
            existing['sources'].append(source)
    for field in ('module', 'sample_call_site', 'registered_by', 'overwrote',
                  'real_declaring_method', 'kind'):
        if existing.get(field) in (None, '') and entry.get(field) not in (None, ''):
            existing[field] = entry[field]
    if entry['invocations_known']:
        if existing['invocations_known']:
            existing['invocations'] = max(existing['invocations'],
                                          entry['invocations'])
        else:
            existing['invocations'] = entry['invocations']
            existing['invocations_known'] = True
    existing['requires_classification'] = (
        existing['requires_classification'] or entry['requires_classification'])


def build_missing_natives(inputs, ledger, classifier, jdk_feature):
    entries = {}

    # (a) Unresolved natives grouped by module -- the VM's own module answer,
    #     which is why this source is preferred over the flat log.
    grouped = inputs.data.get('missing-natives-grouped')
    if grouped is not None:
        modules = grouped.get('modules')
        if not isinstance(modules, dict):
            inputs.degrade('missing-natives-grouped has no "modules" object; '
                           'unresolved natives from that dump were skipped')
            modules = {}
        for module, rows in sorted(modules.items()):
            if not isinstance(rows, list):
                inputs.degrade('missing-natives-grouped module %r is not a '
                               'list; skipped' % module)
                continue
            for row in rows:
                if not isinstance(row, dict):
                    continue
                _merge(entries, _unresolved_entry(
                    row.get('class'), row.get('name'), row.get('descriptor'),
                    module, row.get('sample_call_site'),
                    'missing-natives-grouped'))

    # (b) Flat unresolved-native log. Same facts, no module column, so the
    #     module is derived locally.
    flat = inputs.data.get('missing-natives')
    if flat is not None:
        rows, ok = _rows(flat, 'missing_natives')
        if not ok:
            inputs.degrade('missing-natives has no "missing_natives" array; '
                           'that dump contributed nothing')
        for row in rows:
            class_name = row.get('class')
            _merge(entries, _unresolved_entry(
                class_name, row.get('name'), row.get('descriptor'),
                classifier.classify(class_name) if class_name else None,
                row.get('sample_call_site'), 'missing-natives'))

    # (c) `missing-native` / `missing-implementation` violations from the
    #     strict report. These are the dispatch-time refusals, which the
    #     missing-native log does not necessarily carry.
    report = inputs.data.get('jdk-only-report')
    if report is not None:
        rows, ok = _rows(report, 'violations')
        if not ok:
            inputs.degrade('jdk-only-report has no "violations" array')
        for row in rows:
            kind = row.get('kind')
            if kind not in ('missing-native', 'missing-implementation'):
                continue
            class_name = row.get('class')
            module = row.get('module')
            if not module and class_name:
                module = classifier.classify(class_name)
            _merge(entries, _unresolved_entry(
                class_name, row.get('method'), row.get('descriptor'), module,
                None, 'jdk-only-report:' + str(kind)))

    # (d) Every registration still classified `synthetic-stub`. Not asserted to
    #     be a defect: the kind is ambient and defaults to SyntheticStub, so
    #     some of these are mis-tagged permanent bridges. They are emitted with
    #     `requires_classification` and a pointer at the review checklist.
    registry_totals = None
    registry = inputs.data.get('native-registry')
    if registry is not None:
        counts = registry.get('counts')
        if isinstance(counts, dict):
            registry_totals = {k: counts[k] for k in sorted(counts)}
        rows, ok = _rows(registry, 'natives')
        if not ok:
            inputs.degrade('native-registry has no "natives" array; '
                           'synthetic-stub registrations were not enumerated')
        for row in rows:
            if row.get('kind') != 'synthetic-stub':
                continue
            class_name = row.get('class')
            invocations = row.get('invocations')
            _merge(entries, {
                'class': str(class_name or ''),
                'name': str(row.get('name') or ''),
                'descriptor': str(row.get('descriptor') or ''),
                'category': CAT_STUB_REGISTRATION,
                'module': classifier.classify(class_name) if class_name else None,
                'kind': 'synthetic-stub',
                'invocations': int(invocations) if isinstance(invocations, int) else 0,
                'invocations_known': isinstance(invocations, int),
                'registered_by': row.get('registered_by'),
                'overwrote': row.get('overwrote'),
                'real_declaring_method': row.get('real_declaring_method'),
                'sample_call_site': None,
                'sources': ['native-registry'],
                # The whole point: this row is a request for a human
                # classification decision, not an assertion of a defect.
                'requires_classification': True,
                'status': STATUS_OPEN,
                'status_note': None,
            })

    # Join the operator ledger on, then finalise ordering.
    final = []
    for key in sorted(entries):
        entry = entries[key]
        status, note = ledger.for_native(entry['class'], entry['name'],
                                         entry['descriptor'])
        entry['status'] = status
        entry['status_note'] = note
        entry['sources'] = sorted(entry['sources'])
        if entry['requires_classification']:
            entry['classification_reference'] = NATIVE_REVIEW_DOC
        final.append(_ordered_native(entry))

    counts = {
        'total': len(final),
        'open': sum(1 for e in final if e['status'] == STATUS_OPEN),
        'closed': sum(1 for e in final if e['status'] != STATUS_OPEN),
        'requires_classification': sum(
            1 for e in final if e['requires_classification']),
        'never_invoked': sum(
            1 for e in final if e['invocations_known'] and e['invocations'] == 0),
        'invocations_unknown': sum(
            1 for e in final if not e['invocations_known']),
        'by_category': _tally(final, 'category'),
        'by_status': _tally(final, 'status'),
        'by_module': _tally(final, 'module'),
    }

    return {
        'schema_version': SCHEMA_VERSION,
        'artifact': 'jdk-only-missing-natives',
        'jdk_feature': jdk_feature,
        'partial': inputs.partial,
        'inputs': {k: inputs.state[k] for k in sorted(inputs.state)},
        'module_table_source': classifier.source,
        'status_vocabulary': list(STATUS_VOCABULARY),
        'classification_reference': NATIVE_REVIEW_DOC,
        'contract_reference': CONTRACT_DOC,
        'notes': list(inputs.notes),
        'registry_totals': registry_totals,
        'counts': counts,
        'entries': final,
    }


def _unresolved_entry(class_name, name, descriptor, module, call_site, source):
    return {
        'class': str(class_name or ''),
        'name': str(name or ''),
        'descriptor': str(descriptor or ''),
        'category': CAT_UNRESOLVED,
        'module': module,
        'kind': None,
        # The unresolved log records the first call site and dedupes; it does
        # not carry a count. Saying 0 here would be a fabrication, so the
        # count is explicitly marked unknown.
        'invocations': 0,
        'invocations_known': False,
        'registered_by': None,
        'overwrote': None,
        'real_declaring_method': None,
        'sample_call_site': call_site,
        'sources': [source],
        'requires_classification': False,
        'status': STATUS_OPEN,
        'status_note': None,
    }


_NATIVE_FIELD_ORDER = (
    'class', 'name', 'descriptor', 'category', 'module', 'kind',
    'invocations', 'invocations_known', 'registered_by', 'overwrote',
    'real_declaring_method', 'sample_call_site', 'sources',
    'requires_classification', 'classification_reference', 'status',
    'status_note',
)


def _ordered_native(entry):
    out = {}
    for field in _NATIVE_FIELD_ORDER:
        if field in entry:
            out[field] = entry[field]
    return out


def _tally(entries, field):
    counts = {}
    for entry in entries:
        key = entry.get(field)
        key = 'unknown' if key is None else str(key)
        counts[key] = counts.get(key, 0) + 1
    return {k: counts[k] for k in sorted(counts)}


