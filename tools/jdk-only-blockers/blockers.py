"""Generate the per-JDK JDK-only blocker artifacts, and ratchet them in CI.

    target/jdk-only-audit/jdk-<feature>-missing-natives.json
    target/jdk-only-audit/jdk-<feature>-synthetic-dependencies.json

`jdk-only-audit.md` section 6 requires these two files per supported JDK
image, because no static source review can produce an exhaustive missing-method
list across JDK versions: native surfaces and class-library internals vary by
image, so the list is *generated per image* and is only valid for that image.

Consumes the runtime dumps written by `cratonvm` (see `--help` and the README
next to this file for the exact flags):

    --dump-native-registry          native census, schema_version 2
    --dump-missing-natives          flat unresolved-native log
    --dump-missing-natives-grouped  the same, grouped by JDK module
    --dump-class-origins            class-origin census, schema_version 1
    --jdk-only-report               violations + counters, schema_version 1

Design constraints, all of them load-bearing:

* **Deterministic.** Stable sort order everywhere, no timestamps, no absolute
  paths, LF newlines, ASCII-escaped JSON. Two runs over the same dumps produce
  byte-identical files, so the outputs can be committed as ratchet baselines
  and diffed across hosts.
* **Partial, never fabricated.** A missing or malformed input dump yields a
  partial result carrying an explicit note and `"partial": true`, never a
  silent zero. `--check` fails on a partial result unless `--allow-partial` is
  passed, because "the dump was not produced" must never read as "nothing is
  broken".
* **Allowed generation is not a blocker.** `vm-array`, `hidden-class`,
  `generated-lambda`, `generated-proxy` and `reflection-accessor` classes are
  legitimate (contract section 1 item 6) and are reported in a separate
  `allowed` section. Only `compatibility-stub` origins are blockers. Getting
  that distinction wrong is what makes an origin census useless.
* **`synthetic-stub` is a classification request, not a verdict.** The native
  kind is *ambient*: it comes from `NativeMethodRegistry::set_category` /
  `with_category`, not from a `register()` argument, and it defaults to
  `SyntheticStub`. A `register()` call outside a `with_category(...)` block is
  a stub by omission. Some `synthetic-stub` rows are therefore genuinely
  mis-tagged permanent bridges. Those entries carry
  `"requires_classification": true` and point at
  `docs/jdk-only-native-review.md`; this tool never asserts they are defects.

Exit codes:

    0  success
    1  ratchet failure -- the open blocker set grew against the baseline
    2  usage / configuration error (bad arguments, bad status ledger,
       undeterminable JDK feature version, missing baseline in --check)
    3  partial result where a complete one was required
"""

