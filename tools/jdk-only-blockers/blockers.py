# Status ledger
# ---------------------------------------------------------------------------

class StatusLedger:
    """Operator-maintained closure records, keyed by native triple / class.

    Nothing in a runtime dump can say "this was reviewed and closed" -- closure
    is a human judgement. The ledger is where that judgement is recorded and
    reviewed; the generator only joins it onto the machine-observed rows.
    """

    def __init__(self):
        self.natives = {}
        self.classes = {}
        self.used = set()
        self.source = None

    @classmethod
    def load(cls, path, errors):
        ledger = cls()
        if not path:
            return ledger
        if not os.path.isfile(path):
            # An absent ledger is normal: it means nothing has been closed yet.
            return ledger
        ledger.source = os.path.basename(path)
        try:
            with open(path, encoding='utf-8') as fh:
                data = json.load(fh)
        except (OSError, ValueError) as exc:
            errors.append('status ledger %s could not be parsed: %s: %s'
                          % (path, type(exc).__name__, exc))
            return ledger
        if not isinstance(data, dict):
            errors.append('status ledger %s is not a JSON object' % path)
            return ledger
        for row in data.get('natives') or []:
            if not isinstance(row, dict):
                errors.append('status ledger: natives[] entry is not an object')
                continue
            key = (str(row.get('class', '')), str(row.get('name', '')),
                   str(row.get('descriptor', '')))
            if not all(key):
                errors.append('status ledger: natives[] entry needs class, '
                              'name and descriptor (got %r)' % (key,))
                continue
            status = row.get('status', STATUS_OPEN)
            if status not in STATUS_VOCABULARY:
                errors.append(
                    'status ledger: %s.%s%s has status %r, which is not in the '
                    'closure vocabulary %s' % (key[0], key[1], key[2], status,
                                               list(STATUS_VOCABULARY)))
                continue
            ledger.natives[key] = (status, row.get('note'))
        for row in data.get('classes') or []:
            if not isinstance(row, dict):
                errors.append('status ledger: classes[] entry is not an object')
                continue
            name = str(row.get('name', ''))
            if not name:
                errors.append('status ledger: classes[] entry needs a name')
                continue
            status = row.get('status', STATUS_OPEN)
            if status not in STATUS_VOCABULARY:
                errors.append(
                    'status ledger: class %s has status %r, which is not in '
                    'the closure vocabulary %s'
                    % (name, status, list(STATUS_VOCABULARY)))
                continue
            ledger.classes[name] = (status, row.get('note'))
        return ledger

    def for_native(self, class_name, name, descriptor):
        key = (class_name, name, descriptor)
        hit = self.natives.get(key)
        if hit is None:
            return STATUS_OPEN, None
        self.used.add(('native',) + key)
        return hit

    def for_class(self, name):
        hit = self.classes.get(name)
        if hit is None:
            return STATUS_OPEN, None
        self.used.add(('class', name))
        return hit

    def stale(self):
        """Ledger rows that matched nothing this run, sorted."""
        out = []
        for key in self.natives:
            if ('native',) + key not in self.used:
                out.append('native %s.%s%s' % key)
        for name in self.classes:
            if ('class', name) not in self.used:
                out.append('class %s' % name)
        return sorted(out)


