_MODULE_TABLE_RE = re.compile(
    r'const\s+PREFIX_TO_MODULE\s*:\s*&\[\(&str,\s*&str\)\]\s*=\s*&\[(.*?)\n\s*\];',
    re.DOTALL,
)
_MODULE_ROW_RE = re.compile(r'\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)')


class ModuleClassifier:
    """Longest-prefix-first class-name -> JDK module name mapping."""

    def __init__(self, prefixes, source):
        self.prefixes = tuple(prefixes)
        self.source = source

    @classmethod
    def load(cls, repo_root):
        """Parse the table out of `vm/src/vm/vm_init.rs`, else fall back."""
        path = os.path.join(repo_root, 'vm', 'src', 'vm', 'vm_init.rs')
        try:
            with open(path, encoding='utf-8', errors='replace') as fh:
                text = fh.read()
        except OSError:
            return cls(_FALLBACK_MODULE_PREFIXES, 'fallback-table')
        match = _MODULE_TABLE_RE.search(text)
        if not match:
            return cls(_FALLBACK_MODULE_PREFIXES, 'fallback-table')
        rows = _MODULE_ROW_RE.findall(match.group(1))
        if not rows:
            return cls(_FALLBACK_MODULE_PREFIXES, 'fallback-table')
        return cls(rows, 'vm/src/vm/vm_init.rs')

    def classify(self, class_name):
        for prefix, module in self.prefixes:
            if class_name.startswith(prefix):
                return module
        return 'other'


