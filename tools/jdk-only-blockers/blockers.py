class Inputs:
    """Loaded dumps plus a per-role state string, and the note trail."""

    # Roles are reported verbatim in the `inputs` object of both artifacts.
    STATE_NOT_PROVIDED = 'not-provided'
    STATE_PRESENT = 'present'
    STATE_MISSING = 'missing'
    STATE_MALFORMED = 'malformed'

    def __init__(self):
        self.data = {}
        self.state = {}
        self.notes = []
        self.partial = False

    def load(self, role, path, required_for, degrade_when_absent=True):
        """Load one dump. `required_for` names what degrades without it.

        `degrade_when_absent=False` marks the role as genuinely optional --
        used for the flat unresolved-native log, which carries no fact the
        grouped dump does not already carry.
        """
        if not path:
            self.state[role] = self.STATE_NOT_PROVIDED
            self.data[role] = None
            if degrade_when_absent:
                self.notes.append(
                    'input %s was not provided; %s is incomplete. Re-run '
                    'cratonvm with the corresponding --dump flag.'
                    % (role, required_for))
                self.partial = True
            return None
        if not os.path.isfile(path):
            self.state[role] = self.STATE_MISSING
            self.data[role] = None
            self.notes.append(
                'input %s was requested but the file does not exist; %s is '
                'incomplete. A missing dump is NOT evidence of a clean run.'
                % (role, required_for))
            self.partial = True
            return None
        try:
            with open(path, encoding='utf-8') as fh:
                data = json.load(fh)
        except (OSError, ValueError) as exc:
            self.state[role] = self.STATE_MALFORMED
            self.data[role] = None
            self.notes.append(
                'input %s could not be parsed (%s); %s is incomplete. A '
                'malformed dump is NOT evidence of a clean run.'
                % (role, type(exc).__name__, required_for))
            self.partial = True
            return None
        if not isinstance(data, dict):
            self.state[role] = self.STATE_MALFORMED
            self.data[role] = None
            self.notes.append(
                'input %s parsed but is not a JSON object; %s is incomplete.'
                % (role, required_for))
            self.partial = True
            return None
        self.state[role] = self.STATE_PRESENT
        self.data[role] = data
        return data

    def note(self, text):
        self.notes.append(text)

    def degrade(self, text):
        self.notes.append(text)
        self.partial = True


def _rows(container, key):
    """A list-valued field, or [] plus a flag saying the shape was wrong."""
    value = container.get(key) if isinstance(container, dict) else None
    if isinstance(value, list):
        return [r for r in value if isinstance(r, dict)], True
    return [], value is None


