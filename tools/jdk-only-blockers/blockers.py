def _class_key(entry):
    return (entry['category'], entry['name'])


def build_synthetic_dependencies(inputs, ledger, jdk_feature):
    blockers = {}
    allowed = {}
    origin_counts = {}
    unknown_origins = set()

    origins = inputs.data.get('class-origins')
    if origins is not None:
        rows, ok = _rows(origins, 'classes')
        if not ok:
            inputs.degrade('class-origins has no "classes" array; the '
                           'compatibility-stub inventory is empty for the '
                           'wrong reason')
        for row in rows:
            origin = str(row.get('origin') or 'unknown')
            origin_counts[origin] = origin_counts.get(origin, 0) + 1
            name = str(row.get('name') or '')
            loader_id = row.get('loader_id')
            if origin == BLOCKER_ORIGIN:
                key = (CAT_STUB_CLASS, name)
                entry = blockers.get(key)
                if entry is None:
                    entry = {
                        'name': name,
                        'category': CAT_STUB_CLASS,
                        'origin': origin,
                        'reason': row.get('reason'),
                        'real_bytes_found': bool(row.get('real_bytes_found')),
                        'requested_by': row.get('requested_by'),
                        'loader_ids': [],
                        'occurrences': 0,
                        'sources': ['class-origins'],
                        'status': STATUS_OPEN,
                        'status_note': None,
                    }
                    blockers[key] = entry
                entry['occurrences'] += 1
                if isinstance(loader_id, int) and loader_id not in entry['loader_ids']:
                    entry['loader_ids'].append(loader_id)
                if entry['reason'] in (None, '') and row.get('reason'):
                    entry['reason'] = row.get('reason')
                if entry['requested_by'] in (None, '') and row.get('requested_by'):
                    entry['requested_by'] = row.get('requested_by')
                # `real_bytes_found` on ANY row is the interesting fact: it
                # means the image does have the bytes and the fabrication is
                # gratuitous.
                entry['real_bytes_found'] = (
                    entry['real_bytes_found'] or bool(row.get('real_bytes_found')))
            elif origin in ALLOWED_GENERATED_ORIGINS:
                bucket = allowed.setdefault(origin, {'classes': set(),
                                                     'count': 0})
                bucket['count'] += 1
                bucket['classes'].add(name)
            elif origin in REAL_BYTES_ORIGINS or origin == 'vm-internal':
                pass
            else:
                unknown_origins.add(origin)

    # Classes strict mode REFUSED to fabricate never reach the class census --
    # they were never defined. They are blockers all the same, and are the only
    # evidence of them a `--jdk-only` run leaves behind.
    report = inputs.data.get('jdk-only-report')
    if report is not None:
        rows, ok = _rows(report, 'violations')
        if not ok and inputs.state.get('jdk-only-report') == Inputs.STATE_PRESENT:
            inputs.degrade('jdk-only-report has no "violations" array; '
                           'refused compatibility classes were not enumerated')
        for row in rows:
            if row.get('kind') != 'compatibility-class-requested':
                continue
            name = str(row.get('class') or '')
            key = (CAT_CLASS_REFUSED, name)
            entry = blockers.get(key)
            if entry is None:
                entry = {
                    'name': name,
                    'category': CAT_CLASS_REFUSED,
                    'origin': BLOCKER_ORIGIN,
                    'reason': row.get('reason'),
                    'real_bytes_found': False,
                    'requested_by': row.get('requester'),
                    'loader_ids': [],
                    'occurrences': 0,
                    'sources': ['jdk-only-report'],
                    'status': STATUS_OPEN,
                    'status_note': None,
                }
                blockers[key] = entry
            entry['occurrences'] += 1

    if unknown_origins:
        # An origin tag this tool has never heard of must not be silently
        # treated as allowed. Name it and degrade the result.
        inputs.degrade(
            'class-origins contains origin tag(s) %s that this tool does not '
            'classify; they were counted but placed in neither the blocker nor '
            'the allowed set. Update ALLOWED_GENERATED_ORIGINS / '
            'REAL_BYTES_ORIGINS in tools/jdk-only-blockers/blockers.py.'
            % ', '.join(sorted(unknown_origins)))

    final_blockers = []
    for key in sorted(blockers):
        entry = blockers[key]
        status, note = ledger.for_class(entry['name'])
        entry['status'] = status
        entry['status_note'] = note
        entry['loader_ids'] = sorted(entry['loader_ids'])
        entry['sources'] = sorted(entry['sources'])
        final_blockers.append(_ordered_class(entry))

    final_allowed = []
    for origin in sorted(allowed):
        bucket = allowed[origin]
        final_allowed.append({
            'origin': origin,
            'disposition': 'allowed',
            'count': bucket['count'],
            'classes': sorted(bucket['classes']),
        })

    counts = {
        'blockers_total': len(final_blockers),
        'blockers_open': sum(1 for e in final_blockers
                             if e['status'] == STATUS_OPEN),
        'blockers_closed': sum(1 for e in final_blockers
                               if e['status'] != STATUS_OPEN),
        'allowed_generated_total': sum(b['count'] for b in final_allowed),
        'by_category': _tally(final_blockers, 'category'),
        'by_status': _tally(final_blockers, 'status'),
        'by_origin': {k: origin_counts[k] for k in sorted(origin_counts)},
    }

    return {
        'schema_version': SCHEMA_VERSION,
        'artifact': 'jdk-only-synthetic-dependencies',
        'jdk_feature': jdk_feature,
        'partial': inputs.partial,
        'inputs': {k: inputs.state[k] for k in sorted(inputs.state)},
        'status_vocabulary': list(STATUS_VOCABULARY),
        'allowed_generated_origins': list(ALLOWED_GENERATED_ORIGINS),
        'blocker_origin': BLOCKER_ORIGIN,
        'contract_reference': CONTRACT_DOC,
        'notes': list(inputs.notes),
        'counts': counts,
        'blockers': final_blockers,
        'allowed': final_allowed,
    }


_CLASS_FIELD_ORDER = (
    'name', 'category', 'origin', 'reason', 'real_bytes_found',
    'requested_by', 'loader_ids', 'occurrences', 'sources', 'status',
    'status_note',
)


def _ordered_class(entry):
    return {f: entry[f] for f in _CLASS_FIELD_ORDER if f in entry}


# ---------------------------------------------------------------------------
# Ratchet
# ---------------------------------------------------------------------------

def open_native_keys(doc):
    return {
        '%s|%s.%s%s' % (e.get('category'), e.get('class'), e.get('name'),
                        e.get('descriptor'))
        for e in doc.get('entries') or []
        if e.get('status', STATUS_OPEN) == STATUS_OPEN
    }


def open_class_keys(doc):
    return {
        '%s|%s' % (e.get('category'), e.get('name'))
        for e in doc.get('blockers') or []
        if e.get('status', STATUS_OPEN) == STATUS_OPEN
    }


def compare(current, baseline, extractor):
    """Return (added, removed) open-key lists, sorted.

    Growth is measured on the open-key *set*, which contains no invocation
    count: a brand-new stub with `invocations: 0` adds a key and therefore
    fails the ratchet exactly like an invoked one. An entry that regresses from
    a closed status back to `open` also adds a key, which is the intent.
    """
    now = extractor(current)
    before = extractor(baseline)
    return sorted(now - before), sorted(before - now)


# ---------------------------------------------------------------------------
# IO
# ---------------------------------------------------------------------------

def write_json(path, doc):
    """Deterministic write: LF newlines, ASCII escapes, fixed key order."""
    text = json.dumps(doc, indent=2, ensure_ascii=True) + '\n'
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)


def read_json(path):
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def artifact_names(feature):
    return ('jdk-%s-missing-natives.json' % feature,
            'jdk-%s-synthetic-dependencies.json' % feature)


# ---------------------------------------------------------------------------
# Feature-version resolution
# ---------------------------------------------------------------------------

def resolve_feature(explicit, inputs):
    if explicit is not None:
        return str(explicit), None
    report = inputs.data.get('jdk-only-report')
    if isinstance(report, dict):
        value = report.get('jdk_feature')
        if isinstance(value, int):
            return str(value), None
        if isinstance(value, str) and value.isdigit():
            return value, None
    return None, (
        'the JDK feature version could not be determined. These artifacts are '
        'only valid for one JDK image, so the version is part of the file name '
        'and cannot be guessed. Pass --jdk-feature N, or supply a '
        '--jdk-only-report dump whose "jdk_feature" is populated.')


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def build_parser():
    parser = argparse.ArgumentParser(
        prog='blockers.py',
        description='Generate (and ratchet) the per-JDK JDK-only blocker '
                    'artifacts from cratonvm runtime dumps.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='See tools/jdk-only-blockers/README.md.')
    parser.add_argument('--jdk-feature', metavar='N',
                        help='JDK feature version keying the output files. '
                             'Derived from --jdk-only-report when omitted.')
    parser.add_argument('--native-registry', metavar='FILE',
                        help='--dump-native-registry output (schema 2).')
    parser.add_argument('--missing-natives', metavar='FILE',
                        help='--dump-missing-natives output.')
    parser.add_argument('--missing-natives-grouped', metavar='FILE',
                        help='--dump-missing-natives-grouped output.')
    parser.add_argument('--class-origins', metavar='FILE',
                        help='--dump-class-origins output.')
    parser.add_argument('--jdk-only-report', metavar='FILE',
                        help='--jdk-only-report output (schema 1).')
    parser.add_argument('--out-dir', metavar='DIR',
                        default='target/jdk-only-audit',
                        help='where the two artifacts are written '
                             '(default: %(default)s).')
    parser.add_argument('--baseline-dir', metavar='DIR',
                        default='tools/jdk-only-blockers/baselines',
                        help='committed baselines (default: %(default)s).')
    parser.add_argument('--status-ledger', metavar='FILE',
                        default='tools/jdk-only-blockers/status-ledger.json',
                        help='operator closure records (default: %(default)s). '
                             'Absent means nothing has been closed yet.')
    parser.add_argument('--repo-root', metavar='DIR',
                        help='repository root, used to read the JDK module '
                             'table out of vm/src/vm/vm_init.rs. Defaults to '
                             'the checkout containing this script.')
    parser.add_argument('--check', action='store_true',
                        help='after generating, diff against the baseline and '
                             'exit non-zero if the open set grew.')
    parser.add_argument('--update-baseline', action='store_true',
                        help='copy the freshly generated artifacts into '
                             '--baseline-dir.')
    parser.add_argument('--allow-partial', action='store_true',
                        help='permit --check / --update-baseline on a partial '
                             'result. Off by default: a partial baseline bakes '
                             'in a false-clean ratchet.')
    parser.add_argument('--quiet', action='store_true',
                        help='suppress the human-readable summary.')
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    out = sys.stdout if not args.quiet else open(os.devnull, 'w')

    repo_root = args.repo_root or os.path.dirname(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

    ledger_errors = []
    ledger = StatusLedger.load(args.status_ledger, ledger_errors)
    if ledger_errors:
        for err in ledger_errors:
            print('error: %s' % err, file=sys.stderr)
        return 2

    inputs = Inputs()
    inputs.load('native-registry', args.native_registry,
                'the synthetic-stub registration inventory')
    grouped = inputs.load('missing-natives-grouped',
                          args.missing_natives_grouped,
                          'the module-attributed unresolved-native inventory')
    # The flat log is a strict subset of the grouped one (same rows, no module
    # column). Not passing it is only a gap when the grouped dump is also
    # absent -- otherwise demanding both would make every ordinary run partial.
    inputs.load('missing-natives', args.missing_natives,
                'the unresolved-native inventory',
                degrade_when_absent=grouped is None)
    inputs.load('class-origins', args.class_origins,
                'the compatibility-stub class inventory')
    inputs.load('jdk-only-report', args.jdk_only_report,
                'the dispatch-time refusal inventory')

    if all(state != Inputs.STATE_PRESENT for state in inputs.state.values()):
        print('error: no input dump could be read. Nothing was generated; an '
              'empty blocker file would falsely read as "nothing is broken".',
              file=sys.stderr)
        for note in inputs.notes:
            print('  note: %s' % note, file=sys.stderr)
        return 3

    feature, feature_error = resolve_feature(args.jdk_feature, inputs)
    if feature is None:
        print('error: %s' % feature_error, file=sys.stderr)
        return 2

    classifier = ModuleClassifier.load(repo_root)
    if classifier.source == 'fallback-table':
        inputs.note('the JDK module table could not be read from '
                    'vm/src/vm/vm_init.rs; the embedded fallback copy was used '
                    'and may have drifted.')

    natives_doc = build_missing_natives(inputs, ledger, classifier, feature)
    classes_doc = build_synthetic_dependencies(inputs, ledger, feature)
    # `build_*` may have appended notes / flipped `partial`; re-sync both docs
    # so the two artifacts always agree about the state of the run.
    for doc in (natives_doc, classes_doc):
        doc['partial'] = inputs.partial
        doc['notes'] = list(inputs.notes)

    stale = ledger.stale()
    all_notes = list(inputs.notes)
    if stale:
        all_notes.append(
            'status ledger row(s) matched nothing in this run: %s. Either the '
            'blocker is genuinely gone (drop the row) or this run did not '
            'exercise it (the ledger is not evidence on its own).'
            % ', '.join(stale))
        for doc in (natives_doc, classes_doc):
            doc['notes'] = list(all_notes)

    natives_name, classes_name = artifact_names(feature)
    natives_path = os.path.join(args.out_dir, natives_name)
    classes_path = os.path.join(args.out_dir, classes_name)
    write_json(natives_path, natives_doc)
    write_json(classes_path, classes_doc)

    print('jdk-only blockers  jdk=%s  %s' % (
        feature, 'PARTIAL' if inputs.partial else 'complete'), file=out)
    print('  wrote %s' % natives_path.replace(os.sep, '/'), file=out)
    print('  wrote %s' % classes_path.replace(os.sep, '/'), file=out)
    nc = natives_doc['counts']
    cc = classes_doc['counts']
    print('  missing natives : %d total, %d open, %d closed, %d awaiting '
          'classification' % (nc['total'], nc['open'], nc['closed'],
                              nc['requires_classification']), file=out)
    print('  synthetic deps  : %d blockers (%d open), %d allowed generated '
          'classes' % (cc['blockers_total'], cc['blockers_open'],
                       cc['allowed_generated_total']), file=out)
    for note in all_notes:
        print('  note: %s' % note, file=out)

    if inputs.partial:
        # Loud on stderr too: a partial run scrolling past in a CI log must not
        # be mistaken for a clean one.
        print('warning: PARTIAL result -- one or more input dumps were '
              'missing or malformed. The counts above are a floor, not a '
              'total.', file=sys.stderr)

    status = 0

    if args.update_baseline:
        if inputs.partial and not args.allow_partial:
            print('error: refusing to write a baseline from a partial result. '
                  'A partial baseline freezes a false-clean ratchet. Fix the '
                  'inputs, or pass --allow-partial deliberately.',
                  file=sys.stderr)
            return 3
        os.makedirs(args.baseline_dir, exist_ok=True)
        for name, doc in ((natives_name, natives_doc),
                          (classes_name, classes_doc)):
            path = os.path.join(args.baseline_dir, name)
            write_json(path, doc)
            print('  baseline updated: %s' % path.replace(os.sep, '/'),
                  file=out)

    if args.check:
        if inputs.partial and not args.allow_partial:
            print('error: refusing to ratchet a partial result -- a missing '
                  'input dump would read as a shrinking blocker set. Pass '
                  '--allow-partial only if you understand that.',
                  file=sys.stderr)
            return 3
        missing_baselines = [
            os.path.join(args.baseline_dir, n).replace(os.sep, '/')
            for n in (natives_name, classes_name)
            if not os.path.isfile(os.path.join(args.baseline_dir, n))]
        if missing_baselines:
            print('error: no committed baseline for JDK %s (%s). There is '
                  'nothing to ratchet against. Generate one with '
                  '--update-baseline and commit it.'
                  % (feature, ', '.join(missing_baselines)), file=sys.stderr)
            return 2
        for name, doc, extractor, label in (
                (natives_name, natives_doc, open_native_keys, 'missing native'),
                (classes_name, classes_doc, open_class_keys,
                 'synthetic dependency')):
            baseline_path = os.path.join(args.baseline_dir, name)
            try:
                baseline = read_json(baseline_path)
            except (OSError, ValueError) as exc:
                print('error: baseline %s could not be parsed: %s'
                      % (baseline_path.replace(os.sep, '/'), exc),
                      file=sys.stderr)
                return 2
            added, removed = compare(doc, baseline, extractor)
            if added:
                status = 1
                print('FAIL: %d new open %s blocker(s) vs the baseline:'
                      % (len(added), label), file=sys.stderr)
                for key in added:
                    print('  + %s' % key, file=sys.stderr)
            if removed:
                print('  %d %s blocker(s) closed since the baseline; refresh '
                      'it with --update-baseline:' % (len(removed), label),
                      file=out)
                for key in removed:
                    print('  - %s' % key, file=out)
            if not added and not removed:
                print('  %s ratchet: unchanged (%d open)'
                      % (label, len(extractor(doc))), file=out)
        if status == 0:
            print('  ratchet OK', file=out)
        else:
            print('error: the open blocker set grew. An entry that was never '
                  'invoked is still a blocker -- invocation counts are '
                  'deliberately not part of the ratchet key.', file=sys.stderr)

    return status


if __name__ == '__main__':
    sys.exit(main())
