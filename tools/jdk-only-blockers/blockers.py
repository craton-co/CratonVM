# An entry is *closed* only when it is implemented as a reviewed bridge,
# implemented as a reviewed intrinsic, executed from real bytecode, implemented
# as legitimate generated class bytes, or explicitly declared out of scope with
# a specification-consistent error. Anything else is open. There is no
# "wontfix", no "deferred" and no "probably fine": those all spell `open`.
STATUS_OPEN = 'open'
STATUS_VOCABULARY = (
    'open',            # not closed
    'bridge',          # reviewed NativeKind::Bridge
    'intrinsic',       # reviewed NativeKind::Intrinsic
    'real-bytecode',   # executed from real class bytes; the native is gone
    'generated-class',  # legitimate generated bytes (lambda/proxy/accessor)
    'out-of-scope',    # declared out of scope, spec-consistent error raised
)
CLOSED_STATUSES = frozenset(STATUS_VOCABULARY) - {STATUS_OPEN}

NATIVE_REVIEW_DOC = 'docs/jdk-only-native-review.md'
CONTRACT_DOC = 'docs/feature-designs/jdk-only-mode.md'

# Class origins that are *allowed* under `--jdk-only` (contract section 1 item
# 6 / section 5 rubric). These are reported separately and are never blockers.
