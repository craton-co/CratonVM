import java.lang.classfile.ClassBuilder;
import java.lang.classfile.ClassFile;
import java.lang.classfile.CodeBuilder;
import java.lang.constant.ClassDesc;
import java.lang.constant.ConstantDescs;
import java.lang.constant.MethodTypeDesc;
import java.util.Map;
import java.util.function.Consumer;

public class L7W107InitCallRules {

    static final ClassDesc OBJ = ConstantDescs.CD_Object;
    static final ClassDesc PARENT = ClassDesc.of("L7W107IcParent");
    static final ClassDesc CHILD = ClassDesc.of("L7W107IcChild");
    static final ClassDesc GRANDCHILD = ClassDesc.of("L7W107IcGrandChild");
    static final MethodTypeDesc VOID = MethodTypeDesc.of(ConstantDescs.CD_void);
    static final int PUB = ClassFile.ACC_PUBLIC;
    static final int PUB_STATIC = ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC;

    /** No stack maps: the code is straight-line, and the generator must not judge it. */
    static final ClassFile CF = ClassFile.of(ClassFile.StackMapsOption.DROP_STACK_MAPS);

    static byte[] cls(ClassDesc name, ClassDesc superClass, Consumer<ClassBuilder> body) {
        return CF.build(name, cb -> {
            cb.withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_SUPER);
            cb.withSuperclass(superClass);
            body.accept(cb);
        });
    }

    /** `<init>()V` running `target.<init>()V` on `this`. */
    static void ctor(ClassBuilder cb, ClassDesc target) {
        cb.withMethodBody("<init>", VOID, PUB, c -> c.aload(0).invokespecial(target, "<init>", VOID).return_());
    }

    static byte[] withStaticM(String name, Consumer<CodeBuilder> code) {
        return cls(ClassDesc.of(name), OBJ, cb -> {
            ctor(cb, OBJ);
            cb.withMethodBody("m", VOID, PUB_STATIC, code);
            // m() runs from <clinit>, so initialising the class links it and runs it.
            cb.withMethodBody("<clinit>", VOID, ClassFile.ACC_STATIC, c -> c
                .invokestatic(ClassDesc.of(name), "m", VOID).return_());
        });
    }

    static final class OneLoader extends ClassLoader {
        final Map<String, byte[]> classes;

        OneLoader(Map<String, byte[]> classes) {
            super(L7W107InitCallRules.class.getClassLoader());
            this.classes = classes;
        }

        @Override
        protected Class<?> findClass(String n) throws ClassNotFoundException {
            byte[] b = classes.get(n);
            if (b == null) {
                throw new ClassNotFoundException(n);
            }
            return defineClass(n, b, 0, b.length);
        }
    }

    static Map<String, byte[]> hierarchy() {
        return Map.of(
            "L7W107IcParent", cls(PARENT, OBJ, cb -> ctor(cb, OBJ)),
            "L7W107IcChild", cls(CHILD, PARENT, cb -> ctor(cb, PARENT)));
    }

    static void row(String label, String name, byte[] bytes) {
        java.util.HashMap<String, byte[]> all = new java.util.HashMap<>(hierarchy());
        all.put(name, bytes);
        try {
            Class.forName(name, true, new OneLoader(all));
            System.out.println(label + " -> ok");
        } catch (Throwable t) {
            String msg = String.valueOf(t.getMessage());
            String[] lines = msg.split("\n");
            System.out.println(label + " -> " + t.getClass().getName() + ": " + lines[0]);
            for (int i = 0; i + 1 < lines.length; i++) {
                String l = lines[i].trim();
                if (l.equals("Location:") || l.equals("Reason:")) {
                    System.out.println("  " + lines[i + 1].trim()
                        .replaceAll("\\(constant pool \\d+\\)", "(constant pool #)"));
                }
            }
        }
    }

    public static void main(String[] args) {
        row("grandchild-init-grandparent", "L7W107IcGrandChild",
            cls(GRANDCHILD, CHILD, cb -> ctor(cb, PARENT)));
        row("new-child-init-parent", "L7W107IcWrongInit", withStaticM("L7W107IcWrongInit", c -> c
            .new_(CHILD).dup().invokespecial(PARENT, "<init>", VOID).pop().return_()));
        row("init-twice", "L7W107IcInitTwice", withStaticM("L7W107IcInitTwice", c -> c
            .new_(OBJ).dup().dup().invokespecial(OBJ, "<init>", VOID).invokespecial(OBJ, "<init>", VOID)
            .pop().return_()));
        row("invokestatic-init", "L7W107IcStaticInit", withStaticM("L7W107IcStaticInit", c -> c
            .invokestatic(PARENT, "<init>", VOID).return_()));
        row("invokevirtual-init", "L7W107IcVirtualInit", withStaticM("L7W107IcVirtualInit", c -> c
            .new_(OBJ).dup().invokespecial(OBJ, "<init>", VOID).invokevirtual(OBJ, "<init>", VOID).return_()));
        byte[] newArray;
        try {
            newArray = withStaticM("L7W107IcNewArray", c -> c
                .with(java.lang.classfile.instruction.NewObjectInstruction.of(
                    c.constantPool().classEntry(c.constantPool().utf8Entry("[I"))))
                .pop().return_());
        } catch (RuntimeException e) {
            newArray = null;
        }
        if (newArray == null) {
            System.out.println("new-array-class -> generator refused");
        } else {
            row("new-array-class", "L7W107IcNewArray", newArray);
        }
        row("new-child-init-child", "L7W107IcRightInit", withStaticM("L7W107IcRightInit", c -> c
            .new_(CHILD).dup().invokespecial(CHILD, "<init>", VOID).pop().return_()));
    }
}
