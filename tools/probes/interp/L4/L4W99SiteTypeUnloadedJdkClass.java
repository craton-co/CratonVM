// (residue: a `java/` class the site names that is not loaded yet).
//
// HotSpot links an `invokehandle` site with
// `SystemDictionary::find_method_handle_type`: every class the site's
// descriptor names is RESOLVED (loaded if need be; through the caller's
// loader unless it is a public `java.lang` / `java.lang.invoke` class) and
// `LinkResolver::check_klass_accessibility(caller, klass)` runs on it, before
// the handle is looked at, on every execution. Whether anything loaded the
// class before does not matter. CratonVM's link skipped `java/` names when
// loading, and its access check judged only a class it could find without
// loading, so a package-private `java.*` class nobody had loaded yet
// (`java.util.JumboEnumSet`, `java.util.ArrayPrefixHelpers`) got no verdict
