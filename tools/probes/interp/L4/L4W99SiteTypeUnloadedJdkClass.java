import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.io.IOException;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public class L4W99SiteTypeUnloadedJdkClass {
    static final String CALLER = "L4W99SiteTypeUnloadedJdkClassCaller";
    static final String CHILD_CALLER = "L4W99SiteTypeUnloadedJdkClassChild";
    static final int WARM = 20000;

    public static Object make(Object o) {
        return "made:" + o;
    }

    /** A tiny constant pool: entries keyed by their encoding, deduplicated. */
    static final class Pool {
        final Map<String, Integer> index = new LinkedHashMap<>();
        final ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        final DataOutputStream out = new DataOutputStream(bytes);
        int next = 1;

        int utf8(String s) throws IOException {
            Integer at = index.get("U" + s);
            if (at != null) {
                return at;
            }
            out.writeByte(1);
            out.writeUTF(s);
            index.put("U" + s, next);
            return next++;
        }

        int cls(String name) throws IOException {
            int u = utf8(name);
            Integer at = index.get("C" + name);
            if (at != null) {
                return at;
            }
            out.writeByte(7);
            out.writeShort(u);
            index.put("C" + name, next);
            return next++;
        }

        int methodref(String owner, String name, String desc) throws IOException {
            int c = cls(owner);
            int n = utf8(name);
            int d = utf8(desc);
            out.writeByte(12);
            out.writeShort(n);
            out.writeShort(d);
            int nat = next++;
            out.writeByte(10);
            out.writeShort(c);
            out.writeShort(nat);
            return next++;
        }
    }

    /** `{door, site parameter type}` per generated method `c0`, `c1`, ... */
    static byte[] callerBytes(String self, List<String[]> sites) throws IOException {
        Pool pool = new Pool();
        int thisClass = pool.cls(self);
        int superClass = pool.cls("java/lang/Object");
        int code = pool.utf8("Code");
        int callDesc = pool.utf8("(Ljava/lang/invoke/MethodHandle;)Ljava/lang/Object;");
        int[] names = new int[sites.size()];
        int[] refs = new int[sites.size()];
        for (int i = 0; i < sites.size(); i++) {
            names[i] = pool.utf8("c" + i);
            refs[i] = pool.methodref("java/lang/invoke/MethodHandle", sites.get(i)[0],
                    "(L" + sites.get(i)[1] + ";)Ljava/lang/Object;");
        }
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        DataOutputStream out = new DataOutputStream(bytes);
        out.writeInt(0xCAFEBABE);
        out.writeShort(0);
        out.writeShort(52); // no branch: no StackMapTable needed
        out.writeShort(pool.next);
        pool.out.flush();
        out.write(pool.bytes.toByteArray());
        out.writeShort(0x0001 | 0x0020); // ACC_PUBLIC | ACC_SUPER
        out.writeShort(thisClass);
        out.writeShort(superClass);
        out.writeShort(0); // interfaces
        out.writeShort(0); // fields
        out.writeShort(sites.size());
        for (int i = 0; i < sites.size(); i++) {
            out.writeShort(0x0001 | 0x0008); // ACC_PUBLIC | ACC_STATIC
            out.writeShort(names[i]);
            out.writeShort(callDesc);
            out.writeShort(1);
            out.writeShort(code);
            // aload_0; aconst_null; invokevirtual #ref; areturn
            byte[] body = {0x2a, 0x01, (byte) 0xb6, (byte) (refs[i] >> 8), (byte) refs[i], (byte) 0xb0};
            out.writeInt(12 + body.length);
            out.writeShort(2); // max_stack
            out.writeShort(1); // max_locals
            out.writeInt(body.length);
            out.write(body);
            out.writeShort(0); // exception table
            out.writeShort(0); // code attributes
        }
        out.writeShort(0); // class attributes
        out.flush();
        return bytes.toByteArray();
    }

    /** A plain parent-first user loader named `child`. */
    static final class Child extends ClassLoader {
        Child(ClassLoader parent) {
            super("child", parent);
        }

        Class<?> define(String name, byte[] b) {
            return defineClass(name, b, 0, b.length);
        }
    }

    static String describe(Throwable t) {
        return (t.getClass().getName() + ": " + t.getMessage()).replaceAll("@(0x)?[0-9a-f]+", "@<hash>");
    }

    static String once(MethodHandle call, MethodHandle mh) {
        try {
            return String.valueOf((Object) call.invokeExact(mh));
        } catch (Throwable t) {
            return describe(t);
        }
    }

    static void row(String name, MethodHandle call, MethodHandle mh) {
        System.out.println(name + ": " + once(call, mh));
    }

    /** The site called WARM times; the first outcome kept, the others compared by class and text. */
    static void warm(String name, MethodHandle call, MethodHandle mh) {
        Class<?> firstClass = null;
        String firstText = null;
        String firstShown = null;
        int differ = 0;
        for (int i = 0; i < WARM; i++) {
            Class<?> c;
            String text;
            try {
                Object r = (Object) call.invokeExact(mh);
                c = String.class;
                text = String.valueOf(r);
            } catch (Throwable t) {
                c = t.getClass();
                text = t.getMessage();
                if (firstShown == null) {
                    firstShown = describe(t);
                }
            }
            if (i == 0) {
                firstClass = c;
                firstText = text;
                if (firstShown == null) {
                    firstShown = text;
                }
            } else if (c != firstClass || !String.valueOf(text).equals(String.valueOf(firstText))) {
                differ++;
            }
        }
        System.out.println(name + ": " + firstShown
                + (differ == 0 ? " [all " + WARM + " same]" : " [" + differ + " differ]"));
    }

    public static void main(String[] args) throws Throwable {
        MethodHandles.Lookup lookup = MethodHandles.lookup();
        MethodHandle mh = lookup.findStatic(L4W99SiteTypeUnloadedJdkClass.class, "make",
                MethodType.methodType(Object.class, Object.class));
        MethodType callType = MethodType.methodType(Object.class, MethodHandle.class);

        List<String[]> sites = new ArrayList<>();
        sites.add(new String[] {"invokeExact", "java/util/concurrent/Exchanger"}); // c0
        sites.add(new String[] {"invoke", "java/util/concurrent/Phaser"}); // c1
        sites.add(new String[] {"invokeExact", "java/util/JumboEnumSet"}); // c2
        sites.add(new String[] {"invoke", "java/util/ArrayPrefixHelpers"}); // c3
        sites.add(new String[] {"invokeExact", "jdk/internal/util/xml/PropertiesDefaultHandler"}); // c4
        sites.add(new String[] {"invoke", "jdk/internal/util/xml/SAXParser"}); // c5
        Class<?> caller = lookup.defineClass(callerBytes(CALLER, sites));
        MethodHandle[] c = new MethodHandle[sites.size()];
        for (int i = 0; i < c.length; i++) {
            c[i] = lookup.findStatic(caller, "c" + i, callType);
        }

        List<String[]> childSites = new ArrayList<>();
        childSites.add(new String[] {"invokeExact", "java/util/JumboEnumSet"}); // d0 (loaded by then)
        childSites.add(new String[] {"invoke", "java/util/ArrayPrefixHelpers$CumulateTask"}); // d1
        childSites.add(new String[] {"invoke", "java/util/concurrent/Exchanger"}); // d2
        Class<?> child = new Child(L4W99SiteTypeUnloadedJdkClass.class.getClassLoader())
                .define(CHILD_CALLER, callerBytes(CHILD_CALLER, childSites));
        MethodHandle[] d = new MethodHandle[childSites.size()];
        for (int i = 0; i < d.length; i++) {
            d[i] = MethodHandles.publicLookup().findStatic(child, "c" + i, callType);
        }

        row("public-exact-1", c[0], mh);
        row("public-exact-2", c[0], mh);
        row("public-invoke-1", c[1], mh);
        row("public-invoke-2", c[1], mh);
        row("package-private-exact-1", c[2], mh);
        row("package-private-exact-2", c[2], mh);
        row("package-private-invoke-1", c[3], mh);
        row("package-private-invoke-2", c[3], mh);
        row("not-exported-exact-1", c[4], mh);
        row("not-exported-exact-2", c[4], mh);
        row("not-exported-invoke-1", c[5], mh);
        row("not-exported-invoke-2", c[5], mh);
        row("child-loaded-package-private-1", d[0], mh);
        row("child-loaded-package-private-2", d[0], mh);
        row("child-unloaded-package-private-1", d[1], mh);
        row("child-unloaded-package-private-2", d[1], mh);
        row("child-public-1", d[2], mh);
        row("child-public-2", d[2], mh);

        warm("warm-public-exact", c[0], mh);
        warm("warm-public-invoke", c[1], mh);
        warm("warm-package-private-exact", c[2], mh);
        warm("warm-package-private-invoke", c[3], mh);
        warm("warm-not-exported-exact", c[4], mh);
        warm("warm-not-exported-invoke", c[5], mh);
        warm("warm-child-unloaded-package-private", d[1], mh);
    }
}
