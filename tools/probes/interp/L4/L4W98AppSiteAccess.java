// Interpreter round i4 wave 98, lane L4 -- page
// `docs/internal/fixed-bugs/interpreter-i97-L4-first-execution-of-a-real-handle-site-skips-the-link-access-check-FIXED-20261015.md`
// (the OPEN residue: an APPLICATION-loader caller).
//
// HotSpot links an `invokehandle` site by resolving its `MethodType` through
// the caller (`SystemDictionary::find_method_handle_type`), and runs
// `LinkResolver::check_klass_accessibility(caller, klass)` on every class the
// descriptor names, before the handle is looked at: a class of another
// runtime package the caller may not access is an `IllegalAccessError` at the
// site, on every execution, for `invokeExact` (no `WrongMethodTypeException`
// first) and `invoke` alike. Wave 97 ran that link only for a USER loader's
// caller; an application class's site ran the member.
//
// The caller (`L4W98AppSiteAccessCaller`) is generated byte by byte (javac
// will not compile a reference to an inaccessible class) and defined in the
// application loader with `Lookup.defineClass`. Each of its methods is
//   public static Object cN(MethodHandle mh) { return mh.<door>((T) null); }
// with the site descriptor `(T)Ljava/lang/Object;`; the handle is `(Object)Object`.
//
// `jdk-misc-unsafe-*`: public, package not exported (module message).
// `javax-package-private`: package-private class of an exported package.
// `java-package-private`: the same in a `java/` package (wave 98 second
//   pass: the link judges `java/` names, once per site per thread).
// `javax-public`: public and exported: the call runs (`invoke` converts).
// `own-package`: the caller's own package (the default one): runs.
//
// No setup. Identity hashes are printed as `@<hash>`.
//
// HOTSPOT_EXPECTED_BEGIN (JDK 25; derived from the HotSpot sources)
// caller-loader: app
// jdk-misc-unsafe-exact: java.lang.IllegalAccessError: class L4W98AppSiteAccessCaller (in unnamed module @<hash>) cannot access class jdk.internal.misc.Unsafe (in module java.base) because module java.base does not export jdk.internal.misc to unnamed module @<hash>
// jdk-misc-unsafe-invoke: java.lang.IllegalAccessError: class L4W98AppSiteAccessCaller (in unnamed module @<hash>) cannot access class jdk.internal.misc.Unsafe (in module java.base) because module java.base does not export jdk.internal.misc to unnamed module @<hash>
// jdk-misc-unsafe-again: java.lang.IllegalAccessError: class L4W98AppSiteAccessCaller (in unnamed module @<hash>) cannot access class jdk.internal.misc.Unsafe (in module java.base) because module java.base does not export jdk.internal.misc to unnamed module @<hash>
// javax-package-private: java.lang.IllegalAccessError: failed to access class javax.crypto.CryptoAllPermission from class L4W98AppSiteAccessCaller (javax.crypto.CryptoAllPermission is in module java.base of loader 'bootstrap'; L4W98AppSiteAccessCaller is in unnamed module of loader 'app')
// java-package-private: java.lang.IllegalAccessError: failed to access class java.util.ImmutableCollections from class L4W98AppSiteAccessCaller (java.util.ImmutableCollections is in module java.base of loader 'bootstrap'; L4W98AppSiteAccessCaller is in unnamed module of loader 'app')
// javax-public: made:null
// own-package: made:null
// own-package-exact-wrong-type: java.lang.invoke.WrongMethodTypeException: handle's method type (Object)Object but found (L4W98AppSiteAccessOwn)Object
