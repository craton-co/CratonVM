import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.io.IOException;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public class L4W98AppSiteAccess {
    static final String CALLER = "L4W98AppSiteAccessCaller";

    public static Object make(Object o) {
        return "made:" + o;
    }

    /** A tiny constant pool: entries keyed by their encoding, deduplicated. */
    static final class Pool {
        final Map<String, Integer> index = new LinkedHashMap<>();
        final ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        final DataOutputStream out = new DataOutputStream(bytes);
        int next = 1;

        int utf8(String s) throws IOException {
            Integer at = index.get("U" + s);
            if (at != null) {
                return at;
            }
            out.writeByte(1);
            out.writeUTF(s);
            index.put("U" + s, next);
            return next++;
        }

        int cls(String name) throws IOException {
            int u = utf8(name);
            Integer at = index.get("C" + name);
            if (at != null) {
                return at;
            }
            out.writeByte(7);
            out.writeShort(u);
            index.put("C" + name, next);
            return next++;
        }

        int methodref(String owner, String name, String desc) throws IOException {
            int c = cls(owner);
            int n = utf8(name);
            int d = utf8(desc);
            out.writeByte(12);
            out.writeShort(n);
            out.writeShort(d);
            int nat = next++;
            out.writeByte(10);
            out.writeShort(c);
            out.writeShort(nat);
            return next++;
        }
    }

    /** `{door, site parameter type}` per generated method `c0`, `c1`, ... */
    static byte[] callerBytes(List<String[]> sites) throws IOException {
        Pool pool = new Pool();
        int thisClass = pool.cls(CALLER);
        int superClass = pool.cls("java/lang/Object");
        int code = pool.utf8("Code");
        int callDesc = pool.utf8("(Ljava/lang/invoke/MethodHandle;)Ljava/lang/Object;");
        int[] names = new int[sites.size()];
        int[] refs = new int[sites.size()];
        for (int i = 0; i < sites.size(); i++) {
            names[i] = pool.utf8("c" + i);
            refs[i] = pool.methodref("java/lang/invoke/MethodHandle", sites.get(i)[0],
                    "(L" + sites.get(i)[1] + ";)Ljava/lang/Object;");
        }
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        DataOutputStream out = new DataOutputStream(bytes);
        out.writeInt(0xCAFEBABE);
        out.writeShort(0);
        out.writeShort(52); // no branch: no StackMapTable needed
        out.writeShort(pool.next);
        pool.out.flush();
        out.write(pool.bytes.toByteArray());
        out.writeShort(0x0001 | 0x0020); // ACC_PUBLIC | ACC_SUPER
        out.writeShort(thisClass);
        out.writeShort(superClass);
        out.writeShort(0); // interfaces
        out.writeShort(0); // fields
        out.writeShort(sites.size());
        for (int i = 0; i < sites.size(); i++) {
            out.writeShort(0x0001 | 0x0008); // ACC_PUBLIC | ACC_STATIC
            out.writeShort(names[i]);
            out.writeShort(callDesc);
            out.writeShort(1);
            out.writeShort(code);
            // aload_0; aconst_null; invokevirtual #ref; areturn
            byte[] body = {0x2a, 0x01, (byte) 0xb6, (byte) (refs[i] >> 8), (byte) refs[i], (byte) 0xb0};
            out.writeInt(12 + body.length);
            out.writeShort(2); // max_stack
            out.writeShort(1); // max_locals
            out.writeInt(body.length);
            out.write(body);
            out.writeShort(0); // exception table
            out.writeShort(0); // code attributes
        }
        out.writeShort(0); // class attributes
        out.flush();
        return bytes.toByteArray();
    }

    interface Row {
        Object run() throws Throwable;
    }

    static void row(String name, Row r) {
        String out;
        try {
            out = String.valueOf(r.run());
        } catch (InvocationTargetException e) {
            Throwable t = e.getCause();
            out = t.getClass().getName() + ": " + t.getMessage();
        } catch (Throwable t) {
            out = t.getClass().getName() + ": " + t.getMessage();
        }
        System.out.println(name + ": " + out.replaceAll("@(0x)?[0-9a-f]+", "@<hash>"));
    }

    public static void main(String[] args) throws Throwable {
        MethodHandle mh = MethodHandles.lookup().findStatic(L4W98AppSiteAccess.class, "make",
                MethodType.methodType(Object.class, Object.class));
        List<String[]> sites = new ArrayList<>();
        sites.add(new String[] {"invokeExact", "jdk/internal/misc/Unsafe"}); // c0
        sites.add(new String[] {"invoke", "jdk/internal/misc/Unsafe"}); // c1
        sites.add(new String[] {"invoke", "javax/crypto/CryptoAllPermission"}); // c2
        sites.add(new String[] {"invoke", "java/util/ImmutableCollections"}); // c3
        sites.add(new String[] {"invoke", "javax/crypto/Cipher"}); // c4
        sites.add(new String[] {"invoke", "L4W98AppSiteAccessOwn"}); // c5
        sites.add(new String[] {"invokeExact", "L4W98AppSiteAccessOwn"}); // c6
        Class<?> caller = MethodHandles.lookup().defineClass(callerBytes(sites));
        row("caller-loader", () ->
                caller.getClassLoader() == ClassLoader.getSystemClassLoader() ? "app" : "other");
        Method[] c = new Method[sites.size()];
        for (int i = 0; i < c.length; i++) {
            c[i] = caller.getMethod("c" + i, MethodHandle.class);
        }
        row("jdk-misc-unsafe-exact", () -> c[0].invoke(null, mh));
        row("jdk-misc-unsafe-invoke", () -> c[1].invoke(null, mh));
        row("jdk-misc-unsafe-again", () -> c[1].invoke(null, mh));
        row("javax-package-private", () -> c[2].invoke(null, mh));
        row("java-package-private", () -> c[3].invoke(null, mh));
        row("javax-public", () -> c[4].invoke(null, mh));
        row("own-package", () -> c[5].invoke(null, mh));
        row("own-package-exact-wrong-type", () -> c[6].invoke(null, mh));
    }
}

