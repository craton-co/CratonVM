    static void errRow(String name, ErrLoop loop, boolean hotClassOnly) {
        String cold = attempt(loop, 1, 0);
        long warm = 0;
        for (int r = 0; r < 40; r++) warm += loop.run(1000, -1);
        String hot = attempt(loop, 1000, 999);
        if (hotClassOnly) hot = classOnly(hot);
        int bad = 0;
        for (int k = 0; k < 2000; k++) {
            String again = attempt(loop, 8, 7);
            if (!(hotClassOnly ? classOnly(again) : again).equals(hot)) bad++;
        }
        String coldSame = hotClassOnly ? classOnly(cold) : cold;
        System.out.println("fact " + name + " cold " + cold);
        System.out.println("fact " + name + " warm " + warm);
        System.out.println("fact " + name + " hot " + hot);
        System.out.println("fact " + name + " badrepeat " + bad + " same-as-cold " + hot.equals(coldSame));
    }

