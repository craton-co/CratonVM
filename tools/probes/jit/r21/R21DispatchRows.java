//   coli   |CRATONVM_JIT_MEGA_VTABLE_COLUMN=1 CRATONVM_JIT_MEGA_VTABLE_COLUMN_IFACE=1|   +36 % with
//   lean   |CRATONVM_JIT_MEGA_LEAN_STUB_HIT=1|    the lean stub hit), split: deciders *-mega8-late,
