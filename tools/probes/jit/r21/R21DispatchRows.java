    interface Row { long run(int n); }

    static void time(String name, Row r, int ops) {
        for (int w = 0; w < 5; w++) sink += r.run(ops);
        long[] reps = new long[7];
        for (int k = 0; k < reps.length; k++) {
            long t0 = System.nanoTime();
            sink += r.run(ops);
            reps[k] = System.nanoTime() - t0;
        }
        Arrays.sort(reps);
        System.out.println("time " + name + " "
                + String.format(Locale.ROOT, "%.2f", reps[reps.length / 2] / (double) ops) + " ns/op");
    }

