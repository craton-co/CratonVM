// JIT round 21 wave 4, lane ic: virtual / interface dispatch from compiled code -- inline caches,
// the megamorphic paths (per-site hashed ways, the VM's shared table and its per-class cells), and
// receiver profiles. Facts are driven at MEGAMORPHIC sites (8 receiver classes) unless named mono:
// the splice lane's R21SpliceRows covers the same JVMS rules at mono / bi sites.
//
// Facts (every line self-checks with an `expected` value where one exists):
//   late-mono       a site warmed with ONE class (CHA-mono), then a subclass that overrides, loaded
//                   by name afterwards: the override runs.
//   late-mega       a site warmed megamorphic with 8 subclasses that all inherit MBase.m, then a
//                   class loaded later that overrides it (by name: 70; generated in package g: 80),
//                   and the generated class's PUBLIC mpp() that does NOT override the package-private
//                   MBase.mpp (JVMS 5.4.5, another runtime package): 1.
//   twin-*          one class name (R21DispatchRows$Twin) defined by three loaders, each copy's
//                   static TAG different (1 / 2 / 3): one interface site and one virtual site see all
//                   three plus other classes; a site warmed with copy 1 then given copy 2; and one
//                   CALLER class (TwinRunner) defined by each loader, whose own megamorphic site runs
//                   its own loader's Twin. An inline cache or shared-table key that named a class by
//                   NAME (not identity) would run copy 1's body (TAG 1) for copy 2.
//   dia-mega        default methods at a megamorphic invokeinterface site: a more specific default
//                   (DB extends DA), the same pair in the other order, an inherited default under a
//                   class, a class method over a default; dia-virt: invokevirtual X3.d resolving to
//                   the default DA.d while the receiver X7 selects the more specific DB.d.
//   priv-mega       an interface default calling its interface's PRIVATE method (javac emits
//                   invokeinterface) while each of 8 receivers declares a public namesake: 5 always.
//   err-*           linkage errors raised AT A HOT MEGAMORPHIC SITE (cold = first, interpreted call;
//                   hot = after 40000 good calls through 8 receivers; badrepeat = hot calls of 2000
//                   whose text differs, expected 0). Receivers built with java.lang.classfile:
//                   err-ame-iface   g.AmeNo implements AmeI without ame()  -> AbstractMethodError
//                   err-ame-virt    g.AmeSub extends AmeBase without vame() -> AbstractMethodError
//                                   (hot / repeat lines by exception class only: HotSpot's compiled
//                                   stub words this AME differently from its interpreter)
//                   err-conflict    g.CdBoth implements CdA, CdB (two defaults) -> ICCE
//                   err-icce        invokeinterface AmeI.ame on NotAme (implements nothing; the site is
//                                   generated bytecode with no checkcast) -> ICCE
// Time rows (one op = one call at the row's own site; 8-slot receiver arrays, median of 7 reps of
// <ops> calls after 5 warm-up reps):
//   virt-mono / virt-bi / virt-poly4 / virt-mega8       invokevirtual, 1 / 2 / 4 / 8 classes
//   iface-mono / iface-bi / iface-poly4 / iface-mega8   invokeinterface, 1 / 2 / 4 / 8 classes
//   iface-default-mega8   8 classes, 4 inheriting the interface default, 4 overriding it
//   virt-mega8-early / -late, iface-mega8-early / -late   ONE site per kind: warmed (and timed) with 8
//                   classes, then timed with 8 further classes first loaded after the site compiled
//                   (the R19Mega5Nested late-class-mega-call shape)
//   virt-sv-mega8   8 shallow classes (their shared-table cell arrays are made here, short)
//   iface-depth-mega8   an interface site whose FIRST receiver declares the method deep in a long
//                   vtable (column ~20), then the 7 shallow classes above: under the default their
//                   cells are refused (census `mic_cell_past_array`), under IC21-1 they are grown
//
// Run lines (build: javac -d tools/probes/out tools/probes/jit/r21/R21DispatchRows.java):
//   P=tools/probes/out
//   cratonvm -Xmx512m -cp $P R21DispatchRows                    # --jdk-only (launcher default)
//   cratonvm --compatible -Xmx512m -cp $P R21DispatchRows       # both modes: the same fact lines
//   java -Xmx512m -cp $P R21DispatchRows                        # HotSpot 25 reference
//   optional arguments: calls per timed rep (default 2000000); `facts` prints the fact lines only.
// Arms (interleaved, >= 7 reps, per-row medians; every fact line identical in every arm):
//   def    ||
//   grow   |CRATONVM_JIT_MEGA_CLASS_ROW_GROW=1|   IC21-1 (this lane): decider iface-depth-mega8;
//          engagement: one run each of def / grow with CRATONVM_DBG=mic-prof, `mic_cell_past_array`
//          must drop to ~0 under grow (and `mic_cell` rise); every other row flat
//   baked  |CRATONVM_JIT_MEGA_VTABLE_COLUMN=1 CRATONVM_JIT_MEGA_VTABLE_COLUMN_BAKED=1|   IC21-2 (this
//          lane), against `col`: deciders virt-mega8, virt-mega8-late, virt-sv-mega8 (every site here is
//          in the default package, so the compile-time bind applies); engagement: CRATONVM_DBG=mic-prof
//          `mic_unbound_table_held` falls to 0 for those sites (they are bound from birth)
//   space  |CRATONVM_JIT_MEGA_IFACE_COLUMN_SPACE=1|   IC21-3 (this lane; turns row growth on), and
//   spacec |CRATONVM_JIT_MEGA_IFACE_COLUMN_SPACE=1 CRATONVM_JIT_MEGA_VTABLE_COLUMN=1 CRATONVM_JIT_MEGA_VTABLE_COLUMN_IFACE=1|
