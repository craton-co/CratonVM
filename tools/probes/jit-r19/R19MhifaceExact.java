import java.lang.classfile.ClassFile;
import java.lang.constant.ClassDesc;
import java.lang.constant.ConstantDescs;
import java.lang.constant.MethodTypeDesc;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.util.Arrays;

// JIT round 19 wave 1, lane mhiface: a `static final` interface `findVirtual` handle called by
// invokeExact / invoke from compiled code (MHRESID18-4, CRATONVM_JIT_MH_CONSTANT_INTERFACE,
// opt-in: the optimizing tier compiles the site as an invokeinterface behind an instanceof guard;
// CRATONVM_JIT_MH_CONSTANT_BIND_DIRECT_INTERFACE, opt-in: the helper's bound interface site enters
// the cached compiled entry). Page:
// docs/internal/fixed-bugs/r18-mh-interface-handle-invokeexact-costs-microseconds-FIXED-20261007.md
//
// Answer lines (must match HotSpot 25 byte for byte, every arm, both modes):
//   mono      one implementor, invokeExact: a sum
//   bi        two implementors alternating (bimorphic): a sum
//   default   a default method handle, overridden by one implementor: a sum
//   invoke    MethodHandle.invoke at the handle's exact type: a sum
//   secret    a private interface method through findSpecial: a sum, or the lookup's refusal
//   null      a null receiver after warm-up: the exception, every call
//   wrong     a receiver whose class does not implement the interface (generated bytecode passes
//             an Object where the site's type says Fn; the verifier does not check interface
//             assignability), after warm-up: the exception every call, never Impostor.apply's 999
//   after     mono again after the failing rows
// Timing lines (`time <row> <n> ns/op`, median of reps): mono, bi, default, invoke.
// Usage: R19MhifaceExact [reps]   (default 9)
public class R19MhifaceExact {
    interface Fn {
        int apply(int x);

        default int twice(int x) { return 2 * apply(x); }

        private int secret(int x) { return apply(x) + 1000; }

        static MethodHandles.Lookup lookup() { return MethodHandles.lookup(); }
    }

    static final class AddSeven implements Fn {
        public int apply(int x) { return x + 7; }
    }

    static final class Times3 implements Fn {
        public int apply(int x) { return 3 * x; }

        public int twice(int x) { return 6 * x + 1; }
    }

    // Not an Fn, but has a same-named, same-typed method: a compiled call that dispatched by
    // name instead of guarding the interface would return 999 here.
    public static final class Impostor {
        public int apply(int x) { return 999; }
    }

    static final MethodHandle APPLY;
    static final MethodHandle TWICE;
    static final MethodHandle SECRET;
    static final String SECRET_REFUSAL;

    static {
        try {
            MethodHandles.Lookup l = MethodHandles.lookup();
            MethodType ii = MethodType.methodType(int.class, int.class);
            APPLY = l.findVirtual(Fn.class, "apply", ii);
            TWICE = l.findVirtual(Fn.class, "twice", ii);
        } catch (ReflectiveOperationException e) {
            throw new ExceptionInInitializerError(e);
        }
        MethodHandle s = null;
        String refusal = null;
        try {
            s = Fn.lookup().findSpecial(Fn.class, "secret",
                    MethodType.methodType(int.class, int.class), Fn.class);
        } catch (Throwable t) {
            refusal = describe(t);
        }
        SECRET = s;
        SECRET_REFUSAL = refusal;
    }

    static String describe(Throwable t) {
        return t.getClass().getName() + ": " + t.getMessage();
    }

    static long mono(Fn f, int n) throws Throwable {
        long sum = 0;
        for (int i = 0; i < n; i++) {
            sum += (int) APPLY.invokeExact(f, i);
        }
        return sum;
    }

    static long bi(Fn[] fs, int n) throws Throwable {
        long sum = 0;
        for (int i = 0; i < n; i++) {
            sum += (int) APPLY.invokeExact(fs[i & 1], i);
        }
        return sum;
    }

    static long twice(Fn[] fs, int n) throws Throwable {
        long sum = 0;
        for (int i = 0; i < n; i++) {
            sum += (int) TWICE.invokeExact(fs[i & 1], i);
        }
        return sum;
    }

    static long invoke(Fn f, int n) throws Throwable {
        long sum = 0;
        for (int i = 0; i < n; i++) {
            sum += (int) APPLY.invoke(f, i);
        }
        return sum;
    }

    static long secret(Fn f, int n) throws Throwable {
        long sum = 0;
        for (int i = 0; i < n; i++) {
            sum += (int) SECRET.invokeExact(f, i);
        }
        return sum;
    }

    // One compiled call per element; `fs` may hold a null at its end.
    static String failingNull(Fn[] fs, int n) {
        int thrown = 0;
        String first = "none";
        long sum = 0;
        for (int i = 0; i < n; i++) {
            try {
                sum += (int) APPLY.invokeExact(fs[i % fs.length], i);
            } catch (Throwable t) {
                if (thrown++ == 0) first = describe(t);
            }
        }
        return "throws=" + thrown + " sum=" + sum + " first=" + first;
    }

    // Generated: static int call(Object o, int i) {
    //   return (int) R19MhifaceExact.APPLY.invokeExact((R19MhifaceExact$Fn) <o, unchecked>, i); }
    static MethodHandle generatedCaller() throws Throwable {
        ClassDesc self = ClassDesc.of("R19MhifaceExact");
        ClassDesc fn = ClassDesc.of("R19MhifaceExact$Fn");
        ClassDesc mh = ClassDesc.of("java.lang.invoke.MethodHandle");
        MethodTypeDesc site = MethodTypeDesc.of(ConstantDescs.CD_int, fn, ConstantDescs.CD_int);
        MethodTypeDesc call = MethodTypeDesc.of(ConstantDescs.CD_int, ConstantDescs.CD_Object,
                ConstantDescs.CD_int);
        byte[] bytes = ClassFile.of().build(ClassDesc.of("R19MhifaceExactGen"), cb -> cb
                .withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL)
                .withMethodBody("call", call, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, code -> code
                        .getstatic(self, "APPLY", mh)
                        .aload(0)
                        .iload(1)
                        .invokevirtual(mh, "invokeExact", site)
                        .ireturn()));
        Class<?> gen = MethodHandles.lookup().defineClass(bytes);
        return MethodHandles.lookup().findStatic(gen, "call", MethodType.methodType(int.class,
                Object.class, int.class));
    }

    static String failingWrong(MethodHandle call, Object[] os, int n) {
        int thrown = 0;
        String first = "none";
        long sum = 0;
        for (int i = 0; i < n; i++) {
            try {
                sum += (int) call.invokeExact(os[i % os.length], i);
            } catch (Throwable t) {
                if (thrown++ == 0) first = describe(t);
            }
        }
        return "throws=" + thrown + " sum=" + sum + " first=" + first;
    }

    static long median(long[] xs) {
        long[] c = xs.clone();
        Arrays.sort(c);
        return c[c.length / 2];
    }

    static String nsPerOp(long ns, long ops) {
        return String.format(java.util.Locale.ROOT, "%.1f", (double) ns / ops);
    }

    public static void main(String[] a) throws Throwable {
        int reps = a.length > 0 ? Integer.parseInt(a[0]) : 9;
        final int n = 1000;
        final int calls = 200;
        Fn add = new AddSeven();
        Fn[] two = { new AddSeven(), new Times3() };
        // Warm-up: every kernel entered often enough to be compiled by its invocation counter.
        long mono = 0, bi = 0, dflt = 0, inv = 0;
        for (int c = 0; c < 2000; c++) {
            mono = mono(add, n);
            bi = bi(two, n);
            dflt = twice(two, n);
            inv = invoke(add, n);
        }
        System.out.println("mono " + mono);
        System.out.println("bi " + bi);
        System.out.println("default " + dflt);
        System.out.println("invoke " + inv);
        if (SECRET != null) {
            long s = 0;
            for (int c = 0; c < 200; c++) s = secret(add, n);
            System.out.println("secret " + s);
        } else {
            System.out.println("secret refused " + SECRET_REFUSAL);
        }
        Fn[] withNull = { add, add, add, null };
        for (int c = 0; c < 2000; c++) failingNull(new Fn[] { add }, 100);
        System.out.println("null " + failingNull(withNull, 2000));
        String wrong;
        try {
            MethodHandle call = generatedCaller();
            Object[] good = { add };
            for (int c = 0; c < 2000; c++) failingWrong(call, good, 100);
            wrong = failingWrong(call, new Object[] { add, new Impostor() }, 2000);
        } catch (Throwable t) {
            wrong = "unavailable " + describe(t);
        }
        System.out.println("wrong " + wrong);
        System.out.println("after " + mono(add, n));
        long[] tMono = new long[reps], tBi = new long[reps], tDef = new long[reps],
                tInv = new long[reps];
        long ops = (long) n * calls;
        for (int r = 0; r < reps; r++) {
            long t0 = System.nanoTime();
            for (int c = 0; c < calls; c++) mono(add, n);
            long t1 = System.nanoTime();
            for (int c = 0; c < calls; c++) bi(two, n);
            long t2 = System.nanoTime();
            for (int c = 0; c < calls; c++) twice(two, n);
            long t3 = System.nanoTime();
            for (int c = 0; c < calls; c++) invoke(add, n);
            long t4 = System.nanoTime();
            tMono[r] = t1 - t0;
            tBi[r] = t2 - t1;
            tDef[r] = t3 - t2;
            tInv[r] = t4 - t3;
        }
        System.out.println("time mono " + nsPerOp(median(tMono), ops) + " ns/op");
        System.out.println("time bi " + nsPerOp(median(tBi), ops) + " ns/op");
        System.out.println("time default " + nsPerOp(median(tDef), ops) + " ns/op");
        System.out.println("time invoke " + nsPerOp(median(tInv), ops) + " ns/op");
    }
}
