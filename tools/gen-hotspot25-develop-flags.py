"""Generate vm-cli/src/hotspot25_develop_flags.rs: the `-XX:` names a HotSpot 25
product build knows although `-XX:+PrintFlagsFinal` does not list them.

The launcher refuses an unknown `-XX:` name with HotSpot's `Unrecognized VM
option` lines (`CRATONVM_LAUNCHER_UNKNOWN_XX_REFUSAL`). "Unknown" has to mean
what it means to HotSpot, and a product build knows three kinds of name that
its flag listing leaves out:

* `develop` flags, refused with `Error: VM option '<Name>' is develop and is
  available only in debug version of VM.` and a spelling line;
* obsolete flags, taken with `Ignoring option <Name>; support was removed in
  <version>`;
* aliases (`CreateMinidumpOnCrash`), taken with a deprecation warning.

None of them is listed anywhere a product JDK prints, so this script asks the
JDK itself: every NUL-terminated identifier in `libjvm` that the listing does
not have is tried as `-XX:+<Name> -version`, and the answer classifies it.

    usage: python -I tools/gen-hotspot25-develop-flags.py <java> [<out.rs>]

The answer depends only on the flag table compiled into `libjvm`, not on the
host; run it against the JDK the launcher targets.
"""
import concurrent.futures
import os
import re
import subprocess
import sys

UNLOCK = ['-XX:+UnlockDiagnosticVMOptions', '-XX:+UnlockExperimentalVMOptions']


def libjvm(java):
    home = os.path.dirname(os.path.dirname(os.path.realpath(java)))
    for rel in ('lib/server/libjvm.so', 'bin/server/jvm.dll', 'lib/server/libjvm.dylib'):
        path = os.path.join(home, rel)
        if os.path.exists(path):
            return path
    raise SystemExit(f'no libjvm under {home}')


def listed(java):
    r = subprocess.run([java, *UNLOCK, '-XX:+PrintFlagsFinal', '-version'],
                       capture_output=True, text=True, check=True)
    names = set()
    for line in r.stdout.splitlines()[1:]:
        parts = line.split()
        if len(parts) > 1:
            names.add(parts[1])
    return names, next((l for l in r.stderr.splitlines() if 'Runtime Environment' in l), '?')


def candidates(path):
    data = open(path, 'rb').read()
    return {m.group(1).decode() for m in re.finditer(rb'(?<![\x21-\x7e])([A-Z][A-Za-z0-9_]{3,70})\x00', data)}


def probe(java, name):
    r = subprocess.run([java, f'-XX:+{name}', '-version'], capture_output=True, text=True)
    first = (r.stdout + r.stderr).splitlines()
    return name, first[:3]


def main():
    java = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else 'vm-cli/src/hotspot25_develop_flags.rs'
    names, version = listed(java)
    todo = sorted(candidates(libjvm(java)) - names)
    develop, obsolete, aliases = [], [], []
    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        for name, lines in pool.map(lambda n: probe(java, n), todo):
            head = lines[0] if lines else ''
            if head.startswith('Unrecognized VM option'):
                continue
            if head == f"Error: VM option '{name}' is develop and is available only in debug version of VM.":
                second = lines[1] if len(lines) > 1 else ''
                if second == f"Improperly specified VM option '{name}'":
                    develop.append((name, True))
                elif second == f"Unexpected +/- setting in VM option '{name}'":
                    develop.append((name, False))
                else:
                    raise SystemExit(f'unclassified develop answer for {name}: {lines!r}')
                continue
            m = re.search(rf'Ignoring option {name}; support was removed in (\S+)$', head)
            if m:
                obsolete.append((name, m.group(1)))
                continue
            m = re.search(rf'Option {name} was deprecated in version \S+ and will likely be removed in a future release\. Use option (\S+) instead\.$', head)
            if m:
                aliases.append((name, m.group(1), head.split(' warning: ', 1)[1]))
                continue
            raise SystemExit(f'unclassified answer for {name}: {lines!r}')
    if len(develop) < 200:
        raise SystemExit(f'only {len(develop)} develop flags found: the scan is not reaching libjvm')
    rows = '\n'.join(f'    ("{n}", {"true" if b else "false"}),' for n, b in sorted(develop))
    obs = '\n'.join(f'    ("{n}", "{v}"),' for n, v in sorted(obsolete))
    ali = '\n'.join(f'    ("{n}", "{t}", "{w}"),' for n, t, w in sorted(aliases))
    text = f'''//! The `-XX:` names HotSpot 25 knows that `-XX:+PrintFlagsFinal` does not
//! list: `develop` flags, obsolete flags and aliases. GENERATED by
//! `tools/gen-hotspot25-develop-flags.py` from
//! {version} -- do not edit by hand; rerun the
//! script against the JDK the launcher targets. Sorted by name.

/// `develop` flags (`true`: `bool`). A product build refuses each with
/// `Error: VM option '<Name>' is develop and is available only in debug
/// version of VM.` and the line of its spelling.
#[rustfmt::skip]
pub(crate) const DEVELOP: &[(&str, bool)] = &[
{rows}
];

/// Obsolete flags and the version that removed them (`Ignoring option <Name>;
/// support was removed in <version>`).
#[rustfmt::skip]
pub(crate) const OBSOLETE: &[(&str, &str)] = &[
{obs}
];

/// Aliases: (alias, flag, the deprecation warning after `<vm> warning: `).
#[rustfmt::skip]
pub(crate) const ALIASES: &[(&str, &str, &str)] = &[
{ali}
];

/// Is `name` a `develop` flag, and is it a `bool`?
pub(crate) fn develop(name: &str) -> Option<bool> {{
    DEVELOP
        .binary_search_by(|(n, _)| n.cmp(&name))
        .ok()
        .map(|i| DEVELOP[i].1)
}}
'''
    with open(out, 'w', newline='\n') as f:
        f.write(text)
    print(f'wrote {out}: {len(develop)} develop, {len(obsolete)} obsolete, {len(aliases)} aliases')


if __name__ == '__main__':
    main()
