    public static void main(String[] args) {
        String k = args.length > 0 ? args[0] : "f";
        int n    = args.length > 1 ? Integer.parseInt(args[1]) : (1 << 26);
        int reps = args.length > 2 ? Integer.parseInt(args[2]) : 5;
        int[] a = new int[n]; int[] b = new int[n]; int[] out = new int[n];
        for (int i = 0; i < n; i++) { a[i] = i; b[i] = 1 + (i % 13); }
        boolean nl = k.equals("nl");
        if (nl) heavyNL(a, out); else heavy(a, b, out);          // warmup (cold PTX)
        long best = Long.MAX_VALUE;
        for (int r = 0; r < reps; r++) {
            long t0 = System.nanoTime();
            if (nl) heavyNL(a, out); else heavy(a, b, out);
            long ms = (System.nanoTime() - t0) / 1_000_000L;
            if (ms < best) best = ms;
        }
        long sample = (long) out[0] + out[n/2] + out[n-1];     // cheap correctness sample
        System.out.println("kernel=" + k + " n=" + n + " warm_ms=" + best + " SAMPLE=" + sample);
    }
