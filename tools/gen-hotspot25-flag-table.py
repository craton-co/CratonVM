"""Generate vm-cli/src/hotspot25_flags.rs from a HotSpot 25 JDK's own flag listing.

The launcher's early `-XX:` scan answers every option HotSpot knows the way
HotSpot's `Arguments::parse_argument` does (type, lock kind, range). The table
is read from the JDK, never typed by hand:

    java -XX:+UnlockDiagnosticVMOptions -XX:+UnlockExperimentalVMOptions -XX:+PrintFlagsFinal -version
    java -XX:+UnlockDiagnosticVMOptions -XX:+UnlockExperimentalVMOptions -XX:+PrintFlagsRanges -version

usage: python -I tools/gen-hotspot25-flag-table.py <java> [<out.rs>]

`PrintFlagsRanges` lists every numeric flag; a flag that declares no range
has empty brackets (`R::None`: its type's own limits). Develop / notproduct flags are absent from a product
build's listing and therefore from the table.
"""
import re
import subprocess
import sys

UNLOCK = ['-XX:+UnlockDiagnosticVMOptions', '-XX:+UnlockExperimentalVMOptions']
TYPES = {
    'bool': 'Bool', 'ccstr': 'Ccstr', 'ccstrlist': 'Ccstr', 'double': 'Double',
    'int': 'Int', 'intx': 'Intx', 'uint': 'Uint', 'uintx': 'Uintx',
    'uint64_t': 'Uint64', 'size_t': 'SizeT',
}


def listing(java, flag):
    r = subprocess.run([java, *UNLOCK, flag, '-version'], capture_output=True, text=True, check=True)
    return r.stdout.splitlines(), r.stderr


def main():
    java = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else 'vm-cli/src/hotspot25_flags.rs'
    final, banner = listing(java, '-XX:+PrintFlagsFinal')
    ranges, _ = listing(java, '-XX:+PrintFlagsRanges')
    version = next((l for l in banner.splitlines() if 'Runtime Environment' in l), '?')
    flags = {}
    for line in final[1:]:
        m = re.match(r'\s*(\S+)\s+(\S+)\s+:?=.*?\{([^}]*)\}\s+\{[^}]*\}\s*$', line)
        if not m:
            raise SystemExit(f'unparsed PrintFlagsFinal line: {line!r}')
        ty, name, kind = m.groups()
        if 'experimental' in kind:
            lock = 'Experimental'
        elif 'diagnostic' in kind:
            lock = 'Diagnostic'
        else:
            lock = 'None'
        flags[name] = [TYPES[ty], lock, None]
    for line in ranges[1:]:
        m = re.match(r'\s*(\S+)\s+(\S+)\s+\[\s*(\S*)\s+\.\.\.\s+(\S*)\s*\]', line)
        if not m:
            raise SystemExit(f'unparsed PrintFlagsRanges line: {line!r}')
        ty, name, lo, hi = m.groups()
        if not lo and not hi:
            # No declared range: the type's own limits only.
            flags[name][2] = 'R::None'
        elif ty == 'double':
            flags[name][2] = f'R::Double({float(lo)!r}, {float(hi)!r})'
        else:
            flags[name][2] = f'R::Int({int(lo)}, {int(hi)})'
    rows = []
    for name in sorted(flags):
        ty, lock, rng = flags[name]
        if ty not in ('Bool', 'Ccstr') and rng is None:
            raise SystemExit(f'numeric flag without a range row: {name}')
        rows.append(f'    F {{ name: "{name}", ty: T::{ty}, lock: L::{lock}, range: {rng or "R::None"} }},')
    text = f'''//! HotSpot 25's `-XX:` flags: name, declared type, lock kind and range, as
//! the JDK itself lists them (`-XX:+PrintFlagsFinal`, `-XX:+PrintFlagsRanges`,
//! both unlocks on). GENERATED by `tools/gen-hotspot25-flag-table.py` from
//! {version} -- do not edit by hand; rerun the
//! script against the JDK the launcher targets. Sorted by name (binary search).
//! A double bound is the listing's three-decimal text.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum T {{
    Bool,
    Ccstr,
    Double,
    Int,
    Intx,
    Uint,
    Uintx,
    Uint64,
    SizeT,
}}

/// Which `-XX:+Unlock...VMOptions` must precede the flag.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum L {{
    None,
    Diagnostic,
    Experimental,
}}

#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) enum R {{
    None,
    Int(i128, i128),
    Double(f64, f64),
}}

#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct F {{
    pub(crate) name: &'static str,
    pub(crate) ty: T,
    pub(crate) lock: L,
    pub(crate) range: R,
}}

/// The flag named `name`, if HotSpot 25 has it.
pub(crate) fn lookup(name: &str) -> Option<&'static F> {{
    FLAGS.binary_search_by(|f| f.name.cmp(name)).ok().map(|i| &FLAGS[i])
}}

#[rustfmt::skip]
pub(crate) const FLAGS: &[F] = &[
{chr(10).join(rows)}
];
'''
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print(f'{len(rows)} flags -> {out}')


if __name__ == '__main__':
    main()
