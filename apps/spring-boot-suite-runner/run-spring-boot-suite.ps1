<#
.SYNOPSIS
  Spring Boot JUnit suite runner for CratonVM and HotSpot.

.DESCRIPTION
  Runs the compiled Spring Boot test classes (core/, module/, cli/,
  configuration-metadata/, loader/, test-support/ Gradle subtrees) one
  process per class through apps\spring-boot\sb-runner\SbRunner.class, a
  JUnit Platform launcher harness (mirrors apps\keycloak\kc-runner\KcRunner).
  Records per-class wall time, persists stdout/stderr logs, can select
  classes by category (passed vs all others), and can run JIT on/off x
  category combinations concurrently.

  Unlike the Maven-based Keycloak runner, Spring Boot's per-module test
  runtime classpath is generated by a Gradle init script
  (apps\spring-boot\cratonvm-test-cp.init.gradle) that writes
  <module>\build\cratonvm-test-cp.txt for every project with a `test`
  source set.
#>
[CmdletBinding()]
param(
  [ValidateSet('passed','others','failed','all')] [string]$Category = 'all',
  [ValidateSet('on','off')]                       [string]$Jit = 'on',
  [ValidateSet('craton','hotspot')]               [string]$Vm = 'craton',

  [int]$Start = 1,
  [int]$Count = 0,
  [int]$Parallel = 4,
  [int]$TimeoutSec = 300,

  [string]$RunName = '',
  [string]$ModeName = '',
  [string]$SpringBootRoot = '',
  [string]$WorkDir = '',
  [string]$RefCsv = '',
  # HotSpot results used to tell a CratonVM defect apart from a fixture or
  # upstream failure the reference VM shares. Defaults to the file a `-Vm
  # hotspot` run already writes: <work>/baseline/hotspot-baseline-latest.tsv.
  [string]$HotspotBaseline = '',
  [string]$ClassList = '',
  [string[]]$Subtrees = @('core','module','cli','configuration-metadata','loader','test-support'),
  [string]$Exe = '',
  [string]$JdkHome = '',
  [string]$MaxHeap = '2g',
  [string[]]$CratonArgs = @(),

  # The corrupt-`Value`-cell census is ARMED by default on craton runs. It
  # costs one extra stderr line per class and turns a heap-integrity guard hit
  # from an event nobody sees into one that names its own door, receiver and
  # Java stack the FIRST time it happens. A cell was observed once in this
  # suite on 2026-08-22 and has not been reproduced since; the whole reason it
  # is unexplained is that nothing was armed when it fired.
  [switch]$NoCorruptCellCensus,

  [switch]$RefreshLists,
  [switch]$RefreshClasspaths,
  [switch]$ListOnly,
  [switch]$AllModes,
  [switch]$Setup
