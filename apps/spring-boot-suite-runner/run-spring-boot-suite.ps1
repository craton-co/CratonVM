  $i = $Start
  foreach ($class in $classes) { "{0}`t{1}`t{2}" -f $i, $class.module, $class.class; $i++ }
  return
}
if ($classes.Count -eq 0) { Die "no classes selected" }

Invoke-Mode -Classes $classes
