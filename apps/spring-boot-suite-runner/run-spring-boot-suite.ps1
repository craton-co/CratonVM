# Setup: compile test classes + generate per-module classpaths (Gradle)
# ---------------------------------------------------------------------------
function Invoke-GradleSetup {
  $jdk = Resolve-Jdk
  $env:JAVA_HOME = $jdk
  $gradlew = Join-Path $script:SpringBootDir 'gradlew.bat'
  if (-not (Test-Path $gradlew)) { Die "gradlew.bat not found: $gradlew" }
  $initScript = Join-Path $script:SpringBootDir 'cratonvm-test-cp.init.gradle'
  if (-not (Test-Path $initScript)) { Die "missing init script: $initScript (dumps per-module test runtime classpaths)" }

  foreach ($subtree in $Subtrees) {
    $dir = Join-Path $script:SpringBootDir $subtree
    if (-not (Test-Path $dir)) { Write-Info "skip missing subtree: $subtree"; continue }
    Write-Info "gradlew -p $subtree testClasses"
    $rc = Invoke-Gradlew -Gradlew $gradlew -GradleArgs @('-p', $dir, 'testClasses', '--no-daemon', '--continue')
    if ($rc -ne 0) { Write-Info "WARNING: testClasses had failures in $subtree (continuing; some modules may be env-gated)" }
    Write-Info "gradlew -p $subtree cratonvmTestCp"
    $rc = Invoke-Gradlew -Gradlew $gradlew -GradleArgs @('-p', $dir, 'cratonvmTestCp', '--init-script', $initScript, '--no-daemon', '--continue')
    if ($rc -ne 0) { Write-Info "WARNING: cratonvmTestCp had failures in $subtree" }
  }
  Build-ClassLists
  Write-Info "Setup complete. classes=$((Get-Content (Join-Path $script:WorkRoot 'all-tests.tsv') | Measure-Object -Line).Lines - 1)"
}

function Build-ClassLists {
  New-Item -ItemType Directory -Force -Path $script:WorkRoot | Out-Null
  $allPath = Join-Path $script:WorkRoot 'all-tests.tsv'
  $passedPath = Join-Path $script:WorkRoot 'passed.tsv'
  $othersPath = Join-Path $script:WorkRoot 'others.tsv'
  $testClassPatterns = @('*Test.class', '*Tests.class', '*IT.class', '*ITCase.class')

  $records = New-Object System.Collections.Generic.List[object]
  foreach ($subtree in $Subtrees) {
    $subtreeDir = Join-Path $script:SpringBootDir $subtree
    if (-not (Test-Path $subtreeDir)) { continue }
    $testDirs = Get-ChildItem -Path $subtreeDir -Recurse -Directory -ErrorAction SilentlyContinue |
      Where-Object { $_.FullName -match '[\\/]build[\\/]classes[\\/](java|kotlin)[\\/]test$' } |
      Sort-Object FullName
    foreach ($dir in $testDirs) {
      # module = project dir (…\<subtree>\<name>), the parent of build\classes\<lang>\test
      $moduleDir = $dir.FullName
      while ($moduleDir -and (Split-Path $moduleDir -Leaf) -ne 'build') { $moduleDir = Split-Path $moduleDir -Parent }
      $moduleDir = Split-Path $moduleDir -Parent
      if (-not $moduleDir) { continue }
      $module = $moduleDir.Substring($script:SpringBootDir.Length + 1) -replace '\\', '/'
      $cpFile = Join-Path $moduleDir 'build\cratonvm-test-cp.txt'
      if (-not (Test-Path $cpFile)) { continue }

      $classes = @(foreach ($pattern in $testClassPatterns) { Get-ChildItem -Path $dir.FullName -Recurse -File -Filter $pattern -ErrorAction SilentlyContinue }) |
        Where-Object { $_.Name -notlike '*$*' -and $_.Name -ne 'AbstractTest.class' } |
        Sort-Object FullName -Unique
      foreach ($classFile in $classes) {
        $rel = $classFile.FullName.Substring($dir.FullName.Length + 1)
        $fqcn = ($rel -replace '\.class$', '') -replace '[\\/]', '.'
        $records.Add([pscustomobject]@{ module = $module; class = $fqcn })
      }
    }
  }

  $unique = $records | Sort-Object module, class -Unique
  "module`tclass" | Set-Content -Path $allPath -Encoding ascii
  foreach ($record in $unique) { "$($record.module)`t$($record.class)" | Add-Content -Path $allPath -Encoding ascii }

  $reference = Resolve-ReferenceFile
  if ($reference) {
    $passedKeys = @{}
    foreach ($row in (Import-ResultRows $reference)) {
      if ((Get-RowStatus $row) -eq 'PASS') { $passedKeys["$($row.module)`t$($row.class)"] = $true }
    }
    "module`tclass" | Set-Content -Path $passedPath -Encoding ascii
    "module`tclass" | Set-Content -Path $othersPath -Encoding ascii
    foreach ($record in $unique) {
      $key = "$($record.module)`t$($record.class)"
      if ($passedKeys.ContainsKey($key)) { "$($record.module)`t$($record.class)" | Add-Content -Path $passedPath -Encoding ascii }
      else { "$($record.module)`t$($record.class)" | Add-Content -Path $othersPath -Encoding ascii }
    }
    Write-Info "class lists refreshed: all=$($unique.Count), passed=$((Import-Csv $passedPath -Delimiter "`t").Count), others=$((Import-Csv $othersPath -Delimiter "`t").Count)"
  } else {
    Write-Info "class list refreshed: all=$($unique.Count); no reference found for passed/others split"
  }
}

function Import-ClassRows([string]$Path) {
  if (-not (Test-Path $Path)) { Die "class list not found: $Path" }
  return @(Import-ResultRows $Path)
}

function Get-SelectedClasses {
  $allPath = Join-Path $script:WorkRoot 'all-tests.tsv'
  $passedPath = Join-Path $script:WorkRoot 'passed.tsv'
  $othersPath = Join-Path $script:WorkRoot 'others.tsv'

  if ($ClassList) { return Select-ClassRange (Import-ClassRows $ClassList) }
  if ($RefreshLists -or -not (Test-Path $allPath)) { Build-ClassLists }

  $resolvedCategory = $Category
  if ($resolvedCategory -eq 'failed') { $resolvedCategory = 'others' }
  $source = $allPath
  if ($resolvedCategory -eq 'passed') { $source = $passedPath }
  if ($resolvedCategory -eq 'others') { $source = $othersPath }
  if (-not (Test-Path $source)) {
    if (-not (Resolve-ReferenceFile)) { Die "category '$Category' needs a reference result file. Pass -RefCsv, or run -Category all first." }
    Build-ClassLists
  }
  if (-not (Test-Path $source)) { Die "class list not found: $source" }
  return Select-ClassRange (Import-Csv -Path $source -Delimiter "`t")
}

