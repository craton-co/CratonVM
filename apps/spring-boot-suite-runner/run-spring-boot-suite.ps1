<#
.SYNOPSIS
  Spring Boot JUnit suite runner for CratonVM and HotSpot.

.DESCRIPTION
  Runs the compiled Spring Boot test classes (core/, module/, cli/,
  configuration-metadata/, loader/, test-support/ Gradle subtrees) one
  process per class through apps\spring-boot\sb-runner\SbRunner.class, a
  JUnit Platform launcher harness (mirrors apps\keycloak\kc-runner\KcRunner).
  Records per-class wall time, persists stdout/stderr logs, can select
  classes by category (passed vs all others), and can run JIT on/off x
  category combinations concurrently.

  Unlike the Maven-based Keycloak runner, Spring Boot's per-module test
  runtime classpath is generated by a Gradle init script
  (apps\spring-boot\cratonvm-test-cp.init.gradle) that writes
  <module>\build\cratonvm-test-cp.txt for every project with a `test`
  source set.
#>
[CmdletBinding()]
param(
  [ValidateSet('passed','others','failed','all')] [string]$Category = 'all',
  [ValidateSet('on','off')]                       [string]$Jit = 'on',
  [ValidateSet('craton','hotspot')]               [string]$Vm = 'craton',

  [int]$Start = 1,
  [int]$Count = 0,
  [int]$Parallel = 4,
  [int]$TimeoutSec = 300,

  [string]$RunName = '',
  [string]$ModeName = '',
  [string]$SpringBootRoot = '',
  [string]$WorkDir = '',
  [string]$RefCsv = '',
  [string]$ClassList = '',
  [string[]]$Subtrees = @('core','module','cli','configuration-metadata','loader','test-support'),
  [string]$Exe = '',
  [string]$JdkHome = '',
  [string]$MaxHeap = '2g',
  [string[]]$CratonArgs = @(),

  [switch]$RefreshLists,
  [switch]$RefreshClasspaths,
  [switch]$ListOnly,
  [switch]$AllModes,
  [switch]$Setup
)

$ErrorActionPreference = 'Stop'

function Write-Info([string]$Message) {
  Write-Host "[spring-boot-suite] $Message"
}

function Die([string]$Message) {
  Write-Error "[spring-boot-suite] $Message"
  exit 1
}

function Get-RepoRoot {
  try {
    $root = & git -C $PSScriptRoot rev-parse --show-toplevel 2>$null
    if ($LASTEXITCODE -eq 0 -and $root) { return $root.Trim() }
  } catch {}
  return (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent)
}

function Get-PowerShellExe {
  if ($PSHOME) {
    $candidate = Join-Path $PSHOME 'pwsh.exe'
    if (Test-Path $candidate) { return $candidate }
    $candidate = Join-Path $PSHOME 'powershell.exe'
    if (Test-Path $candidate) { return $candidate }
  }
  return 'powershell.exe'
}

function ConvertTo-SafeName([string]$Value) {
  return ($Value -replace '[^A-Za-z0-9_.-]', '_')
}

function ConvertTo-SafeFileStem([string]$Value, [int]$MaxLength = 96) {
  $safe = ConvertTo-SafeName $Value
  if ($MaxLength -lt 16) { $MaxLength = 16 }
  if ($safe.Length -le $MaxLength) { return $safe }
  $sha = [System.Security.Cryptography.SHA256]::Create()
  try {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($safe)
    $hash = ([System.BitConverter]::ToString($sha.ComputeHash($bytes)) -replace '-', '').Substring(0, 12).ToLowerInvariant()
  } finally {
    $sha.Dispose()
  }
  $prefixLength = $MaxLength - $hash.Length - 1
  return "$($safe.Substring(0, $prefixLength))-$hash"
}

function Get-Sha256Hex([string]$Value) {
  $sha = [System.Security.Cryptography.SHA256]::Create()
  try {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($Value)
    return (([System.BitConverter]::ToString($sha.ComputeHash($bytes))) -replace '-', '').ToLowerInvariant()
  } finally {
    $sha.Dispose()
  }
}

function ConvertTo-InvariantString([double]$Value) {
  return $Value.ToString('F3', [System.Globalization.CultureInfo]::InvariantCulture)
}

function ConvertFrom-InvariantString([string]$Value) {
  $parsed = 0.0
  if ([double]::TryParse($Value, [System.Globalization.NumberStyles]::Float, [System.Globalization.CultureInfo]::InvariantCulture, [ref]$parsed)) {
    return $parsed
  }
  return 0.0
}

function Quote-WindowsArgument([string]$Argument) {
  if ($null -eq $Argument) { return '""' }
  if ($Argument.Length -eq 0) { return '""' }
  if ($Argument -notmatch '[\s"]') { return $Argument }
  $result = New-Object System.Text.StringBuilder
  [void]$result.Append('"')
  $backslashes = 0
  foreach ($ch in $Argument.ToCharArray()) {
    if ($ch -eq '\') {
      $backslashes++
    } elseif ($ch -eq '"') {
      if ($backslashes -gt 0) { [void]$result.Append('\' * ($backslashes * 2)) }
      $backslashes = 0
      [void]$result.Append('\"')
    } else {
      if ($backslashes -gt 0) { [void]$result.Append('\' * $backslashes) }
      $backslashes = 0
      [void]$result.Append($ch)
    }
  }
  if ($backslashes -gt 0) { [void]$result.Append('\' * ($backslashes * 2)) }
  [void]$result.Append('"')
  return $result.ToString()
}

function Set-ProcessArguments([System.Diagnostics.ProcessStartInfo]$StartInfo, [string[]]$Arguments) {
  # ProcessStartInfo.ArgumentList is unavailable/null under Windows PowerShell
  # 5.1 (.NET Framework) in some environments — fall back to the classic
  # pre-quoted Arguments string when it's not usable.
  $argListProp = $StartInfo.GetType().GetProperty('ArgumentList')
  if ($argListProp -and $StartInfo.ArgumentList) {
    foreach ($arg in $Arguments) { [void]$StartInfo.ArgumentList.Add($arg) }
  } else {
    $StartInfo.Arguments = (($Arguments | ForEach-Object { Quote-WindowsArgument $_ }) -join ' ')
  }
}

function Start-RedirectedProcess {
  param([string]$FilePath, [string[]]$Arguments, [string]$WorkingDirectory, [string]$StdoutPath, [string]$StderrPath)
  $psi = [System.Diagnostics.ProcessStartInfo]::new()
  $psi.FileName = $FilePath
  $psi.WorkingDirectory = $WorkingDirectory
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  Set-ProcessArguments -StartInfo $psi -Arguments $Arguments
  $proc = [System.Diagnostics.Process]::new()
  $proc.StartInfo = $psi
  [void]$proc.Start()
  return [pscustomobject]@{
    proc = $proc
    stdoutTask = $proc.StandardOutput.ReadToEndAsync()
    stderrTask = $proc.StandardError.ReadToEndAsync()
    stdoutPath = $StdoutPath
    stderrPath = $StderrPath
  }
}

function Complete-RedirectedProcess([object]$Record) {
  $Record.proc.WaitForExit()
  try { $Record.stdoutTask.Wait(5000) | Out-Null } catch {}
  try { $Record.stderrTask.Wait(5000) | Out-Null } catch {}
  $stdout = ''; $stderr = ''
  try { $stdout = $Record.stdoutTask.Result } catch {}
  try { $stderr = $Record.stderrTask.Result } catch {}
  if ($Record.stdoutPath) { [System.IO.File]::WriteAllText($Record.stdoutPath, $stdout, [System.Text.Encoding]::UTF8) }
  if ($Record.stderrPath) { [System.IO.File]::WriteAllText($Record.stderrPath, $stderr, [System.Text.Encoding]::UTF8) }
  $exitCode = $Record.proc.ExitCode
  try { $Record.proc.Dispose() } catch {}
  return $exitCode
}

function Split-ClasspathEntries([string]$Classpath) {
  if (-not $Classpath) { return @() }
  $separator = [string][System.IO.Path]::PathSeparator
  return @($Classpath -split [regex]::Escape($separator) | Where-Object { $_ })
}

function Add-UniqueClasspathEntry {
  param([System.Collections.Generic.List[string]]$Entries, [hashtable]$Seen, [string]$Entry)
  if (-not $Entry) { return }
  try {
    $full = [System.IO.Path]::GetFullPath($Entry)
    $key = $full.ToLowerInvariant()
    $value = $full
  } catch {
    $key = $Entry.ToLowerInvariant()
    $value = $Entry
  }
  if (-not $Seen.ContainsKey($key)) {
    $Entries.Add($value)
    $Seen[$key] = $true
  }
}

function Get-GradleCacheRoot {
  if ($script:GradleCacheRootCache) { return $script:GradleCacheRootCache }
  $candidates = @()
  if ($env:GRADLE_USER_HOME) { $candidates += (Join-Path $env:GRADLE_USER_HOME 'caches\modules-2\files-2.1') }
  if ($env:USERPROFILE) { $candidates += (Join-Path $env:USERPROFILE '.gradle\caches\modules-2\files-2.1') }
  foreach ($c in $candidates) { if (Test-Path $c) { $script:GradleCacheRootCache = $c; return $c } }
  $script:GradleCacheRootCache = ''
  return ''
}

function Find-GradleCacheJar([string]$Group, [string]$Artifact) {
  $root = Get-GradleCacheRoot
  if (-not $root) { return $null }
  $artifactDir = Join-Path $root "$Group\$Artifact"
  if (-not (Test-Path $artifactDir)) { return $null }
  return Get-ChildItem -Path $artifactDir -Recurse -File -Filter "$Artifact-*.jar" -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -notmatch '(-sources|-javadoc)\.jar$' } |
    Sort-Object FullName -Descending | Select-Object -First 1
}

function Add-JUnitPlatformInfraEntries {
  # SbRunner drives every class through the JUnit Platform Launcher's default
  # ServiceLoader engine auto-registration, so both jupiter (JUnit5) and
  # vintage (JUnit4, if a class needs it) run uniformly. A module's own
  # Gradle testRuntimeClasspath does NOT necessarily include the launcher
  # jar (Gradle's `test` task manages that on its own internal classpath,
  # not the project's), so make it universally available here — same
  # rationale as the Keycloak runner's Add-JUnitPlatformInfraEntries.
  param([System.Collections.Generic.List[string]]$Entries, [hashtable]$Seen)
  $artifacts = @(
    @('org.junit.platform', 'junit-platform-commons'),
    @('org.junit.platform', 'junit-platform-engine'),
    @('org.junit.platform', 'junit-platform-launcher'),
    @('org.junit.jupiter', 'junit-jupiter-api'),
    @('org.junit.jupiter', 'junit-jupiter-engine'),
    @('org.junit.vintage', 'junit-vintage-engine'),
    @('org.opentest4j', 'opentest4j'),
    @('org.apiguardian', 'apiguardian-api'),
    @('junit', 'junit')
  )
  foreach ($pair in $artifacts) {
    $jar = Find-GradleCacheJar -Group $pair[0] -Artifact $pair[1]
    if ($jar) { Add-UniqueClasspathEntry -Entries $Entries -Seen $Seen -Entry $jar.FullName }
  }
}

function ConvertTo-ManifestClasspathUrl([string]$Entry) {
  $full = [System.IO.Path]::GetFullPath($Entry)
  if ((Test-Path $full -PathType Container) -and -not ($full.EndsWith('\') -or $full.EndsWith('/'))) {
    $full += [System.IO.Path]::DirectorySeparatorChar
  }
  return ([System.Uri]::new($full, [System.UriKind]::Absolute)).AbsoluteUri
}

function Split-ManifestLine([string]$Line) {
  $max = 70
  $out = New-Object System.Collections.Generic.List[string]
  if ($Line.Length -le $max) { $out.Add($Line); return @($out) }
  $out.Add($Line.Substring(0, $max))
  $offset = $max
  while ($offset -lt $Line.Length) {
    $take = [Math]::Min($max - 1, $Line.Length - $offset)
    $out.Add(' ' + $Line.Substring($offset, $take))
    $offset += $take
  }
  return @($out)
}

function New-PathingJar {
  param([string]$Module, [string[]]$Entries)
  # -AllModes launches JIT and no-JIT child runners concurrently.  They have
  # the same module classpath signature but must not race over one
  # classpath.jar (one child can observe the other deleting/recreating it).
  # Mode-local wrappers retain caching within a lane while making the two
  # child processes independent.
  $modePath = ConvertTo-SafeName $(if ($script:EffectiveModeName) { $script:EffectiveModeName } else { 'default' })
  $pathingDir = Join-Path (Join-Path $script:WorkRoot 'pathing-jars') $modePath
  New-Item -ItemType Directory -Force -Path $pathingDir | Out-Null
  $signature = 'pathing-jar-manifest-url-v1' + "`n" + (($Entries | ForEach-Object { [System.IO.Path]::GetFullPath($_) }) -join "`n")
  $hash = (Get-Sha256Hex $signature).Substring(0, 16)
  $stem = ConvertTo-SafeFileStem $(if ($Module) { $Module } else { 'universal' })
  # Spring Boot's ModifiedClassPathClassLoader expands the manifest class
  # path only for IntelliJ-style `classpath.jar` files.  The runner needs
  # that expansion for @ClassPathExclusions/@ClassPathOverrides: otherwise
  # it sees this one wrapper JAR instead of the individual dependency JARs.
  # Keep module/content isolation in directories so the wrapper name itself
  # can retain the recognized IntelliJ convention.
  $jarDir = Join-Path (Join-Path $pathingDir $stem) $hash
  $jarPath = Join-Path $jarDir 'classpath.jar'
  if (Test-Path $jarPath) { return [System.IO.Path]::GetFullPath($jarPath) }
  New-Item -ItemType Directory -Force -Path $jarDir | Out-Null

  Add-Type -AssemblyName System.IO.Compression | Out-Null
  Add-Type -AssemblyName System.IO.Compression.FileSystem | Out-Null
  $urls = @($Entries | ForEach-Object { ConvertTo-ManifestClasspathUrl $_ })
  $lines = New-Object System.Collections.Generic.List[string]
  $lines.Add('Manifest-Version: 1.0')
  $lines.Add('Created-By: IntelliJ IDEA')
  $lines.Add('Main-Class: SbRunner')
  foreach ($line in (Split-ManifestLine ('Class-Path: ' + ($urls -join ' ')))) { $lines.Add($line) }
  $lines.Add('')

  if (Test-Path $jarPath) { Remove-Item -LiteralPath $jarPath -Force }
  $zip = [System.IO.Compression.ZipFile]::Open($jarPath, [System.IO.Compression.ZipArchiveMode]::Create)
  try {
    $entry = $zip.CreateEntry('META-INF/MANIFEST.MF')
    $stream = $entry.Open()
    try {
      $writer = [System.IO.StreamWriter]::new($stream, [System.Text.Encoding]::ASCII)
      try { $writer.NewLine = "`r`n"; foreach ($line in $lines) { $writer.WriteLine($line) } } finally { $writer.Dispose() }
    } finally { $stream.Dispose() }
  } finally { $zip.Dispose() }
  return [System.IO.Path]::GetFullPath($jarPath)
}

function Import-ResultRows([string]$Path) {
  if (-not (Test-Path $Path)) { return @() }
  $first = Get-Content -Path $Path -TotalCount 1
  $delimiter = ','
  if ($first -like "*`t*") { $delimiter = "`t" }
  return @(Import-Csv -Path $Path -Delimiter $delimiter)
}

function Select-ClassRange([object[]]$List) {
  $list = @($List)
  $from = [Math]::Max(1, $Start) - 1
  if ($from -ge $list.Count) { return @() }
  $end = $list.Count
  if ($Count -gt 0) { $end = [Math]::Min($list.Count, $from + $Count) }
  return @($list[$from..($end - 1)])
}

function Resolve-ReferenceFile {
  if ($RefCsv -and (Test-Path $RefCsv)) { return $RefCsv }
  $candidates = @((Join-Path $script:WorkRoot 'reference.tsv'), (Join-Path $script:WorkRoot 'reference.csv'))
  foreach ($candidate in $candidates) { if (Test-Path $candidate) { return $candidate } }
  return ''
}

function Get-RowStatus($Row) {
  if ($Row.PSObject.Properties.Name -contains 'status') { return ([string]$Row.status).ToUpperInvariant() }
  return ''
}

# ---------------------------------------------------------------------------
# gradlew invocation helper
# ---------------------------------------------------------------------------
function Invoke-Gradlew {
  param([string]$Gradlew, [string[]]$GradleArgs)
  # Windows PowerShell 5.1 wraps ANY stderr line from a native process as a
  # terminating NativeCommandError while $ErrorActionPreference = 'Stop' is in
  # effect, even on exit code 0 (Gradle routinely logs benign warnings to
  # stderr). Temporarily relax to 'Continue' and check $LASTEXITCODE instead
  # (same pattern as the tomcat-suite-runner's Invoke-Setup).
  # NOTE: parameter deliberately NOT named $Args -- that collides with
  # PowerShell's automatic $args variable and silently corrupts the splat
  # (gradlew received zero args, defaulted to the `help` task against the
  # wrong project dir, every "Setup" run up to 2026-07-17 was silently
  # discovering 0 classes / regenerating no classpaths despite exit 0).
  $prevEAP = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  # gradlew.bat relies on the CALLER's current directory being the Gradle
  # project root (it does not `cd` into its own location) -- invoking it via
  # `& $Gradlew` from an arbitrary caller cwd (e.g. the CratonVM repo root)
  # fails with "Directory '<cwd>' does not contain a Gradle build" even
  # though $Gradlew's own path is fully qualified. Push into its directory
  # for the duration of the call.
  Push-Location (Split-Path $Gradlew -Parent)
  try {
    & $Gradlew @GradleArgs 2>&1 | ForEach-Object { Write-Host $_ }
    return $LASTEXITCODE
  } finally {
    Pop-Location
    $ErrorActionPreference = $prevEAP
  }
}

# ---------------------------------------------------------------------------
# Setup: compile test classes + generate per-module classpaths (Gradle)
# ---------------------------------------------------------------------------
function Invoke-GradleSetup {
  $jdk = Resolve-Jdk
  $env:JAVA_HOME = $jdk
  $gradlew = Join-Path $script:SpringBootDir 'gradlew.bat'
  if (-not (Test-Path $gradlew)) { Die "gradlew.bat not found: $gradlew" }
  $initScript = Join-Path $script:SpringBootDir 'cratonvm-test-cp.init.gradle'
  if (-not (Test-Path $initScript)) { Die "missing init script: $initScript (dumps per-module test runtime classpaths)" }

  foreach ($subtree in $Subtrees) {
    $dir = Join-Path $script:SpringBootDir $subtree
    if (-not (Test-Path $dir)) { Write-Info "skip missing subtree: $subtree"; continue }
    Write-Info "gradlew -p $subtree testClasses"
    $rc = Invoke-Gradlew -Gradlew $gradlew -GradleArgs @('-p', $dir, 'testClasses', '--no-daemon', '--continue')
    if ($rc -ne 0) { Write-Info "WARNING: testClasses had failures in $subtree (continuing; some modules may be env-gated)" }
    Write-Info "gradlew -p $subtree cratonvmTestCp"
    $rc = Invoke-Gradlew -Gradlew $gradlew -GradleArgs @('-p', $dir, 'cratonvmTestCp', '--init-script', $initScript, '--no-daemon', '--continue')
    if ($rc -ne 0) { Write-Info "WARNING: cratonvmTestCp had failures in $subtree" }
  }
  Build-ClassLists
  Write-Info "Setup complete. classes=$((Get-Content (Join-Path $script:WorkRoot 'all-tests.tsv') | Measure-Object -Line).Lines - 1)"
}

function Build-ClassLists {
  New-Item -ItemType Directory -Force -Path $script:WorkRoot | Out-Null
  $allPath = Join-Path $script:WorkRoot 'all-tests.tsv'
  $passedPath = Join-Path $script:WorkRoot 'passed.tsv'
  $othersPath = Join-Path $script:WorkRoot 'others.tsv'
  $testClassPatterns = @('*Test.class', '*Tests.class', '*IT.class', '*ITCase.class')

  $records = New-Object System.Collections.Generic.List[object]
  foreach ($subtree in $Subtrees) {
    $subtreeDir = Join-Path $script:SpringBootDir $subtree
    if (-not (Test-Path $subtreeDir)) { continue }
    $testDirs = Get-ChildItem -Path $subtreeDir -Recurse -Directory -ErrorAction SilentlyContinue |
      Where-Object { $_.FullName -match '[\\/]build[\\/]classes[\\/](java|kotlin)[\\/]test$' } |
      Sort-Object FullName
    foreach ($dir in $testDirs) {
      # module = project dir (…\<subtree>\<name>), the parent of build\classes\<lang>\test
      $moduleDir = $dir.FullName
      while ($moduleDir -and (Split-Path $moduleDir -Leaf) -ne 'build') { $moduleDir = Split-Path $moduleDir -Parent }
      $moduleDir = Split-Path $moduleDir -Parent
      if (-not $moduleDir) { continue }
      $module = $moduleDir.Substring($script:SpringBootDir.Length + 1) -replace '\\', '/'
      $cpFile = Join-Path $moduleDir 'build\cratonvm-test-cp.txt'
      if (-not (Test-Path $cpFile)) { continue }

      $classes = @(foreach ($pattern in $testClassPatterns) { Get-ChildItem -Path $dir.FullName -Recurse -File -Filter $pattern -ErrorAction SilentlyContinue }) |
        Where-Object { $_.Name -notlike '*$*' -and $_.Name -ne 'AbstractTest.class' } |
        Sort-Object FullName -Unique
      foreach ($classFile in $classes) {
        $rel = $classFile.FullName.Substring($dir.FullName.Length + 1)
        $fqcn = ($rel -replace '\.class$', '') -replace '[\\/]', '.'
        $records.Add([pscustomobject]@{ module = $module; class = $fqcn })
      }
    }
  }

  $unique = $records | Sort-Object module, class -Unique
  "module`tclass" | Set-Content -Path $allPath -Encoding ascii
  foreach ($record in $unique) { "$($record.module)`t$($record.class)" | Add-Content -Path $allPath -Encoding ascii }

  $reference = Resolve-ReferenceFile
  if ($reference) {
    $passedKeys = @{}
    foreach ($row in (Import-ResultRows $reference)) {
      if ((Get-RowStatus $row) -eq 'PASS') { $passedKeys["$($row.module)`t$($row.class)"] = $true }
    }
    "module`tclass" | Set-Content -Path $passedPath -Encoding ascii
    "module`tclass" | Set-Content -Path $othersPath -Encoding ascii
    foreach ($record in $unique) {
      $key = "$($record.module)`t$($record.class)"
      if ($passedKeys.ContainsKey($key)) { "$($record.module)`t$($record.class)" | Add-Content -Path $passedPath -Encoding ascii }
      else { "$($record.module)`t$($record.class)" | Add-Content -Path $othersPath -Encoding ascii }
    }
    Write-Info "class lists refreshed: all=$($unique.Count), passed=$((Import-Csv $passedPath -Delimiter "`t").Count), others=$((Import-Csv $othersPath -Delimiter "`t").Count)"
  } else {
    Write-Info "class list refreshed: all=$($unique.Count); no reference found for passed/others split"
  }
}

function Import-ClassRows([string]$Path) {
  if (-not (Test-Path $Path)) { Die "class list not found: $Path" }
  return @(Import-ResultRows $Path)
}

function Get-SelectedClasses {
  $allPath = Join-Path $script:WorkRoot 'all-tests.tsv'
  $passedPath = Join-Path $script:WorkRoot 'passed.tsv'
  $othersPath = Join-Path $script:WorkRoot 'others.tsv'

  if ($ClassList) { return Select-ClassRange (Import-ClassRows $ClassList) }
  if ($RefreshLists -or -not (Test-Path $allPath)) { Build-ClassLists }

  $resolvedCategory = $Category
  if ($resolvedCategory -eq 'failed') { $resolvedCategory = 'others' }
  $source = $allPath
  if ($resolvedCategory -eq 'passed') { $source = $passedPath }
  if ($resolvedCategory -eq 'others') { $source = $othersPath }
  if (-not (Test-Path $source)) {
    if (-not (Resolve-ReferenceFile)) { Die "category '$Category' needs a reference result file. Pass -RefCsv, or run -Category all first." }
    Build-ClassLists
  }
  if (-not (Test-Path $source)) { Die "class list not found: $source" }
  return Select-ClassRange (Import-Csv -Path $source -Delimiter "`t")
}

# ---------------------------------------------------------------------------
# Classpath resolution (per module, cached)
# ---------------------------------------------------------------------------
function Get-ModuleClasspathEntries {
  param([string]$Module)
  if (-not $script:ModuleClasspathCache) { $script:ModuleClasspathCache = @{} }
  if ($script:ModuleClasspathCache.ContainsKey($Module)) { return @($script:ModuleClasspathCache[$Module]) }

  $modulePath = $Module -replace '/', '\'
  $moduleRoot = Join-Path $script:SpringBootDir $modulePath
  $cpFile = Join-Path $moduleRoot 'build\cratonvm-test-cp.txt'
  if ($RefreshClasspaths -or -not (Test-Path $cpFile)) {
    $jdk = Resolve-Jdk
    $env:JAVA_HOME = $jdk
    $gradlew = Join-Path $script:SpringBootDir 'gradlew.bat'
    $initScript = Join-Path $script:SpringBootDir 'cratonvm-test-cp.init.gradle'
    $projPath = ':' + ($Module -replace '/', ':')
    Write-Info "refreshing classpath for $Module"
    Invoke-Gradlew -Gradlew $gradlew -GradleArgs @("${projPath}:cratonvmTestCp", '--init-script', $initScript, '--no-daemon', '--continue') | Out-Null
  }
  if (-not (Test-Path $cpFile)) { Die "missing classpath file: $cpFile (run -Setup or -RefreshClasspaths first)" }

  $entries = New-Object System.Collections.Generic.List[string]
  $seen = @{}
  Add-UniqueClasspathEntry -Entries $entries -Seen $seen -Entry $script:SbRunnerDir
  foreach ($entry in (Split-ClasspathEntries ((Get-Content -Path $cpFile -Raw).Trim()))) {
    Add-UniqueClasspathEntry -Entries $entries -Seen $seen -Entry $entry
  }
  Add-JUnitPlatformInfraEntries -Entries $entries -Seen $seen

  $result = @($entries)
  $script:ModuleClasspathCache[$Module] = $result
  return $result
}

function Get-LaunchSpec {
  param([object]$ClassRow)
  $module = [string]$ClassRow.module
  $entries = @(Get-ModuleClasspathEntries -Module $module)
  $separator = [string][System.IO.Path]::PathSeparator
  $cp = ($entries -join $separator)
  $usePathingJar = ([System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT) -and ($cp.Length -gt 24000)
  if ($usePathingJar) {
    $jar = New-PathingJar -Module $module -Entries $entries
    return [pscustomobject]@{ kind = 'jar'; value = $jar; entries = $entries.Count; length = $cp.Length }
  }
  return [pscustomobject]@{ kind = 'cp'; value = $cp; entries = $entries.Count; length = $cp.Length }
}

function Resolve-CratonExe {
  if ($Exe) { if (-not (Test-Path $Exe)) { Die "CratonVM executable not found: $Exe" }; return [System.IO.Path]::GetFullPath($Exe) }
  if ($env:CV_BIN -and (Test-Path $env:CV_BIN)) { return [System.IO.Path]::GetFullPath($env:CV_BIN) }
  if ($env:CRATONVM_SPRING_BOOT_EXE -and (Test-Path $env:CRATONVM_SPRING_BOOT_EXE)) { return [System.IO.Path]::GetFullPath($env:CRATONVM_SPRING_BOOT_EXE) }

  $unique = Join-Path $script:RepoRoot 'target\release\cratonvm-spring-boot-suite.exe'
  if (Test-Path $unique) { return [System.IO.Path]::GetFullPath($unique) }
  $generic = Join-Path $script:RepoRoot 'target\release\cratonvm.exe'
  if (Test-Path $generic) {
    New-Item -ItemType Directory -Force -Path (Split-Path $unique) | Out-Null
    Copy-Item -Path $generic -Destination $unique -Force
    Write-Info "copied generic cratonvm.exe to unique runner binary: $unique"
    return [System.IO.Path]::GetFullPath($unique)
  }
  Die "CratonVM executable not found. Pass -Exe or set CV_BIN/CRATONVM_SPRING_BOOT_EXE."
}

function Resolve-Jdk {
  if ($JdkHome) { return $JdkHome }
  if ($env:JAVA_HOME) { return $env:JAVA_HOME }
  return 'C:\Program Files\Java\jdk-25'
}

