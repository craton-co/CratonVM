# Classpath resolution (per module, cached)
# ---------------------------------------------------------------------------
function Get-ModuleClasspathEntries {
  param([string]$Module)
  if (-not $script:ModuleClasspathCache) { $script:ModuleClasspathCache = @{} }
  if ($script:ModuleClasspathCache.ContainsKey($Module)) { return @($script:ModuleClasspathCache[$Module]) }

  $modulePath = $Module -replace '/', '\'
  $moduleRoot = Join-Path $script:SpringBootDir $modulePath
  $cpFile = Join-Path $moduleRoot 'build\cratonvm-test-cp.txt'
  if ($RefreshClasspaths -or -not (Test-Path $cpFile)) {
    $jdk = Resolve-Jdk
    $env:JAVA_HOME = $jdk
    $gradlew = Join-Path $script:SpringBootDir 'gradlew.bat'
    $initScript = Join-Path $script:SpringBootDir 'cratonvm-test-cp.init.gradle'
    $projPath = ':' + ($Module -replace '/', ':')
    Write-Info "refreshing classpath for $Module"
    Invoke-Gradlew -Gradlew $gradlew -GradleArgs @("${projPath}:cratonvmTestCp", '--init-script', $initScript, '--no-daemon', '--continue') | Out-Null
  }
  if (-not (Test-Path $cpFile)) { Die "missing classpath file: $cpFile (run -Setup or -RefreshClasspaths first)" }

  $entries = New-Object System.Collections.Generic.List[string]
  $seen = @{}
  Add-UniqueClasspathEntry -Entries $entries -Seen $seen -Entry $script:SbRunnerDir
  foreach ($entry in (Split-ClasspathEntries ((Get-Content -Path $cpFile -Raw).Trim()))) {
    Add-UniqueClasspathEntry -Entries $entries -Seen $seen -Entry $entry
  }
  Add-JUnitPlatformInfraEntries -Entries $entries -Seen $seen

  $result = @($entries)
  $script:ModuleClasspathCache[$Module] = $result
  return $result
}

function Get-LaunchSpec {
  param([object]$ClassRow)
  $module = [string]$ClassRow.module
  $entries = @(Get-ModuleClasspathEntries -Module $module)
  $separator = [string][System.IO.Path]::PathSeparator
  $cp = ($entries -join $separator)
  $usePathingJar = ([System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT) -and ($cp.Length -gt 24000)
  if ($usePathingJar) {
    $jar = New-PathingJar -Module $module -Entries $entries
    return [pscustomobject]@{ kind = 'jar'; value = $jar; entries = $entries.Count; length = $cp.Length }
  }
  return [pscustomobject]@{ kind = 'cp'; value = $cp; entries = $entries.Count; length = $cp.Length }
}

function Resolve-CratonExe {
  if ($Exe) { if (-not (Test-Path $Exe)) { Die "CratonVM executable not found: $Exe" }; return [System.IO.Path]::GetFullPath($Exe) }
  if ($env:CV_BIN -and (Test-Path $env:CV_BIN)) { return [System.IO.Path]::GetFullPath($env:CV_BIN) }
  if ($env:CRATONVM_SPRING_BOOT_EXE -and (Test-Path $env:CRATONVM_SPRING_BOOT_EXE)) { return [System.IO.Path]::GetFullPath($env:CRATONVM_SPRING_BOOT_EXE) }

  $unique = Join-Path $script:RepoRoot 'target\release\cratonvm-spring-boot-suite.exe'
  if (Test-Path $unique) { return [System.IO.Path]::GetFullPath($unique) }
  $generic = Join-Path $script:RepoRoot 'target\release\cratonvm.exe'
  if (Test-Path $generic) {
    New-Item -ItemType Directory -Force -Path (Split-Path $unique) | Out-Null
    Copy-Item -Path $generic -Destination $unique -Force
    Write-Info "copied generic cratonvm.exe to unique runner binary: $unique"
    return [System.IO.Path]::GetFullPath($unique)
  }
  Die "CratonVM executable not found. Pass -Exe or set CV_BIN/CRATONVM_SPRING_BOOT_EXE."
}

