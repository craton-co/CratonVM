}

function New-ProcessRecord {
  param([object]$ClassRow, [string]$ModeOut, [object]$LaunchSpec, [string]$ExePath, [string]$JavaExe, [string]$JdkPath, [bool]$NoJit, [int]$Timeout, [int]$Retries = 0)
  $module = [string]$ClassRow.module
  $class = [string]$ClassRow.class
  $workingDirectory = $script:SpringBootDir
  $modulePath = $module -replace '/', [System.IO.Path]::DirectorySeparatorChar
  $moduleRoot = Join-Path $script:SpringBootDir $modulePath
  if (Test-Path $moduleRoot) { $workingDirectory = $moduleRoot }
  $logDir = Join-Path $ModeOut 'logs'
  New-Item -ItemType Directory -Force -Path $logDir | Out-Null
  # `WriteAllText` still observes the legacy MAX_PATH limit on some Windows
  # PowerShell/.NET Framework combinations.  Worktree and run names are both
  # intentionally unique and can be long, so size the per-class stem from the
  # actual log-directory prefix rather than assuming the historical 96-char
  # cap always leaves room for the extension.
  $maxStemLength = [Math]::Max(16, 240 - $logDir.Length - '.out.log'.Length - 1)
  $safe = ConvertTo-SafeFileStem "$module.$class" -MaxLength $maxStemLength
  $outFile = Join-Path $logDir "$safe.out.log"
  $errFile = Join-Path $logDir "$safe.err.log"

  if ($Vm -eq 'hotspot') {
    $file = $JavaExe
    # Several modules' own build.gradle add --add-opens=java.base/java.net=ALL-UNNAMED
    # to their Gradle `test` task JVM args (jetty/security/servlet/tomcat/webflux/
    # websocket -- reflective field reset in their web-server test fixtures). This
    # runner launches SbRunner directly instead of through Gradle's test task, so
    # none of those per-module jvmArgs apply; without it those classes fail with
    # "IllegalStateException: Unable to reset field" on real HotSpot too, which is
    # a harness gap, not a genuine VM behavior difference. Apply it universally --
    # opens are additive and harmless for modules that don't need it.
    $args = @("-Xmx$MaxHeap", '-Dfile.encoding=UTF-8', '-Djava.awt.headless=true', '--add-opens=java.base/java.net=ALL-UNNAMED')
    if ($NoJit) { $args += '-Xint' }
    if ($LaunchSpec.kind -eq 'jar') { $args += @('-jar', $LaunchSpec.value, $class) }
    else { $args += @('-cp', $LaunchSpec.value, 'SbRunner', $class) }
  } else {
    $file = $ExePath
    $args = @('--java-home', $JdkPath, '--Xmx', $MaxHeap)
    # The suite normally disables the VM watchdog because it owns the
    # per-class timeout.  Preserve that default, but let a caller provide a
    # real watchdog value through -CratonArgs for a diagnostic run.
    $hasWatchdogArg = @($CratonArgs | Where-Object { $_ -match '^--stack-dump-on-timeout(?:=|$)' }).Count -gt 0
    if (-not $hasWatchdogArg) { $args += @('--stack-dump-on-timeout', '0') }
    if ($NoJit) { $args += '--nojit' }
    if ($CratonArgs.Count -gt 0) { $args += $CratonArgs }
    $args += @('-Dfile.encoding=UTF-8', '-Djava.awt.headless=true')
    if ($LaunchSpec.kind -eq 'jar') { $args += @('--jar', $LaunchSpec.value, $class) }
    else { $args += @('-cp', $LaunchSpec.value, 'SbRunner', $class) }
  }

  $psi = [System.Diagnostics.ProcessStartInfo]::new()
  $psi.FileName = $file
  $psi.WorkingDirectory = $workingDirectory
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  # Spring Boot's JUL formatter deliberately treats LOG_FORMAT as an
  # application-facing override.  Letting a developer's ambient value leak
  # into every direct JUnit launch changes assertions that exercise its
  # documented default format (for example JavaLoggingSystemTests), and makes
  # the CratonVM/HotSpot comparison host-dependent.  The runner owns a
  # hermetic test-process environment, so remove only this formatter override;
  # individual tests can still set the Java system property explicitly.
  [void]$psi.Environment.Remove('LOG_FORMAT')
  Set-ProcessArguments -StartInfo $psi -Arguments $args
  $proc = [System.Diagnostics.Process]::new()
  $proc.StartInfo = $psi
  [void]$proc.Start()
  return [pscustomobject]@{
    proc = $proc
    stdoutTask = $proc.StandardOutput.ReadToEndAsync()
    stderrTask = $proc.StandardError.ReadToEndAsync()
    module = $module; class = $class; start = Get-Date
    outFile = $outFile; errFile = $errFile; timeoutSec = $Timeout; retries = $Retries
  }
}

function Read-ProcessOutputs([object]$Record) {
  try { $Record.stdoutTask.Wait(5000) | Out-Null } catch {}
  try { $Record.stderrTask.Wait(5000) | Out-Null } catch {}
  $stdout = ''; $stderr = ''
  try { $stdout = $Record.stdoutTask.Result } catch {}
  try { $stderr = $Record.stderrTask.Result } catch {}
  return [pscustomobject]@{ stdout = $stdout; stderr = $stderr }
}

function Complete-ProcessRecord {
  param([object]$Record, [string]$ResultPath, [object]$ExitCode, [double]$Seconds, [string]$Stdout, [string]$Stderr)
  [System.IO.File]::WriteAllText($Record.outFile, $Stdout, [System.Text.Encoding]::UTF8)
  [System.IO.File]::WriteAllText($Record.errFile, $Stderr, [System.Text.Encoding]::UTF8)
  $combined = "$Stdout`n$Stderr"
  $status = 'NOSUMMARY'; $tests = 0; $failed = 0; $aborted = 0; $skipped = 0; $containersFailed = 0

  if ([string]$ExitCode -eq 'TIMEOUT') {
    $status = 'HANG'
  } elseif ($combined -match '(?i)EXCEPTION_ACCESS_VIOLATION|SIGSEGV|fatal runtime error|panicked at|stack smashing|illegal instruction|STATUS_ACCESS|STATUS_STACK_BUFFER|caught fatal signal|cratonvm panic|internal error: entered unreachable') {
    $status = 'CRASH'
  }

  $m = [regex]::Match($combined, 'SBRUNNER_RESULT tests=(\d+) failed=(\d+) aborted=(\d+) skipped=(\d+) containersFailed=(\d+)')
  if ($m.Success) {
    $tests = [int]$m.Groups[1].Value; $failed = [int]$m.Groups[2].Value; $aborted = [int]$m.Groups[3].Value
    $skipped = [int]$m.Groups[4].Value; $containersFailed = [int]$m.Groups[5].Value
    if ($status -ne 'CRASH' -and $status -ne 'HANG') {
      if ($combined -match 'SBRUNNER_LOAD_FAIL') { $status = 'LOADFAIL' }
      elseif ($failed -gt 0 -or $aborted -gt 0 -or $containersFailed -gt 0) { $status = 'FAIL' }
      elseif ($tests -eq 0) { $status = 'EMPTY' }
      else { $status = 'PASS' }
    }
  } elseif ($status -ne 'HANG' -and $status -ne 'CRASH' -and $ExitCode -ne 0) {
    $status = 'CRASH'
  }

  $note = ''
  if ($status -ne 'PASS' -and $status -ne 'EMPTY') {
    $noteMatch = [regex]::Match($combined, '(?im)^(?!\s+at\s)(.*(?:Exception|Error|Caused by|SBRUNNER_LOAD_FAIL|panicked|not implemented|NoClassDef|NoSuchMethod|AbstractMethod|AssertionError).*)$')
    if ($noteMatch.Success) { $note = (($noteMatch.Groups[1].Value -replace "`t", ' ') -replace "`r|`n", ' ') }
  }
  if ($note.Length -gt 180) { $note = $note.Substring(0, 180) }

  $line = @(
    $script:ResultIndex, $Record.module, $Record.class, $Vm, $(if ($Jit -eq 'off') { 'off' } else { 'on' }),
    $ExitCode, $status, (ConvertTo-InvariantString $Seconds), $tests, $failed, $aborted, $skipped, $containersFailed,
    $Record.outFile, $Record.errFile, $note
  ) -join "`t"
  Add-Content -Path $ResultPath -Value $line -Encoding ascii
  $script:ResultIndex++
  Write-Host ("  [{0}] {1,-9} {2,7:N1}s {3}.{4}" -f $script:EffectiveModeName, $status, $Seconds, $Record.module, $Record.class)
}

function Invoke-Mode {
  param([object[]]$Classes)
  $jdk = Resolve-Jdk
  $javaBin = Join-Path $jdk 'bin'
  $java = @((Join-Path $javaBin 'java.exe'), (Join-Path $javaBin 'java')) | Where-Object { Test-Path $_ } | Select-Object -First 1
  if (-not $java) { Die "HotSpot java executable not found under: $javaBin" }
  $craton = ''
  if ($Vm -eq 'craton') {
    $craton = Resolve-CratonExe
    # Matches tomcat-suite-runner's craton knobs. CRATONVM_REAL_NET_SOCKETS in
    # particular is load-bearing here: without it, java.net.ServerSocket uses
    # the legacy synthetic layout whose field-slot mapping doesn't match the
    # real JDK-25 class (declaration order impl@0/created@1/bound@2/closed@3/
    # socketLock@4/options@5), so socketLock reads back null and any real
    # bind (Hazelcast, embedded servers, etc.) throws
    # "NullPointerException: Cannot enter synchronized block because
    # this.socketLock is null" — see docs/known-issues (reference_server_socket_gap
    # in memory) for the full history; this is a known, already-fixed-behind-
    # a-flag issue, not something to re-report as a new bug.
    $env:CRATONVM_REAL = 'net-sockets,aqs'
    $env:CRATONVM_THREADS = '-default-watchdog'
    $env:CRATONVM_JIT = 'rootsnap-cache'
  }

  $run = $RunName
  if (-not $run) { $run = Get-Date -Format 'yyyyMMdd-HHmmss' }
  $mode = $ModeName
  if (-not $mode) {
    if ($Vm -eq 'hotspot') { $mode = if ($Jit -eq 'off') { 'hotspot-xint' } else { 'hotspot-jit' } }
    else { $mode = "$Category-$(if ($Jit -eq 'off') { 'nojit' } else { 'jit' })" }
  }
  $script:EffectiveModeName = $mode

  $modeOut = Join-Path (Join-Path (Join-Path $script:WorkRoot 'results') $run) $mode
  New-Item -ItemType Directory -Force -Path $modeOut | Out-Null
  $results = Join-Path $modeOut 'results.tsv'
  if (-not (Test-Path $results)) {
    "index`tmodule`tclass`tvm`tjit`trc`tstatus`tseconds`ttests`tfailed`taborted`tskipped`tcontainersFailed`tstdoutLog`tstderrLog`tnote" | Set-Content -Path $results -Encoding ascii
  }
  $done = @{}
  foreach ($row in (Import-Csv -Path $results -Delimiter "`t")) { if ($row.class) { $done["$($row.module)`t$($row.class)"] = $true } }
  $todo = @($Classes | Where-Object { -not $done.ContainsKey("$($_.module)`t$($_.class)") })
  $script:ResultIndex = (Import-Csv -Path $results -Delimiter "`t").Count + 1

  Write-Info "mode=$mode vm=$Vm jit=$Jit category=$Category selected=$($Classes.Count) todo=$($todo.Count) parallel=$Parallel timeout=${TimeoutSec}s"
  if ($Vm -eq 'craton') { Write-Info "craton exe=$craton" }
  Write-Info "logs/results=$modeOut"

  $modeStarted = Get-Date
  $script:RunningRecords = New-Object System.Collections.Generic.List[object]

  function Drain-Running {
    $still = New-Object System.Collections.Generic.List[object]
    foreach ($record in $script:RunningRecords) {
      $elapsed = ((Get-Date) - $record.start).TotalSeconds
      if ($record.proc.HasExited) {
        $code = $record.proc.ExitCode
        $outputs = Read-ProcessOutputs $record
        Complete-ProcessRecord -Record $record -ResultPath $results -ExitCode $code -Seconds ([Math]::Round($elapsed, 3)) -Stdout $outputs.stdout -Stderr $outputs.stderr
        try { $record.proc.Dispose() } catch {}
      } elseif ($elapsed -ge $record.timeoutSec) {
        try { $record.proc.Kill($true) } catch { try { $record.proc.Kill() } catch {} }
        try { $record.proc.WaitForExit(5000) | Out-Null } catch {}
        $outputs = Read-ProcessOutputs $record
        Complete-ProcessRecord -Record $record -ResultPath $results -ExitCode 'TIMEOUT' -Seconds ([Math]::Round($elapsed, 3)) -Stdout $outputs.stdout -Stderr $outputs.stderr
        try { $record.proc.Dispose() } catch {}
      } else { $still.Add($record) }
    }
    $script:RunningRecords = $still
  }

  foreach ($classRow in $todo) {
    while ($script:RunningRecords.Count -ge $Parallel) { Drain-Running; if ($script:RunningRecords.Count -ge $Parallel) { Start-Sleep -Milliseconds 200 } }
    $launch = Get-LaunchSpec -ClassRow $classRow
    $classTimeoutSec = Get-EffectiveClassTimeoutSec -ClassRow $classRow -BaseTimeoutSec $TimeoutSec
    if ($classTimeoutSec -ne $TimeoutSec) { Write-Info "timeout override=${classTimeoutSec}s $($classRow.module).$($classRow.class)" }
    $script:RunningRecords.Add((New-ProcessRecord -ClassRow $classRow -ModeOut $modeOut -LaunchSpec $launch -ExePath $craton -JavaExe $java -JdkPath $jdk -NoJit:($Jit -eq 'off') -Timeout $classTimeoutSec))
  }
  while ($script:RunningRecords.Count -gt 0) { Drain-Running; if ($script:RunningRecords.Count -gt 0) { Start-Sleep -Milliseconds 200 } }
  Remove-Variable -Name RunningRecords -Scope Script -ErrorAction SilentlyContinue

  $elapsed = [Math]::Round(((Get-Date) - $modeStarted).TotalSeconds, 3)
  $rows = @(Import-Csv -Path $results -Delimiter "`t")
  $summaryPath = Join-Path $modeOut 'summary.md'
  $counts = $rows | Group-Object status | Sort-Object Name
  $classSeconds = 0.0
  foreach ($row in $rows) { $classSeconds += ConvertFrom-InvariantString ([string]$row.seconds) }

  $summary = New-Object System.Collections.Generic.List[string]
  $summary.Add("# Spring Boot suite result")
  $summary.Add(""); $summary.Add("- run: $run"); $summary.Add("- mode: $mode"); $summary.Add("- vm: $Vm"); $summary.Add("- jit: $Jit")
  $summary.Add("- category: $Category"); $summary.Add("- classes recorded: $($rows.Count)")
  $summary.Add("- wall seconds: $(ConvertTo-InvariantString $elapsed)"); $summary.Add("- summed class seconds: $(ConvertTo-InvariantString $classSeconds)")
  $summary.Add("- spring-boot root: $script:SpringBootDir")
  if ($Vm -eq 'craton') { $summary.Add("- craton exe: $craton") }
  $summary.Add(""); $summary.Add("## Status Counts")
  foreach ($group in $counts) { $summary.Add("- $($group.Name): $($group.Count)") }
  $summary.Add(""); $summary.Add("## Files"); $summary.Add("- results: $results"); $summary.Add("- logs: $(Join-Path $modeOut 'logs')")
  $summary | Set-Content -Path $summaryPath -Encoding ascii

  if ($Vm -eq 'hotspot') {
    $baselineDir = Join-Path $script:WorkRoot 'baseline'
    New-Item -ItemType Directory -Force -Path $baselineDir | Out-Null
    $baselineBase = "hotspot-baseline-$run"
    Copy-Item -Path $results -Destination (Join-Path $baselineDir "$baselineBase.tsv") -Force
    Copy-Item -Path $summaryPath -Destination (Join-Path $baselineDir "$baselineBase.md") -Force
    Copy-Item -Path $results -Destination (Join-Path $baselineDir 'hotspot-baseline-latest.tsv') -Force
    Copy-Item -Path $summaryPath -Destination (Join-Path $baselineDir 'hotspot-baseline-latest.md') -Force
    Write-Info "baseline copied to $baselineDir\$baselineBase.tsv"
  }
  Write-Info "DONE mode=$mode wall=${elapsed}s summary=$summaryPath"
}

function Invoke-AllModes {
  $run = $RunName
  if (-not $run) { $run = Get-Date -Format 'yyyyMMdd-HHmmss' }
  $self = $PSCommandPath
  $psExe = Get-PowerShellExe
  $modes = @(
    @{ jit = 'on';  name = 'jit' },
    @{ jit = 'off'; name = 'nojit' }
  )
  $runRoot = Join-Path (Join-Path $script:WorkRoot 'results') $run
  New-Item -ItemType Directory -Force -Path $runRoot | Out-Null
  $children = @()
  foreach ($mode in $modes) {
    $log = Join-Path $runRoot "$($mode.name).console.log"
    $err = Join-Path $runRoot "$($mode.name).console.err.log"
    $args = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $self,
      '-Category', $Category, '-Jit', $mode.jit, '-Vm', 'craton',
      '-Start', $Start, '-Count', $Count, '-Parallel', $Parallel, '-TimeoutSec', $TimeoutSec,
      '-RunName', $run, '-ModeName', $mode.name, '-SpringBootRoot', $script:SpringBootDir,
      '-WorkDir', $script:WorkRoot, '-JdkHome', (Resolve-Jdk), '-MaxHeap', $MaxHeap)
    if ($Exe) { $args += @('-Exe', $Exe) }
    if ($RefCsv) { $args += @('-RefCsv', $RefCsv) }
    if ($ClassList) { $args += @('-ClassList', $ClassList) }
    if ($CratonArgs.Count -gt 0) { foreach ($extra in $CratonArgs) { $args += @('-CratonArgs', $extra) } }
    Write-Info "launching $($mode.name) in background"
    $children += Start-RedirectedProcess -FilePath $psExe -Arguments $args -WorkingDirectory $script:RepoRoot -StdoutPath $log -StderrPath $err
  }
  $failedChildren = 0
  foreach ($child in $children) { $exitCode = Complete-RedirectedProcess $child; if ($exitCode -ne 0) { $failedChildren++ } }
  if ($failedChildren -gt 0) { Die "$failedChildren all-mode child process(es) failed; inspect $runRoot\*.console*.log" }
  Write-Info "ALL MODES DONE. Results under $runRoot"
}

$script:RepoRoot = Get-RepoRoot
if (-not $SpringBootRoot) {
  $appsRoot = Split-Path $PSScriptRoot -Parent
  $SpringBootRoot = Join-Path $appsRoot 'spring-boot'
}
$script:SpringBootDir = [System.IO.Path]::GetFullPath($SpringBootRoot)
if (-not (Test-Path $script:SpringBootDir)) { Die "Spring Boot root not found: $script:SpringBootDir" }
$script:SbRunnerDir = Join-Path $script:SpringBootDir 'sb-runner'
if (-not (Test-Path (Join-Path $script:SbRunnerDir 'SbRunner.class'))) { Die "missing SbRunner.class in $script:SbRunnerDir (javac SbRunner.java against the JUnit platform jars first)" }

if (-not $WorkDir) { $WorkDir = Join-Path $PSScriptRoot '.suite' }
$script:WorkRoot = [System.IO.Path]::GetFullPath($WorkDir)
New-Item -ItemType Directory -Force -Path $script:WorkRoot | Out-Null

if ($Start -lt 1) { Die "-Start is 1-based and must be >= 1" }
if ($Count -lt 0) { Die "-Count must be >= 0" }
if ($Parallel -lt 1) { Die "-Parallel must be >= 1" }
if ($TimeoutSec -lt 1) { Die "-TimeoutSec must be >= 1" }

if ($Setup) {
  Invoke-GradleSetup
  if (-not $AllModes -and $Category -eq 'all' -and -not $ListOnly -and $Count -eq 0 -and $Start -eq 1) {
    Write-Info "Setup-only invocation complete (no -Count given). Re-run without -Setup to execute."
    return
  }
}

if ($AllModes) {
  if ($Vm -ne 'craton') { Die "-AllModes is CratonVM-only" }
  Invoke-AllModes
  return
}

$classes = @(Get-SelectedClasses)
Write-Info "selected $($classes.Count) classes (category=$Category start=$Start count=$(if ($Count -gt 0) { $Count } else { 'all' }))"
if ($ListOnly) {
  $i = $Start
  foreach ($class in $classes) { "{0}`t{1}`t{2}" -f $i, $class.module, $class.class; $i++ }
  return
}
if ($classes.Count -eq 0) { Die "no classes selected" }

Invoke-Mode -Classes $classes
