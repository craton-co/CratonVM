function Get-RepoRoot {
  try {
    $root = & git -C $PSScriptRoot rev-parse --show-toplevel 2>$null
    if ($LASTEXITCODE -eq 0 -and $root) { return $root.Trim() }
  } catch {}
  return (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent)
}

function Get-PowerShellExe {
  if ($PSHOME) {
    $candidate = Join-Path $PSHOME 'pwsh.exe'
    if (Test-Path $candidate) { return $candidate }
    $candidate = Join-Path $PSHOME 'powershell.exe'
    if (Test-Path $candidate) { return $candidate }
  }
  return 'powershell.exe'
}

function ConvertTo-SafeName([string]$Value) {
  return ($Value -replace '[^A-Za-z0-9_.-]', '_')
}

function ConvertTo-SafeFileStem([string]$Value, [int]$MaxLength = 96) {
  $safe = ConvertTo-SafeName $Value
  if ($MaxLength -lt 16) { $MaxLength = 16 }
  if ($safe.Length -le $MaxLength) { return $safe }
  $sha = [System.Security.Cryptography.SHA256]::Create()
  try {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($safe)
    $hash = ([System.BitConverter]::ToString($sha.ComputeHash($bytes)) -replace '-', '').Substring(0, 12).ToLowerInvariant()
  } finally {
    $sha.Dispose()
  }
  $prefixLength = $MaxLength - $hash.Length - 1
  return "$($safe.Substring(0, $prefixLength))-$hash"
}

function Get-Sha256Hex([string]$Value) {
  $sha = [System.Security.Cryptography.SHA256]::Create()
  try {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($Value)
    return (([System.BitConverter]::ToString($sha.ComputeHash($bytes))) -replace '-', '').ToLowerInvariant()
  } finally {
    $sha.Dispose()
  }
}

function ConvertTo-InvariantString([double]$Value) {
  return $Value.ToString('F3', [System.Globalization.CultureInfo]::InvariantCulture)
}

function ConvertFrom-InvariantString([string]$Value) {
  $parsed = 0.0
  if ([double]::TryParse($Value, [System.Globalization.NumberStyles]::Float, [System.Globalization.CultureInfo]::InvariantCulture, [ref]$parsed)) {
    return $parsed
  }
  return 0.0
}

function Quote-WindowsArgument([string]$Argument) {
  if ($null -eq $Argument) { return '""' }
  if ($Argument.Length -eq 0) { return '""' }
  if ($Argument -notmatch '[\s"]') { return $Argument }
  $result = New-Object System.Text.StringBuilder
  [void]$result.Append('"')
  $backslashes = 0
  foreach ($ch in $Argument.ToCharArray()) {
    if ($ch -eq '\') {
      $backslashes++
    } elseif ($ch -eq '"') {
      if ($backslashes -gt 0) { [void]$result.Append('\' * ($backslashes * 2)) }
      $backslashes = 0
      [void]$result.Append('\"')
    } else {
      if ($backslashes -gt 0) { [void]$result.Append('\' * $backslashes) }
      $backslashes = 0
      [void]$result.Append($ch)
    }
  }
  if ($backslashes -gt 0) { [void]$result.Append('\' * ($backslashes * 2)) }
  [void]$result.Append('"')
  return $result.ToString()
}

function Set-ProcessArguments([System.Diagnostics.ProcessStartInfo]$StartInfo, [string[]]$Arguments) {
  # ProcessStartInfo.ArgumentList is unavailable/null under Windows PowerShell
  # 5.1 (.NET Framework) in some environments — fall back to the classic
  # pre-quoted Arguments string when it's not usable.
  $argListProp = $StartInfo.GetType().GetProperty('ArgumentList')
  if ($argListProp -and $StartInfo.ArgumentList) {
    foreach ($arg in $Arguments) { [void]$StartInfo.ArgumentList.Add($arg) }
  } else {
    $StartInfo.Arguments = (($Arguments | ForEach-Object { Quote-WindowsArgument $_ }) -join ' ')
  }
}

function Start-RedirectedProcess {
  param([string]$FilePath, [string[]]$Arguments, [string]$WorkingDirectory, [string]$StdoutPath, [string]$StderrPath)
  $psi = [System.Diagnostics.ProcessStartInfo]::new()
  $psi.FileName = $FilePath
  $psi.WorkingDirectory = $WorkingDirectory
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  Set-ProcessArguments -StartInfo $psi -Arguments $Arguments
  $proc = [System.Diagnostics.Process]::new()
  $proc.StartInfo = $psi
  [void]$proc.Start()
  return [pscustomobject]@{
    proc = $proc
    stdoutTask = $proc.StandardOutput.ReadToEndAsync()
    stderrTask = $proc.StandardError.ReadToEndAsync()
    stdoutPath = $StdoutPath
    stderrPath = $StderrPath
  }
}

function Complete-RedirectedProcess([object]$Record) {
  $Record.proc.WaitForExit()
  try { $Record.stdoutTask.Wait(5000) | Out-Null } catch {}
  try { $Record.stderrTask.Wait(5000) | Out-Null } catch {}
  $stdout = ''; $stderr = ''
  try { $stdout = $Record.stdoutTask.Result } catch {}
  try { $stderr = $Record.stderrTask.Result } catch {}
  if ($Record.stdoutPath) { [System.IO.File]::WriteAllText($Record.stdoutPath, $stdout, [System.Text.Encoding]::UTF8) }
  if ($Record.stderrPath) { [System.IO.File]::WriteAllText($Record.stderrPath, $stderr, [System.Text.Encoding]::UTF8) }
  $exitCode = $Record.proc.ExitCode
  try { $Record.proc.Dispose() } catch {}
  return $exitCode
}

function Split-ClasspathEntries([string]$Classpath) {
  if (-not $Classpath) { return @() }
  $separator = [string][System.IO.Path]::PathSeparator
  return @($Classpath -split [regex]::Escape($separator) | Where-Object { $_ })
}

function Add-UniqueClasspathEntry {
  param([System.Collections.Generic.List[string]]$Entries, [hashtable]$Seen, [string]$Entry)
  if (-not $Entry) { return }
  try {
    $full = [System.IO.Path]::GetFullPath($Entry)
    $key = $full.ToLowerInvariant()
    $value = $full
  } catch {
    $key = $Entry.ToLowerInvariant()
    $value = $Entry
  }
  if (-not $Seen.ContainsKey($key)) {
    $Entries.Add($value)
    $Seen[$key] = $true
  }
}

function Get-GradleCacheRoot {
  if ($script:GradleCacheRootCache) { return $script:GradleCacheRootCache }
  $candidates = @()
  if ($env:GRADLE_USER_HOME) { $candidates += (Join-Path $env:GRADLE_USER_HOME 'caches\modules-2\files-2.1') }
  if ($env:USERPROFILE) { $candidates += (Join-Path $env:USERPROFILE '.gradle\caches\modules-2\files-2.1') }
  foreach ($c in $candidates) { if (Test-Path $c) { $script:GradleCacheRootCache = $c; return $c } }
  $script:GradleCacheRootCache = ''
  return ''
}

function Find-GradleCacheJar([string]$Group, [string]$Artifact) {
  $root = Get-GradleCacheRoot
  if (-not $root) { return $null }
  $artifactDir = Join-Path $root "$Group\$Artifact"
  if (-not (Test-Path $artifactDir)) { return $null }
  return Get-ChildItem -Path $artifactDir -Recurse -File -Filter "$Artifact-*.jar" -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -notmatch '(-sources|-javadoc)\.jar$' } |
    Sort-Object FullName -Descending | Select-Object -First 1
}

function Add-JUnitPlatformInfraEntries {
  # SbRunner drives every class through the JUnit Platform Launcher's default
  # ServiceLoader engine auto-registration, so both jupiter (JUnit5) and
  # vintage (JUnit4, if a class needs it) run uniformly. A module's own
  # Gradle testRuntimeClasspath does NOT necessarily include the launcher
  # jar (Gradle's `test` task manages that on its own internal classpath,
  # not the project's), so make it universally available here — same
  # rationale as the Keycloak runner's Add-JUnitPlatformInfraEntries.
  param([System.Collections.Generic.List[string]]$Entries, [hashtable]$Seen)
  $artifacts = @(
    @('org.junit.platform', 'junit-platform-commons'),
    @('org.junit.platform', 'junit-platform-engine'),
    @('org.junit.platform', 'junit-platform-launcher'),
    @('org.junit.jupiter', 'junit-jupiter-api'),
    @('org.junit.jupiter', 'junit-jupiter-engine'),
    @('org.junit.vintage', 'junit-vintage-engine'),
    @('org.opentest4j', 'opentest4j'),
    @('org.apiguardian', 'apiguardian-api'),
    @('junit', 'junit')
  )
  foreach ($pair in $artifacts) {
    $jar = Find-GradleCacheJar -Group $pair[0] -Artifact $pair[1]
    if ($jar) { Add-UniqueClasspathEntry -Entries $Entries -Seen $Seen -Entry $jar.FullName }
  }
}

function ConvertTo-ManifestClasspathUrl([string]$Entry) {
  $full = [System.IO.Path]::GetFullPath($Entry)
  if ((Test-Path $full -PathType Container) -and -not ($full.EndsWith('\') -or $full.EndsWith('/'))) {
    $full += [System.IO.Path]::DirectorySeparatorChar
  }
  return ([System.Uri]::new($full, [System.UriKind]::Absolute)).AbsoluteUri
}

function Split-ManifestLine([string]$Line) {
  $max = 70
  $out = New-Object System.Collections.Generic.List[string]
  if ($Line.Length -le $max) { $out.Add($Line); return @($out) }
  $out.Add($Line.Substring(0, $max))
  $offset = $max
  while ($offset -lt $Line.Length) {
    $take = [Math]::Min($max - 1, $Line.Length - $offset)
    $out.Add(' ' + $Line.Substring($offset, $take))
    $offset += $take
  }
  return @($out)
}

function New-PathingJar {
  param([string]$Module, [string[]]$Entries)
  # -AllModes launches JIT and no-JIT child runners concurrently.  They have
  # the same module classpath signature but must not race over one
  # classpath.jar (one child can observe the other deleting/recreating it).
  # Mode-local wrappers retain caching within a lane while making the two
  # child processes independent.
  $modePath = ConvertTo-SafeName $(if ($script:EffectiveModeName) { $script:EffectiveModeName } else { 'default' })
  $pathingDir = Join-Path (Join-Path $script:WorkRoot 'pathing-jars') $modePath
  New-Item -ItemType Directory -Force -Path $pathingDir | Out-Null
  $signature = 'pathing-jar-manifest-url-v1' + "`n" + (($Entries | ForEach-Object { [System.IO.Path]::GetFullPath($_) }) -join "`n")
  $hash = (Get-Sha256Hex $signature).Substring(0, 16)
  $stem = ConvertTo-SafeFileStem $(if ($Module) { $Module } else { 'universal' })
  # Spring Boot's ModifiedClassPathClassLoader expands the manifest class
  # path only for IntelliJ-style `classpath.jar` files.  The runner needs
  # that expansion for @ClassPathExclusions/@ClassPathOverrides: otherwise
  # it sees this one wrapper JAR instead of the individual dependency JARs.
  # Keep module/content isolation in directories so the wrapper name itself
  # can retain the recognized IntelliJ convention.
  $jarDir = Join-Path (Join-Path $pathingDir $stem) $hash
  $jarPath = Join-Path $jarDir 'classpath.jar'
  if (Test-Path $jarPath) { return [System.IO.Path]::GetFullPath($jarPath) }
  New-Item -ItemType Directory -Force -Path $jarDir | Out-Null

  Add-Type -AssemblyName System.IO.Compression | Out-Null
  Add-Type -AssemblyName System.IO.Compression.FileSystem | Out-Null
  $urls = @($Entries | ForEach-Object { ConvertTo-ManifestClasspathUrl $_ })
  $lines = New-Object System.Collections.Generic.List[string]
  $lines.Add('Manifest-Version: 1.0')
  $lines.Add('Created-By: IntelliJ IDEA')
  $lines.Add('Main-Class: SbRunner')
  foreach ($line in (Split-ManifestLine ('Class-Path: ' + ($urls -join ' ')))) { $lines.Add($line) }
  $lines.Add('')

  if (Test-Path $jarPath) { Remove-Item -LiteralPath $jarPath -Force }
  $zip = [System.IO.Compression.ZipFile]::Open($jarPath, [System.IO.Compression.ZipArchiveMode]::Create)
  try {
    $entry = $zip.CreateEntry('META-INF/MANIFEST.MF')
    $stream = $entry.Open()
    try {
      $writer = [System.IO.StreamWriter]::new($stream, [System.Text.Encoding]::ASCII)
      try { $writer.NewLine = "`r`n"; foreach ($line in $lines) { $writer.WriteLine($line) } } finally { $writer.Dispose() }
    } finally { $stream.Dispose() }
  } finally { $zip.Dispose() }
  return [System.IO.Path]::GetFullPath($jarPath)
}

function Import-ResultRows([string]$Path) {
  if (-not (Test-Path $Path)) { return @() }
  $first = Get-Content -Path $Path -TotalCount 1
  $delimiter = ','
  if ($first -like "*`t*") { $delimiter = "`t" }
  return @(Import-Csv -Path $Path -Delimiter $delimiter)
}

function Select-ClassRange([object[]]$List) {
  $list = @($List)
  $from = [Math]::Max(1, $Start) - 1
  if ($from -ge $list.Count) { return @() }
  $end = $list.Count
  if ($Count -gt 0) { $end = [Math]::Min($list.Count, $from + $Count) }
  return @($list[$from..($end - 1)])
}

function Get-CorruptCellCensus {
  <#
    Read back the `[corrupt-cell] decoded=N reported=M` line every armed
    cratonvm.exe prints from its shutdown trailer.

    The ARMED count is reported separately from the DECODED count on purpose.
    An absent line and a zero line are different claims: the first armed sweep
    run against this suite printed the census in ZERO of 1975 logs -- a JUnit
    runner exits through System.exit, and the summary was on a path it never
    took -- and that run looked exactly like a clean one. Counting the logs that
    actually carried the line is what makes "0 decoded" mean something.
  #>
  param([string]$LogDir)
  $logs = @(Get-ChildItem -Path $LogDir -Filter '*.err.log' -ErrorAction SilentlyContinue)
  $armed = 0; $decoded = 0; $reported = 0; $arrayRecv = 0; $classes = @()
  foreach ($f in $logs) {
    $m = Select-String -Path $f.FullName -Pattern '\[corrupt-cell\] decoded=(\d+) reported=(\d+)' -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $m) { continue }
    $armed++
    $d = [int]$m.Matches[0].Groups[1].Value
    $r = [int]$m.Matches[0].Groups[2].Value
    $decoded += $d; $reported += $r
    # `array_receiver` is the SAME defect one step earlier: a plain-object field
    # access whose receiver is an array, refused at the heap accessor. It is a
    # COUNT where `decoded` is a floor -- the corrupt-cell guard only fires when
    # the striden element bytes happen to form an out-of-range discriminant --
    # so a sweep with `decoded=0 array_receiver=N` has found N producers the
    # guard could not see. Reported separately for that reason.
    $a = Select-String -Path $f.FullName -Pattern '\[corrupt-cell\] array_receiver=(\d+)' -ErrorAction SilentlyContinue | Select-Object -First 1
    $av = 0
    if ($a) { $av = [int]$a.Matches[0].Groups[1].Value; $arrayRecv += $av }
    if ($d -gt 0 -or $av -gt 0) {
      # `<module>.<fqcn>.err.log` -- keep the class, drop the module and suffix.
      $stem = $f.Name -replace '\.err\.log$', ''
      $classes += ("{0}  (decoded={1} named={2} array_receiver={3})" -f $stem, $d, $r, $av)
    }
  }
  return [pscustomobject]@{
    Logs = $logs.Count; Armed = $armed; Unarmed = ($logs.Count - $armed)
    Decoded = $decoded; Reported = $reported; ArrayReceiver = $arrayRecv; Classes = $classes
  }
}

function Resolve-ReferenceFile {
