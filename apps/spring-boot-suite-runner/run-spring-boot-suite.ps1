    # perf-test shape -- N property sources x M keys x K
    # `environment.getProperty()` iterations -- measured CONSTANT
    # per-iteration cost, ~47ms/iter at 5 sources x 1000 keys, no quadratic
    # growth across 20-iteration buckets, confirmed linear not superlinear
    # scaling) all point to a real but DIFFUSE interpreter/dispatch
    # throughput gap, not a deadlock -- consistent with the already-tracked
    # reference_hashmap_native_call_dispatch_overhead /
    # reference_junit5_execution_machinery_dispatch_overhead family in
    # project memory. The class deliberately exercises an "uncached"
    # O(sources x keys) baseline against ~100 property sources x 1000 keys x
    # 1000 iterations (explicit `cached < uncached/2` perf assertions) --
    # genuinely CPU-heavy by design, not merely slow-to-start. A standalone
    # rerun completed (PASS) in 2645.0s; keep headroom above that observed
    # time instead of reporting a false HANG.
    #
    # NOTE: `ConfigurationPropertiesBeanRegistrationAotProcessorTests` (the
    # other class originally reported alongside this one) is DELIBERATELY
    # NOT in this table -- unlike this class, it never completed even at a
    # 7200s (2-hour) ceiling with ZERO of its 9 `@Test` methods reporting a
    # result, and a CPU-sampled stack repeatedly lands at the identical
    # bytecode offset in Hibernate Validator's
    # `BeanMetaDataImpl.getClassLevelConstraintsAsDescriptors` across samples
    # taken minutes and hours apart -- a real, still-unfixed hang, not a
    # throughput gap. Do not paper over it with a timeout; see
    # docs/known-issues/springboot/configurationpropertiesbeanregistrationaotprocessortests-hang.md.
    'core/spring-boot|org.springframework.boot.context.properties.source.ConfigurationPropertySourcesTests' = 5400
    # EMBEDDED-SERVER-BUDGET.1 (2026-08-11): these two build, start and stop a
    # fresh embedded container per @Test -- 121 (Tomcat) and ~100 (Jetty)
    # container starts in one process, each of which runs Jasper's whole TLD
    # scan over the module's 130-jar test classpath. Both were reported as
    # HANG at 300s in every full-suite run since 2026-08-06, and the Jetty one
    # once as `tests=0` at a 2400s ceiling. Neither is stuck. Measured alone
    # on an idle Windows host, default collector, -Xmx 2g, after the
    # JarFile-accessor stat fix landed:
    #   Tomcat 420.2s, 132 tests, 0 failed   (HotSpot 41.1s / 129 tests)
    #   Jetty  407.0s, 113 tests, 0 failed   (HotSpot 28.6s / 111 tests)
    # -- see fixed-suite-bugs/springboot/tomcat-jetty-servletwebserverfactorytests-300s-budget-overrun-FIXED-20260811.md.
    # The 10-14x ratio is a real throughput item and is tracked as one
    # (known-issues/tomcat/!webapp-deploy-annotation-scan-interpreted-226x.md);
    # this entry exists so the suite reports 132/132 and 113/113 instead of a
    # HANG, not to hide the ratio. Headroom over the observed time for
    # contention when several slow classes share a -Parallel batch.
    'module/spring-boot-tomcat|org.springframework.boot.tomcat.servlet.TomcatServletWebServerFactoryTests' = 900
    'module/spring-boot-jetty|org.springframework.boot.jetty.servlet.JettyServletWebServerFactoryTests' = 900
    # PULSAR-BUDGET.1 (2026-08-11): reported as a deterministic 300s HANG in
    # the three 2026-08-06/07 full-suite runs. It is not stuck -- the evidence
    # for "hang" was a 0-byte .out.log (SbRunner prints nothing until the run
    # finishes, and this class logs nothing of its own) and an identical last
    # .err.log line, which is the last line of every PASSING run of this class
    # too. Alone on an idle host it completes 74/74 in 178-204s, and 220-277s
    # when sharing the box -- right on the 300s boundary, which is why the
    # suite has always seen it flip between HANG and PASS. See
    # fixed-suite-bugs/springboot/pulsarautoconfigurationtests-onbeancondition-multivaluemap-classcastexception-flake-FIXED-20260811.md.
    'module/spring-boot-pulsar|org.springframework.boot.pulsar.autoconfigure.PulsarAutoConfigurationTests' = 900
  }
  # The same budgets, in a form the Linux shard driver can read too
  # (`linux-oracles/run-sb-gc-shard.sh`). The ad-hoc copy of that driver which
  # ran the 2026-08-19 three-collector sweep re-implemented the launch and
  # dropped this table entirely, so every class above the 300-second default
  # came back HANG -- eight of the nine HANG rows in the 2026-08-21 re-run,
  # all of which pass with test counts identical to HotSpot once given the
  # budget already recorded here. One table, two readers, so that cannot
  # recur. The file wins where both define a key; the inline table above
  # remains the fallback, so a missing file changes nothing.
  $timeoutsFile = Join-Path $PSScriptRoot '.suite/class-timeouts.tsv'
  if (Test-Path -LiteralPath $timeoutsFile) {
    foreach ($row in @(Import-Csv -LiteralPath $timeoutsFile -Delimiter "`t")) {
      if (-not $row.module -or -not $row.class) { continue }
      $seconds = 0
      if ([int]::TryParse([string]$row.seconds, [ref]$seconds) -and $seconds -gt 0) {
        $slowClasses["$($row.module)|$($row.class)"] = $seconds
      }
    }
  }
  $key = "$($ClassRow.module)|$($ClassRow.class)"
  if ($slowClasses.ContainsKey($key)) {
    return [Math]::Max($BaseTimeoutSec, $slowClasses[$key])
  }
  return $BaseTimeoutSec
}

function New-ProcessRecord {
  param([object]$ClassRow, [string]$ModeOut, [object]$LaunchSpec, [string]$ExePath, [string]$JavaExe, [string]$JdkPath, [bool]$NoJit, [int]$Timeout, [int]$Retries = 0)
  $module = [string]$ClassRow.module
  $class = [string]$ClassRow.class
  $workingDirectory = $script:SpringBootDir
  $modulePath = $module -replace '/', [System.IO.Path]::DirectorySeparatorChar
  $moduleRoot = Join-Path $script:SpringBootDir $modulePath
  if (Test-Path $moduleRoot) { $workingDirectory = $moduleRoot }
  $logDir = Join-Path $ModeOut 'logs'
  New-Item -ItemType Directory -Force -Path $logDir | Out-Null
  # `WriteAllText` still observes the legacy MAX_PATH limit on some Windows
  # PowerShell/.NET Framework combinations.  Worktree and run names are both
  # intentionally unique and can be long, so size the per-class stem from the
  # actual log-directory prefix rather than assuming the historical 96-char
  # cap always leaves room for the extension.
  $maxStemLength = [Math]::Max(16, 240 - $logDir.Length - '.out.log'.Length - 1)
  $safe = ConvertTo-SafeFileStem "$module.$class" -MaxLength $maxStemLength
  $outFile = Join-Path $logDir "$safe.out.log"
  $errFile = Join-Path $logDir "$safe.err.log"

  # Several modules' own build.gradle add --add-opens=java.base/java.net=ALL-UNNAMED
  # to their Gradle `test` task JVM args (jetty/security/servlet/tomcat/webflux/
  # websocket -- reflective field reset in their web-server test fixtures, via
  # @DirtiesUrlFactories -> ReflectionTestUtils.setField(URL.class, "factory", null)).
  # This runner launches SbRunner directly instead of through Gradle's test task,
  # so none of those per-module jvmArgs apply; without it those classes fail with
  # "IllegalStateException: Unable to reset field", which is a harness gap, not a
  # genuine VM behavior difference. Apply it universally -- opens are additive and
  # harmless for modules that don't need it.
  #
  # "Universally" has to mean BOTH launch arms, and for three weeks it did not:
  # the flag was added (948df715a, 2026-07-17) to the hotspot branch only,
  # deliberately, because CratonVM did not enforce the module boundary at all and
  # the flag was moot there. Commit 7c92363bd (2026-08-06) closed that
  # encapsulation hole, and the same seven-plus classes that had always needed the
  # flag on HotSpot started failing 100% on CratonVM -- a harness asymmetry that
  # had been invisible only because the VM was wrong in a compensating direction.
  # Keep the argument in one variable so a future arm cannot silently omit it. See
  # fixed-suite-bugs/springboot/dirtiesurlfactories-craton-launcher-missing-add-opens-FIXED-20260809.md.
  $addOpensJavaNet = '--add-opens=java.base/java.net=ALL-UNNAMED'

  if ($Vm -eq 'hotspot') {
    $file = $JavaExe
    $args = @("-Xmx$MaxHeap", '-Dfile.encoding=UTF-8', '-Djava.awt.headless=true', $addOpensJavaNet)
    if ($NoJit) { $args += '-Xint' }
    if ($LaunchSpec.kind -eq 'jar') { $args += @('-jar', $LaunchSpec.value, $class) }
    else { $args += @('-cp', $LaunchSpec.value, 'SbRunner', $class) }
  } else {
    $file = $ExePath
    $args = @('--java-home', $JdkPath, '--Xmx', $MaxHeap, $addOpensJavaNet)
    # The suite normally disables the VM watchdog because it owns the
    # per-class timeout.  Preserve that default, but let a caller provide a
    # real watchdog value through -CratonArgs for a diagnostic run.
    $hasWatchdogArg = @($CratonArgs | Where-Object { $_ -match '^--stack-dump-on-timeout(?:=|$)' }).Count -gt 0
    if (-not $hasWatchdogArg) { $args += @('--stack-dump-on-timeout', '0') }
    if ($NoJit) { $args += '--nojit' }
    if ($CratonArgs.Count -gt 0) { $args += $CratonArgs }
    $args += @('-Dfile.encoding=UTF-8', '-Djava.awt.headless=true')
    if ($LaunchSpec.kind -eq 'jar') { $args += @('--jar', $LaunchSpec.value, $class) }
    else { $args += @('-cp', $LaunchSpec.value, 'SbRunner', $class) }
  }

  $psi = [System.Diagnostics.ProcessStartInfo]::new()
  $psi.FileName = $file
  $psi.WorkingDirectory = $workingDirectory
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  # Spring Boot's JUL formatter deliberately treats LOG_FORMAT as an
  # application-facing override.  Letting a developer's ambient value leak
  # into every direct JUnit launch changes assertions that exercise its
  # documented default format (for example JavaLoggingSystemTests), and makes
  # the CratonVM/HotSpot comparison host-dependent.  The runner owns a
  # hermetic test-process environment, so remove only this formatter override;
  # individual tests can still set the Java system property explicitly.
  [void]$psi.Environment.Remove('LOG_FORMAT')
  Set-ProcessArguments -StartInfo $psi -Arguments $args
  $proc = [System.Diagnostics.Process]::new()
  $proc.StartInfo = $psi
  [void]$proc.Start()
  return [pscustomobject]@{
    proc = $proc
    stdoutTask = $proc.StandardOutput.ReadToEndAsync()
    stderrTask = $proc.StandardError.ReadToEndAsync()
    module = $module; class = $class; start = Get-Date
    outFile = $outFile; errFile = $errFile; timeoutSec = $Timeout; retries = $Retries
  }
}

function Read-ProcessOutputs([object]$Record) {
  try { $Record.stdoutTask.Wait(5000) | Out-Null } catch {}
  try { $Record.stderrTask.Wait(5000) | Out-Null } catch {}
  $stdout = ''; $stderr = ''
  try { $stdout = $Record.stdoutTask.Result } catch {}
  try { $stderr = $Record.stderrTask.Result } catch {}
  return [pscustomobject]@{ stdout = $stdout; stderr = $stderr }
}

function Complete-ProcessRecord {
  param([object]$Record, [string]$ResultPath, [object]$ExitCode, [double]$Seconds, [string]$Stdout, [string]$Stderr)
  [System.IO.File]::WriteAllText($Record.outFile, $Stdout, [System.Text.Encoding]::UTF8)
  [System.IO.File]::WriteAllText($Record.errFile, $Stderr, [System.Text.Encoding]::UTF8)
  $combined = "$Stdout`n$Stderr"
  $status = 'NOSUMMARY'; $tests = 0; $failed = 0; $aborted = 0; $skipped = 0; $containersFailed = 0

  if ([string]$ExitCode -eq 'TIMEOUT') {
    $status = 'HANG'
  } elseif ($combined -match '(?i)EXCEPTION_ACCESS_VIOLATION|SIGSEGV|fatal runtime error|panicked at|stack smashing|illegal instruction|STATUS_ACCESS|STATUS_STACK_BUFFER|caught fatal signal|cratonvm panic|internal error: entered unreachable') {
    $status = 'CRASH'
  }

  $m = [regex]::Match($combined, 'SBRUNNER_RESULT tests=(\d+) failed=(\d+) aborted=(\d+) skipped=(\d+) containersFailed=(\d+)')
  if ($m.Success) {
    $tests = [int]$m.Groups[1].Value; $failed = [int]$m.Groups[2].Value; $aborted = [int]$m.Groups[3].Value
    $skipped = [int]$m.Groups[4].Value; $containersFailed = [int]$m.Groups[5].Value
    if ($status -ne 'CRASH' -and $status -ne 'HANG') {
      if ($combined -match 'SBRUNNER_LOAD_FAIL') { $status = 'LOADFAIL' }
      elseif ($failed -gt 0 -or $aborted -gt 0 -or $containersFailed -gt 0) { $status = 'FAIL' }
      elseif ($tests -eq 0) { $status = 'EMPTY' }
      else { $status = 'PASS' }
    }
  } elseif ($status -ne 'HANG' -and $status -ne 'CRASH' -and $ExitCode -ne 0) {
    $status = 'CRASH'
  }

  $note = ''
  if ($status -ne 'PASS' -and $status -ne 'EMPTY') {
    $noteMatch = [regex]::Match($combined, '(?im)^(?!\s+at\s)(.*(?:Exception|Error|Caused by|SBRUNNER_LOAD_FAIL|panicked|not implemented|NoClassDef|NoSuchMethod|AbstractMethod|AssertionError).*)$')
    if ($noteMatch.Success) { $note = (($noteMatch.Groups[1].Value -replace "`t", ' ') -replace "`r|`n", ' ') }
  }
  # Record how far the [moving-young] GC fallback escalated, because that count
  # is what distinguishes the two very different rows that both surface as a
  # 300s HANG:
  #
  #   * a handful of fallbacks is harmless -- FlywayAutoConfigurationTests hits
  #     7 and still completes (496s standalone, 73/73);
  #   * a count in the thousands is a death spiral -- the young free list
  #     fragments until allocation fails. IntegrationAutoConfigurationTests
  #     reaches #16384 and dies of OutOfMemoryError after 3.8 HOURS;
  #     QuartzEndpointWebIntegrationTests reaches #4096 and does not finish in
  #     2400s. Both pass in ~220-260s under `--nojit`, with zero fallbacks.
  #
  # Without this, all three read as "the class is slow, raise its timeout" --
  # which is the wrong fix for the latter two and costs a multi-hour standalone
  # rerun to discover. Same mechanism as the ZipContentTests OOM (512
  # consecutive fallbacks, clean under `--nojit`).
  $fallbacks = [regex]::Matches($combined, '\[moving-young\] fallback #(\d+)')
  if ($fallbacks.Count -gt 0) {
    $peak = 0
    foreach ($m in $fallbacks) {
      $n = [int]$m.Groups[1].Value
      if ($n -gt $peak) { $peak = $n }
    }
    $reason = ''
    $rm = [regex]::Match($combined, '\[moving-young\] fallback #\d+: reason=([a-z-]+)')
    if ($rm.Success) { $reason = " $($rm.Groups[1].Value)" }
    $gcNote = "moving-young-fallback peak=#$peak$reason"
    $note = if ($note) { "$gcNote | $note" } else { $gcNote }
  }
  # Truncate AFTER the GC note is prepended, so a long exception string cannot
  # push the fallback count out of the row.
  if ($note.Length -gt 240) { $note = $note.Substring(0, 240) }

  # Reclassify a failure the reference VM shares, and in every other case still
  # record what HotSpot did, so a row that stayed FAIL despite a failing
  # baseline (a crash, or more failed tests than HotSpot) shows why.
  if ($status -ne 'PASS' -and $status -ne 'EMPTY') {
    $baselineNote = Get-BaselineNote -Baseline $script:HotspotBaselineMap -Module $Record.module -Class $Record.class
    $bothFail = Resolve-BothFailStatus -Baseline $script:HotspotBaselineMap -Module $Record.module `
      -Class $Record.class -Status $status -Failed $failed -Aborted $aborted -ContainersFailed $containersFailed
    if ($bothFail) { $status = $bothFail }
    if ($baselineNote) { $note = if ($note) { "$note | $baselineNote" } else { $baselineNote } }
    # Host-capability gating runs after the baseline reclassifier and can still
    # apply to a row the baseline left alone: it needs no reference VM, which
    # matters because no Windows full-suite HotSpot baseline has ever existed.
    $envGated = Resolve-EnvGatedStatus -Status $status -Stdout $Stdout `
      -Failed $failed -Aborted $aborted -ContainersFailed $containersFailed
    if ($envGated) {
      $status = $envGated
      $gateNote = 'env-gated: host cannot create symbolic links (needs SeCreateSymbolicLinkPrivilege or Developer Mode); stock HotSpot fails these same tests here'
      $note = if ($note) { "$gateNote | $note" } else { $gateNote }
      if ($note.Length -gt 240) { $note = $note.Substring(0, 240) }
    }
  }

  $line = @(
    $script:ResultIndex, $Record.module, $Record.class, $Vm, $(if ($Jit -eq 'off') { 'off' } else { 'on' }),
    $ExitCode, $status, (ConvertTo-InvariantString $Seconds), $tests, $failed, $aborted, $skipped, $containersFailed,
    $Record.outFile, $Record.errFile, $note
  ) -join "`t"
  Add-Content -Path $ResultPath -Value $line -Encoding ascii
  $script:ResultIndex++
  Write-Host ("  [{0}] {1,-9} {2,7:N1}s {3}.{4}" -f $script:EffectiveModeName, $status, $Seconds, $Record.module, $Record.class)
}

function Invoke-Mode {
  param([object[]]$Classes)
  $script:HotspotBaselineMap = Import-HotspotBaseline
  $jdk = Resolve-Jdk
  $javaBin = Join-Path $jdk 'bin'
  $java = @((Join-Path $javaBin 'java.exe'), (Join-Path $javaBin 'java')) | Where-Object { Test-Path $_ } | Select-Object -First 1
  if (-not $java) { Die "HotSpot java executable not found under: $javaBin" }
  $craton = ''
  if ($Vm -eq 'craton') {
    $craton = Resolve-CratonExe
    # Matches tomcat-suite-runner's craton knobs. CRATONVM_REAL_NET_SOCKETS in
    # particular is load-bearing here: without it, java.net.ServerSocket uses
    # the legacy synthetic layout whose field-slot mapping doesn't match the
    # real JDK-25 class (declaration order impl@0/created@1/bound@2/closed@3/
    # socketLock@4/options@5), so socketLock reads back null and any real
    # bind (Hazelcast, embedded servers, etc.) throws
    # "NullPointerException: Cannot enter synchronized block because
    # this.socketLock is null" — see docs/known-issues (reference_server_socket_gap
    # in memory) for the full history; this is a known, already-fixed-behind-
    # a-flag issue, not something to re-report as a new bug.
    $env:CRATONVM_REAL = 'net-sockets,aqs'
    $env:CRATONVM_THREADS = '-default-watchdog'
    $env:CRATONVM_JIT = 'rootsnap-cache'
    # Corrupt-`Value`-cell census -- see `-NoCorruptCellCensus`. Armed here so
    # every child cratonvm.exe inherits it; the per-class cost is one line of
    # stderr, and `decoded=0` is what makes a quiet run a MEASUREMENT rather
    # than an absence of one.
    if ($NoCorruptCellCensus) {
      $env:CRATONVM_DBG_CORRUPT_CELL = $null
    } else {
      $env:CRATONVM_DBG_CORRUPT_CELL = '1'
    }
  }

  $run = $RunName
  if (-not $run) { $run = Get-Date -Format 'yyyyMMdd-HHmmss' }
  $mode = $ModeName
  if (-not $mode) {
    if ($Vm -eq 'hotspot') { $mode = if ($Jit -eq 'off') { 'hotspot-xint' } else { 'hotspot-jit' } }
    else { $mode = "$Category-$(if ($Jit -eq 'off') { 'nojit' } else { 'jit' })" }
  }
  $script:EffectiveModeName = $mode

  $modeOut = Join-Path (Join-Path (Join-Path $script:WorkRoot 'results') $run) $mode
  New-Item -ItemType Directory -Force -Path $modeOut | Out-Null
  $results = Join-Path $modeOut 'results.tsv'
  if (-not (Test-Path $results)) {
    "index`tmodule`tclass`tvm`tjit`trc`tstatus`tseconds`ttests`tfailed`taborted`tskipped`tcontainersFailed`tstdoutLog`tstderrLog`tnote" | Set-Content -Path $results -Encoding ascii
  }
  $done = @{}
  foreach ($row in (Import-Csv -Path $results -Delimiter "`t")) { if ($row.class) { $done["$($row.module)`t$($row.class)"] = $true } }
  $todo = @($Classes | Where-Object { -not $done.ContainsKey("$($_.module)`t$($_.class)") })
  $script:ResultIndex = (Import-Csv -Path $results -Delimiter "`t").Count + 1

  Write-Info "mode=$mode vm=$Vm jit=$Jit category=$Category selected=$($Classes.Count) todo=$($todo.Count) parallel=$Parallel timeout=${TimeoutSec}s"
  if ($Vm -eq 'craton') { Write-Info "craton exe=$craton" }
  Write-Info "logs/results=$modeOut"

  $modeStarted = Get-Date
  $script:RunningRecords = New-Object System.Collections.Generic.List[object]

  function Drain-Running {
    $still = New-Object System.Collections.Generic.List[object]
    foreach ($record in $script:RunningRecords) {
      $elapsed = ((Get-Date) - $record.start).TotalSeconds
      if ($record.proc.HasExited) {
        $code = $record.proc.ExitCode
        $outputs = Read-ProcessOutputs $record
        Complete-ProcessRecord -Record $record -ResultPath $results -ExitCode $code -Seconds ([Math]::Round($elapsed, 3)) -Stdout $outputs.stdout -Stderr $outputs.stderr
        try { $record.proc.Dispose() } catch {}
      } elseif ($elapsed -ge $record.timeoutSec) {
        try { $record.proc.Kill($true) } catch { try { $record.proc.Kill() } catch {} }
        try { $record.proc.WaitForExit(5000) | Out-Null } catch {}
        $outputs = Read-ProcessOutputs $record
        Complete-ProcessRecord -Record $record -ResultPath $results -ExitCode 'TIMEOUT' -Seconds ([Math]::Round($elapsed, 3)) -Stdout $outputs.stdout -Stderr $outputs.stderr
        try { $record.proc.Dispose() } catch {}
      } else { $still.Add($record) }
    }
    $script:RunningRecords = $still
  }

  foreach ($classRow in $todo) {
    while ($script:RunningRecords.Count -ge $Parallel) { Drain-Running; if ($script:RunningRecords.Count -ge $Parallel) { Start-Sleep -Milliseconds 200 } }
    $launch = Get-LaunchSpec -ClassRow $classRow
    $classTimeoutSec = Get-EffectiveClassTimeoutSec -ClassRow $classRow -BaseTimeoutSec $TimeoutSec
    if ($classTimeoutSec -ne $TimeoutSec) { Write-Info "timeout override=${classTimeoutSec}s $($classRow.module).$($classRow.class)" }
    $script:RunningRecords.Add((New-ProcessRecord -ClassRow $classRow -ModeOut $modeOut -LaunchSpec $launch -ExePath $craton -JavaExe $java -JdkPath $jdk -NoJit:($Jit -eq 'off') -Timeout $classTimeoutSec))
  }
  while ($script:RunningRecords.Count -gt 0) { Drain-Running; if ($script:RunningRecords.Count -gt 0) { Start-Sleep -Milliseconds 200 } }
  Remove-Variable -Name RunningRecords -Scope Script -ErrorAction SilentlyContinue

  $elapsed = [Math]::Round(((Get-Date) - $modeStarted).TotalSeconds, 3)
  $rows = @(Import-Csv -Path $results -Delimiter "`t")
  $summaryPath = Join-Path $modeOut 'summary.md'
  $counts = $rows | Group-Object status | Sort-Object Name
  $classSeconds = 0.0
  foreach ($row in $rows) { $classSeconds += ConvertFrom-InvariantString ([string]$row.seconds) }

  $summary = New-Object System.Collections.Generic.List[string]
  $summary.Add("# Spring Boot suite result")
  $summary.Add(""); $summary.Add("- run: $run"); $summary.Add("- mode: $mode"); $summary.Add("- vm: $Vm"); $summary.Add("- jit: $Jit")
  $summary.Add("- category: $Category"); $summary.Add("- classes recorded: $($rows.Count)")
  $summary.Add("- wall seconds: $(ConvertTo-InvariantString $elapsed)"); $summary.Add("- summed class seconds: $(ConvertTo-InvariantString $classSeconds)")
  $summary.Add("- spring-boot root: $script:SpringBootDir")
  if ($Vm -eq 'craton') { $summary.Add("- craton exe: $craton") }
  $summary.Add(""); $summary.Add("## Status Counts")
  foreach ($group in $counts) { $summary.Add("- $($group.Name): $($group.Count)") }
  if ($Vm -eq 'craton' -and -not $NoCorruptCellCensus) {
    $cc = Get-CorruptCellCensus -LogDir (Join-Path $modeOut 'logs')
    $summary.Add(""); $summary.Add("## Corrupt Value cell census")
    $summary.Add("- logs scanned: $($cc.Logs)")
    $summary.Add("- logs carrying the census line: $($cc.Armed)")
    $summary.Add("- logs with NO census line: $($cc.Unarmed) (a class killed before the shutdown trailer -- HANG/TIMEOUT -- cannot print it)")
    $summary.Add("- cells decoded: $($cc.Decoded)")
    $summary.Add("- cells named (door or backstop): $($cc.Reported)")
    $summary.Add("- array-receiver field accesses refused: $($cc.ArrayReceiver) (a plain-object field read whose receiver was an ARRAY -- the same defect one step earlier, and a COUNT where `cells decoded` is a floor)")
    if ($cc.Classes.Count -gt 0) {
      $summary.Add(""); $summary.Add("### Classes that decoded a cell or strided an array")
      foreach ($c in $cc.Classes) { $summary.Add("- $c") }
    }
    # Loud on stdout too: a census buried in a file nobody opens is the same
    # silence this exists to remove.
    if ($cc.Decoded -gt 0 -or $cc.ArrayReceiver -gt 0) {
      Write-Info "CORRUPT-VALUE-CELL: $($cc.Decoded) decoded, $($cc.Reported) named, $($cc.ArrayReceiver) array-receiver refusals, in $($cc.Classes.Count) class(es) -- see $summaryPath"
      foreach ($c in $cc.Classes) { Write-Info "  corrupt-cell: $c" }
    } else {
      Write-Info "corrupt-cell census: 0 decoded, 0 array-receiver refusals across $($cc.Armed) of $($cc.Logs) logs (armed)"
    }
  }
  $summary.Add(""); $summary.Add("## Files"); $summary.Add("- results: $results"); $summary.Add("- logs: $(Join-Path $modeOut 'logs')")
  $summary | Set-Content -Path $summaryPath -Encoding ascii

  if ($Vm -eq 'hotspot') {
    $baselineDir = Join-Path $script:WorkRoot 'baseline'
    New-Item -ItemType Directory -Force -Path $baselineDir | Out-Null
    $baselineBase = "hotspot-baseline-$run"
    Copy-Item -Path $results -Destination (Join-Path $baselineDir "$baselineBase.tsv") -Force
    Copy-Item -Path $summaryPath -Destination (Join-Path $baselineDir "$baselineBase.md") -Force
    Copy-Item -Path $summaryPath -Destination (Join-Path $baselineDir 'hotspot-baseline-latest.md') -Force
    $latestCount = Merge-HotspotBaselineLatest -BaselineDir $baselineDir -ResultsPath $results
    Write-Info "baseline copied to $baselineDir\$baselineBase.tsv; hotspot-baseline-latest.tsv now covers $latestCount classes"
  }
  Write-Info "DONE mode=$mode wall=${elapsed}s summary=$summaryPath"
}

function Invoke-AllModes {
  $run = $RunName
  if (-not $run) { $run = Get-Date -Format 'yyyyMMdd-HHmmss' }
  $self = $PSCommandPath
  $psExe = Get-PowerShellExe
  $modes = @(
    @{ jit = 'on';  name = 'jit' },
    @{ jit = 'off'; name = 'nojit' }
  )
  $runRoot = Join-Path (Join-Path $script:WorkRoot 'results') $run
  New-Item -ItemType Directory -Force -Path $runRoot | Out-Null
  $children = @()
  foreach ($mode in $modes) {
    $log = Join-Path $runRoot "$($mode.name).console.log"
    $err = Join-Path $runRoot "$($mode.name).console.err.log"
    $args = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $self,
      '-Category', $Category, '-Jit', $mode.jit, '-Vm', 'craton',
      '-Start', $Start, '-Count', $Count, '-Parallel', $Parallel, '-TimeoutSec', $TimeoutSec,
      '-RunName', $run, '-ModeName', $mode.name, '-SpringBootRoot', $script:SpringBootDir,
      '-WorkDir', $script:WorkRoot, '-JdkHome', (Resolve-Jdk), '-MaxHeap', $MaxHeap)
    if ($Exe) { $args += @('-Exe', $Exe) }
    if ($RefCsv) { $args += @('-RefCsv', $RefCsv) }
    if ($HotspotBaseline) { $args += @('-HotspotBaseline', $HotspotBaseline) }
    if ($ClassList) { $args += @('-ClassList', $ClassList) }
    if ($CratonArgs.Count -gt 0) { foreach ($extra in $CratonArgs) { $args += @('-CratonArgs', $extra) } }
    Write-Info "launching $($mode.name) in background"
    $children += Start-RedirectedProcess -FilePath $psExe -Arguments $args -WorkingDirectory $script:RepoRoot -StdoutPath $log -StderrPath $err
  }
  $failedChildren = 0
  foreach ($child in $children) { $exitCode = Complete-RedirectedProcess $child; if ($exitCode -ne 0) { $failedChildren++ } }
  if ($failedChildren -gt 0) { Die "$failedChildren all-mode child process(es) failed; inspect $runRoot\*.console*.log" }
  Write-Info "ALL MODES DONE. Results under $runRoot"
}

$script:RepoRoot = Get-RepoRoot
if (-not $SpringBootRoot) {
  $appsRoot = Split-Path $PSScriptRoot -Parent
  $SpringBootRoot = Join-Path $appsRoot 'spring-boot'
}
$script:SpringBootDir = [System.IO.Path]::GetFullPath($SpringBootRoot)
if (-not (Test-Path $script:SpringBootDir)) { Die "Spring Boot root not found: $script:SpringBootDir" }
$script:SbRunnerDir = Join-Path $script:SpringBootDir 'sb-runner'
if (-not (Test-Path (Join-Path $script:SbRunnerDir 'SbRunner.class'))) { Die "missing SbRunner.class in $script:SbRunnerDir (javac SbRunner.java against the JUnit platform jars first)" }
# Existence was the only thing ever checked, so a `.class` compiled before the
# `.java` last changed kept running unnoticed -- and the fixture directory is
# NOT under version control, so it goes stale by default. That is why
# `SBRUNNER_ABORTED_DETAIL` was documented as landed and yet appeared in no run
# log: `SbRunner.class` in the fixture predated the change that emits it, and
# the missing line was then read as "the reason strings are not wired up".
# (Confirmed 2026-08-11 on the Azure fixture: `SbRunner$OutcomeReasonCollector.class`
# did not exist beside a `SbRunner.java` that declares it.)
#
# Refuse to run on a stale runner rather than produce logs missing the very
# evidence the harness now classifies on -- `Resolve-EnvGatedStatus` counts
# those lines.
foreach ($src in @('SbRunner.java', 'SbRunnerMethod.java')) {
  $srcPath = Join-Path $script:SbRunnerDir $src
  if (-not (Test-Path $srcPath)) { continue }
  $clsPath = Join-Path $script:SbRunnerDir ([System.IO.Path]::ChangeExtension($src, '.class'))
  if (-not (Test-Path $clsPath) -or
      (Get-Item $srcPath).LastWriteTimeUtc -gt (Get-Item $clsPath).LastWriteTimeUtc) {
    Die ("stale sb-runner: $src is newer than its .class in $script:SbRunnerDir. " +
         "Recompile before running, e.g.`n" +
         "  javac -cp `"<any module>/build/cratonvm-test-cp.txt contents>`" -d `"$script:SbRunnerDir`" `"$script:SbRunnerDir\*.java`"")
  }
}

if (-not $WorkDir) { $WorkDir = Join-Path $PSScriptRoot '.suite' }
$script:WorkRoot = [System.IO.Path]::GetFullPath($WorkDir)
New-Item -ItemType Directory -Force -Path $script:WorkRoot | Out-Null

if ($Start -lt 1) { Die "-Start is 1-based and must be >= 1" }
if ($Count -lt 0) { Die "-Count must be >= 0" }
if ($Parallel -lt 1) { Die "-Parallel must be >= 1" }
if ($TimeoutSec -lt 1) { Die "-TimeoutSec must be >= 1" }

