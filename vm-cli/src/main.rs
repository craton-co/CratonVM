/// - a separate value must be non-empty (libjli's `has_arg`), except the
///   class path's (`has_arg_any_len`: `-cp ""` boots);
/// - the scan ends at `-version`, `--version`, `-fullversion`,
///   `--full-version`, the help options and `-X` (the launcher returns
///   there: `-version --add-modules` prints the banner, rc 0), at the
///   program selector (a bare main class, a `-m` module, `-jar`) and at `--`.
///
/// `-jar` keeps this launcher's rule here (its next token is the jar); see
/// [`scan_launcher_missing_value_refusal_with`] for libjli's. Other value
/// options of this launcher (`-Xmx 256m`, ...) skip their value token as
/// [`insert_program_args_separator`] does. Pure. `run` calls
/// [`scan_launcher_missing_value_refusal_with`] since zt t16/tg7; this
/// spelling (both `-jar` rules off) is the tests'.
