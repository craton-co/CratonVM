/// zt t12/tg5: the JDK 25 `java` launcher's "requires ..." refusal for the
/// first launcher option of the leading section given without its value, or
/// `None`. The rules are libjli's `ParseArguments` / `GetOpt`, checked
/// against local 25.0.3 (rc 1, the one line on stderr, no usage text):
///
/// - a separate-value option takes the next token only when it does not
///   start with `-` (`IsOptionWithArgument`): `--add-modules -version` is a
///   missing value;
/// - `--add-modules`, `--add-exports`, `--add-opens`, `--add-reads`,
///   `--patch-module`, `--limit-modules`, `--enable-native-access`:
///   `Error: <opt> requires modules to be specified`;
/// - `--module-path`, `-p`, `--upgrade-module-path`:
///   `Error: <opt> requires module path specification`;
/// - `-cp`, `-classpath`, `--class-path`:
///   `Error: <opt> requires class path specification`;
/// - `-m`, `--module`, and `--module=` with nothing after the `=`:
///   `Error: <opt> requires module name`;
/// - the `=` forms with nothing after the `=` that `IsLongFormModuleOption`
///   lists (`--module-path=`, `--upgrade-module-path=`, `--add-modules=`,
///   `--enable-native-access=`, `--limit-modules=`, `--add-exports=`,
///   `--add-reads=`, `--patch-module=`): `Error: <opt>= requires modules to
///   be specified`. `--add-opens=` and `--class-path=` are not on that list:
///   `--class-path=` boots (an empty class path), and `--add-opens=` reaches
///   the boot layer, which refuses it
