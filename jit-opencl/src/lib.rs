//! Kernel IR → OpenCL C rendering for CratonVM GPU offload.
//!
//! Emits clean, standards-compliant OpenCL C (1.2 / 2.0 compatible) from
//! CratonVM's target-neutral Kernel IR ([`cratonvm_jit_cuda::kir`]).
//!
//! # Safety and Refusal
//!
//! Similar to `jit-hip`, [`Instr::Raw`] holds unlifted instructions and is refused
//! explicitly. All register variables are declared at the top of the kernel body.

use cratonvm_jit_cuda::emitter::{PtxKernel, PtxModule, PtxParamKind, RegKind};
use cratonvm_jit_cuda::kir::{
    BinOp, Cmp, CvtMode, FOp, Imm, Instr, Operand, ParamRef, PredOp, SpecialReg, Ty, UnOp,
};
use thiserror::Error;

pub mod target;
pub use target::OpenClTarget;

#[derive(Debug, Error)]
pub enum OpenClRenderError {
    /// An instruction that has no structured form yet.
    #[error("kernel `{kernel}` contains unlifted instruction with no OpenCL form yet: {text}")]
    Unstructured { kernel: String, text: String },

    /// An instruction that cannot be expressed on this target.
    #[error("kernel `{kernel}` cannot be lowered for OpenCL target {target}: {why}")]
    Unsupported {
        kernel: String,
        target: String,
        why: String,
    },
}

/// A module rendered as OpenCL C source.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct OpenClModule {
    /// OpenCL C source text for `clCreateProgramWithSource`.
    pub source: String,
    /// The entry-point kernel names in `source`, in module order.
    pub kernel_names: Vec<String>,
}

/// Render `module` as OpenCL C for `target`.
pub fn render_module(
    module: &PtxModule,
    target: &OpenClTarget,
) -> Result<OpenClModule, OpenClRenderError> {
    let mut source = String::with_capacity(4096);
    source.push_str(&format!(
        "// Generated by CratonVM for OpenCL {}.{} ({})\n\n",
        target.opencl_version.0, target.opencl_version.1, target.device_name
    ));

    let mut has_fp64 = false;
    let mut has_int64_atomics = false;
    for k in &module.kernels {
        for p in &k.params {
            if matches!(p.kind, PtxParamKind::F64) {
                has_fp64 = true;
            }
        }
        for d in &k.reg_decls {
            if matches!(d.kind, RegKind::F64) {
                has_fp64 = true;
            }
        }
        for instr in k.code.code() {
            if let Instr::RedAdd { ty, .. } = instr {
                if matches!(ty, Ty::S64 | Ty::U64 | Ty::B64) {
                    has_int64_atomics = true;
                }
            }
        }
    }

    if has_fp64 {
        source.push_str("#pragma OPENCL EXTENSION cl_khr_fp64 : enable\n");
    }
    if has_int64_atomics {
        source.push_str("#pragma OPENCL EXTENSION cl_khr_int64_base_atomics : enable\n");
    }
    if has_fp64 || has_int64_atomics {
        source.push('\n');
    }

    let mut kernel_names = Vec::with_capacity(module.kernels.len());
    let mut kernels = String::new();
    for k in &module.kernels {
        render_kernel(k, target, &mut kernels)?;
        kernel_names.push(k.name.clone());
        kernels.push('\n');
    }

    if kernels.contains("craton_f2") || kernels.contains("craton_d2") {
        source.push_str(CVT_PRELUDE);
    }
    source.push_str(&kernels);

    Ok(OpenClModule {
        source,
        kernel_names,
    })
}

fn reg(name: &str) -> String {
    format!("v{}", name.trim_start_matches('%'))
}

fn reg_opencl_ty(kind: RegKind) -> &'static str {
    match kind {
        RegKind::U32 => "uint",
        RegKind::U64 => "__global char*",
        RegKind::S32 => "int",
        RegKind::S64 => "long",
        RegKind::F32 => "float",
        RegKind::F64 => "double",
        RegKind::Pred => "bool",
        RegKind::B16 => "ushort",
    }
}

fn is_float_reg(name: &str) -> bool {
    let n = name.trim_start_matches('%');
    n.starts_with("fd") || n.starts_with('f')
}

fn render_kernel(
    k: &PtxKernel,
    target: &OpenClTarget,
    out: &mut String,
) -> Result<(), OpenClRenderError> {
    out.push_str(&format!("__kernel void {}(\n", k.name));
    for (i, p) in k.params.iter().enumerate() {
        let comma = if i + 1 == k.params.len() { "" } else { "," };
        let ty = match p.kind {
            PtxParamKind::U64Ptr => "__global void*",
            PtxParamKind::S32 => "int",
            PtxParamKind::S64 => "long",
            PtxParamKind::F32 => "float",
            PtxParamKind::F64 => "double",
        };
        out.push_str(&format!("    {ty} {}{comma}\n", p.name));
    }
    out.push_str(") {\n");

    for d in &k.reg_decls {
        if d.count == 0 {
            continue;
        }
        let ty = reg_opencl_ty(d.kind);
        let (base, star) = match ty.strip_suffix('*') {
            Some(base) => (base, "*"),
            None => (ty, ""),
        };
        let names: Vec<String> = (0..d.count)
            .map(|i| format!("{star}v{}{i}", reg_kind_prefix(d.kind)))
            .collect();
        out.push_str(&format!("    {base} {};\n", names.join(", ")));
    }
    out.push('\n');

    for instr in k.code.code() {
        render_instr(instr, k, target, out)?;
    }
    out.push_str("}\n");
    Ok(())
}

fn reg_kind_prefix(kind: RegKind) -> &'static str {
    match kind {
        RegKind::U32 => "ru",
        RegKind::U64 => "rd",
        RegKind::S32 => "r",
        RegKind::S64 => "rl",
        RegKind::F32 => "f",
        RegKind::F64 => "fd",
        RegKind::Pred => "p",
        RegKind::B16 => "rs",
    }
}

fn opencl_ty(ty: Ty) -> &'static str {
    match ty {
        Ty::S8 => "char",
        Ty::U8 => "uchar",
        Ty::S16 => "short",
        Ty::U16 | Ty::B16 => "ushort",
        Ty::S32 => "int",
        Ty::U32 | Ty::B32 => "uint",
        Ty::S64 => "long",
        Ty::U64 | Ty::B64 => "ulong",
        Ty::F16 => "half",
        Ty::F32 => "float",
        Ty::F64 => "double",
    }
}

fn operand(o: &Operand) -> String {
    match o {
        Operand::Reg(r) => reg(r),
        Operand::Imm(i) => imm(i),
    }
}

fn imm(i: &Imm) -> String {
    match i {
        Imm::Int(v) => format!("{v}"),
        Imm::Hex(h) => h.clone(),
        Imm::F32(h) => format!("as_float(0x{}u)", &h[2..]),
        Imm::F64(h) => format!("as_double(0x{}UL)", &h[2..]),
    }
}

fn render_instr(
    instr: &Instr,
    k: &PtxKernel,
    target: &OpenClTarget,
    out: &mut String,
) -> Result<(), OpenClRenderError> {
    let unsupported = |why: &str| OpenClRenderError::Unsupported {
        kernel: k.name.clone(),
        target: target.device_name.clone(),
        why: why.to_string(),
    };
    match instr {
        Instr::Raw(text) => {
            return Err(OpenClRenderError::Unstructured {
                kernel: k.name.clone(),
                text: text.trim().to_string(),
            });
        }
        Instr::ReadSpecial { dst, which } => {
            let expr = match which {
                SpecialReg::ThreadIdxX => "((uint)get_local_id(0))",
                SpecialReg::BlockDimX => "((uint)get_local_size(0))",
                SpecialReg::BlockIdxX => "((uint)get_group_id(0))",
                SpecialReg::LaneId => {
                    let w = target.warp_size;
                    return {
                        out.push_str(&format!(
                            "    {} = ((uint)(get_local_id(0) % {w}));\n",
                            reg(dst)
                        ));
                        Ok(())
                    };
                }
            };
            out.push_str(&format!("    {} = {expr};\n", reg(dst)));
        }
        Instr::Label(name) => {
            out.push_str(&format!("{name}: ;\n"));
        }
        Instr::Bra { target: t, pred } => match pred {
            None => out.push_str(&format!("    goto {t};\n")),
            Some(p) => {
                let bang = if p.negated { "!" } else { "" };
                out.push_str(&format!("    if ({bang}{}) goto {t};\n", reg(&p.reg)));
            }
        },
        Instr::Ret => out.push_str("    return;\n"),
        Instr::LdParam { dst, ty, param } => {
            let name = param.name();
            match param {
                ParamRef::ArrayPtr(_) | ParamRef::FailureFlag | ParamRef::RetPtr => {
                    out.push_str(&format!("    {} = (__global char*){name};\n", reg(dst)));
                }
                _ => {
                    out.push_str(&format!("    {} = ({}){name};\n", reg(dst), opencl_ty(*ty)));
                }
            }
        }
        Instr::MovImm { dst, ty, imm } => {
            let value = self::imm(imm);
            if matches!(imm, Imm::F32(_) | Imm::F64(_)) {
                out.push_str(&format!("    {} = {value};\n", reg(dst)));
            } else {
                out.push_str(&format!("    {} = ({}){value};\n", reg(dst), opencl_ty(*ty)));
            }
        }
        Instr::Bitcast { dst, src, width } => {
            if is_float_reg(dst) || is_float_reg(src) {
                let as_ty = match opencl_ty_of_reg(dst) {
                    "float" => "as_float",
                    "double" => "as_double",
                    "uint" => "as_uint",
                    "ulong" => "as_ulong",
                    "int" => "as_int",
                    "long" => "as_long",
                    other => other,
                };
                out.push_str(&format!("    {} = {}({});\n", reg(dst), as_ty, reg(src)));
                return Ok(());
            }
            debug_assert!(*width == 32 || *width == 64);
            out.push_str(&format!(
                "    {} = ({}){};\n",
                reg(dst),
                opencl_ty_of_reg(dst),
                reg(src)
            ));
        }
        Instr::Mov { dst, ty, src } => {
            out.push_str(&format!(
                "    {} = ({}){};\n",
                reg(dst),
                opencl_ty(*ty),
                reg(src)
            ));
        }
        Instr::Bin {
            op: op @ (BinOp::Shl | BinOp::Shr),
            ty,
            dst,
            a,
            b,
        } => {
            let Some(bits) = int_bits(*ty) else {
                return Err(unsupported("shift of non-32/64 bit type"));
            };
            let t = opencl_ty(*ty);
            let ut = unsigned_of(bits);
            let (a, n) = (operand(a), operand(b));
            let expr = match (op, ty) {
                (BinOp::Shl, _) => {
                    format!("(({ut})({n}) >= {bits}u) ? ({t})0 : ({t})(({ut}){a} << ({ut})({n}))")
                }
                (_, Ty::S32 | Ty::S64) => {
                    format!(
                        "({t})(({t}){a} >> (({ut})({n}) >= {bits}u ? {} : ({ut})({n})))",
                        bits - 1
                    )
                }
                _ => format!("(({ut})({n}) >= {bits}u) ? ({t})0 : ({t})(({ut}){a} >> ({ut})({n}))"),
            };
            out.push_str(&format!(
                "    {} = ({})({expr});\n",
                reg(dst),
                opencl_ty_of_reg(dst)
            ));
        }
        Instr::Bin { op, ty, dst, a, b } => {
            out.push_str(&format!(
                "    {} = ({})(({}){} {} ({}){});\n",
                reg(dst),
                opencl_ty_of_reg(dst),
                opencl_ty(*ty),
                operand(a),
                bin_op_symbol(*op),
                opencl_ty(*ty),
                operand(b)
            ));
        }
        Instr::MadLo { ty, dst, a, b, c } => {
            if matches!(ty, Ty::F32 | Ty::F64) {
                return Err(unsupported("mad on floating-point types"));
            }
            out.push_str(&format!(
                "    {} = ({})(({}){} * ({}){} + ({}){});\n",
                reg(dst),
                opencl_ty_of_reg(dst),
                opencl_ty(*ty),
                reg(a),
                opencl_ty(*ty),
                reg(b),
                opencl_ty(*ty),
                reg(c)
            ));
        }
        Instr::ElementAddr {
            dst,
            base,
            index,
            elem_size,
            ..
        } => {
            out.push_str(&format!(
                "    {} = {} + (long){} * {};\n",
                reg(dst),
                reg(base),
                reg(index),
                elem_size
            ));
        }
        Instr::LdGlobal { dst, ty, addr } => {
            out.push_str(&format!(
                "    {} = ({})*(__global {}*){};\n",
                reg(dst),
                opencl_ty_of_reg(dst),
                opencl_ty(*ty),
                reg(addr)
            ));
        }
        Instr::StGlobal { ty, addr, value } => {
            out.push_str(&format!(
                "    *(__global {}*){} = ({}){};\n",
                opencl_ty(*ty),
                reg(addr),
                opencl_ty(*ty),
                operand(value)
            ));
        }
        Instr::Setp { cmp, ty, dst, a, b } => {
            let (t, a, b) = (opencl_ty(*ty), operand(a), operand(b));
            let float = matches!(ty, Ty::F32 | Ty::F64);
            let expr = match cmp {
                Cmp::Nan => format!("isnan(({t}){a}) || isnan(({t}){b})"),
                Cmp::Ne if float => format!("(({t}){a} < ({t}){b}) || (({t}){a} > ({t}){b})"),
                _ => format!("({t}){a} {} ({t}){b}", cmp_symbol(*cmp)),
            };
            out.push_str(&format!("    {} = ({expr});\n", reg(dst)));
        }
        Instr::FArith { op, ty, dst, a, b } => {
            out.push_str(&format!(
                "    {} = ({})(({}){} {} ({}){});\n",
                reg(dst),
                opencl_ty_of_reg(dst),
                opencl_ty(*ty),
                operand(a),
                fop_symbol(*op),
                opencl_ty(*ty),
                operand(b)
            ));
        }
        Instr::IDivRem { rem, ty, dst, a, b } => {
            let Some(bits) = int_bits(*ty) else {
                return Err(unsupported("integer div/rem of unsupported width"));
            };
            let (t, ut) = (opencl_ty(*ty), unsigned_of(bits));
            let (a, b) = (operand(a), operand(b));
            let signed = matches!(ty, Ty::S32 | Ty::S64);
            let expr = match (signed, rem) {
                (true, false) => {
                    format!("(({t}){b} == -1) ? ({t})(0 - ({ut}){a}) : ({t})(({t}){a} / ({t}){b})")
                }
                (true, true) => format!("(({t}){b} == -1) ? ({t})0 : ({t})(({t}){a} % ({t}){b})"),
                (false, false) => format!("({t})(({t}){a} / ({t}){b})"),
                (false, true) => format!("({t})(({t}){a} % ({t}){b})"),
            };
            out.push_str(&format!(
                "    {} = ({})({expr});\n",
                reg(dst),
                opencl_ty_of_reg(dst)
            ));
        }
        Instr::Unary { op, ty, dst, src } => {
            let t = opencl_ty(*ty);
            let src = operand(src);
            let float = matches!(ty, Ty::F32 | Ty::F64);
            let expr = match (op, float) {
                (UnOp::Neg, true) => format!("-({t}){src}"),
                (UnOp::Neg, false) => format!("({t})(0 - ({t}){src})"),
                (UnOp::Abs, true) => format!("fabs(({t}){src})"),
                (UnOp::Abs, false) => {
                    format!("(({t}){src} < 0) ? ({t})(0 - ({t}){src}) : ({t}){src}")
                }
                (UnOp::Sqrt, _) => format!("sqrt(({t}){src})"),
                (UnOp::Ex2Approx, _) => format!("exp2(({t}){src})"),
            };
            out.push_str(&format!(
                "    {} = ({})({expr});\n",
                reg(dst),
                opencl_ty_of_reg(dst)
            ));
        }
        Instr::Fma { ty, dst, a, b, c } => {
            let t = opencl_ty(*ty);
            out.push_str(&format!(
                "    {} = ({})(fma(({t}){}, ({t}){}, ({t}){}));\n",
                reg(dst),
                opencl_ty_of_reg(dst),
                operand(a),
                operand(b),
                operand(c)
            ));
        }
        Instr::Cvt {
            mode,
            dst_ty,
            src_ty,
            dst,
            src,
        } => {
            let expr = cvt_expr(*mode, *dst_ty, *src_ty, &reg(src)).ok_or_else(|| {
                unsupported("a conversion between these types has no OpenCL C spelling yet")
            })?;
            out.push_str(&format!(
                "    {} = ({})({expr});\n",
                reg(dst),
                opencl_ty_of_reg(dst)
            ));
        }
        Instr::Selp {
            ty,
            dst,
            a,
            b,
            pred,
        } => {
            let t = opencl_ty(*ty);
            out.push_str(&format!(
                "    {} = ({})({} ? ({t}){} : ({t}){});\n",
                reg(dst),
                opencl_ty_of_reg(dst),
                reg(pred),
                operand(a),
                operand(b)
            ));
        }
        Instr::PredBin { op, dst, a, b } => {
            let o = match op {
                PredOp::And => "&&",
                PredOp::Or => "||",
            };
            out.push_str(&format!("    {} = {} {o} {};\n", reg(dst), reg(a), reg(b)));
        }
        Instr::RedAdd { ty, addr, value } => {
            match ty {
                Ty::S32 | Ty::U32 | Ty::B32 => {
                    out.push_str(&format!(
                        "    atomic_add((__global volatile int*){}, (int){});\n",
                        reg(addr),
                        reg(value)
                    ));
                }
                Ty::S64 | Ty::U64 | Ty::B64 => {
                    out.push_str(&format!(
                        "    atom_add((__global volatile long*){}, (long){});\n",
                        reg(addr),
                        reg(value)
                    ));
                }
                _ => return Err(unsupported("atomic add of float or sub-word type")),
            }
        }
        Instr::Guarded { pred, inner } => {
            let mut stmt = String::new();
            render_instr(inner, k, target, &mut stmt)?;
            let bang = if pred.negated { "!" } else { "" };
            out.push_str(&format!(
                "    if ({bang}{}) {{ {} }}\n",
                reg(&pred.reg),
                stmt.trim()
            ));
        }
        Instr::WarpFold { acc, ty, .. } => {
            // In OpenCL, fold can be performed if sub-groups are available or loop
            let w = target.warp_size;
            let t = opencl_ty(*ty);
            let a = reg(acc);
            // OpenCL sub_group_shuffle_down available in cl_khr_subgroups or OpenCL 2.0+
            out.push_str(&format!(
                "    for (int craton_o = {}; craton_o > 0; craton_o >>= 1) {{ {a} = ({t})({a} + sub_group_shuffle_down({a}, craton_o)); }}\n",
                w / 2
            ));
        }
    }
    Ok(())
}

fn bin_op_symbol(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",
        BinOp::Sub => "-",
        BinOp::Mul => "*",
        BinOp::And => "&",
        BinOp::Or => "|",
        BinOp::Xor => "^",
        BinOp::Shl => "<<",
        BinOp::Shr => ">>",
    }
}

fn fop_symbol(op: FOp) -> &'static str {
    match op {
        FOp::Add => "+",
        FOp::Sub => "-",
        FOp::Mul => "*",
        FOp::Div => "/",
    }
}

fn cmp_symbol(cmp: Cmp) -> &'static str {
    match cmp {
        Cmp::Eq => "==",
        Cmp::Ne => "!=",
        Cmp::Lt => "<",
        Cmp::Le => "<=",
        Cmp::Gt => ">",
        Cmp::Ge => ">=",
        Cmp::Nan => "==",
    }
}

fn int_bits(ty: Ty) -> Option<u32> {
    match ty {
        Ty::S32 | Ty::U32 | Ty::B32 => Some(32),
        Ty::S64 | Ty::U64 | Ty::B64 => Some(64),
        _ => None,
    }
}

fn unsigned_of(bits: u32) -> &'static str {
    if bits == 64 {
        "ulong"
    } else {
        "uint"
    }
}

fn cvt_expr(mode: CvtMode, dst: Ty, src: Ty, s: &str) -> Option<String> {
    let float = |t: Ty| matches!(t, Ty::F32 | Ty::F64);
    Some(match (float(dst), float(src)) {
        (true, true) if mode == CvtMode::Rzi => {
            if dst != src {
                return None;
            }
            format!("trunc(({}){s})", opencl_ty(dst))
        }
        (true, true) | (true, false) => format!("({})({}){s}", opencl_ty(dst), opencl_ty(src)),
        (false, true) => {
            let f = match (dst, src) {
                (Ty::S32, Ty::F32) => "craton_f2i",
                (Ty::S32, Ty::F64) => "craton_d2i",
                (Ty::S64, Ty::F32) => "craton_f2l",
                (Ty::S64, Ty::F64) => "craton_d2l",
                _ => return None,
            };
            format!("{f}({s})")
        }
        (false, false) => format!("({})({}){s}", opencl_ty(dst), opencl_ty(src)),
    })
}

const CVT_PRELUDE: &str = "\
static inline int craton_f2i(float f) {
    return isnan(f) ? 0 : f >= 2147483648.0f ? 2147483647 : f <= -2147483648.0f ? (-2147483647 - 1) : (int)f;
}
static inline int craton_d2i(double f) {
    return isnan(f) ? 0 : f >= 2147483647.0 ? 2147483647 : f <= -2147483648.0 ? (-2147483647 - 1) : (int)f;
}
static inline long craton_f2l(float f) {
    return isnan(f) ? 0 : f >= 9223372036854775808.0f ? 9223372036854775807L : f <= -9223372036854775808.0f ? (-9223372036854775807L - 1) : (long)f;
}
static inline long craton_d2l(double f) {
    return isnan(f) ? 0 : f >= 9223372036854775808.0 ? 9223372036854775807L : f <= -9223372036854775808.0 ? (-9223372036854775807L - 1) : (long)f;
}

";

fn opencl_ty_of_reg(name: &str) -> &'static str {
    let n = name.trim_start_matches('%');
    for (prefix, kind) in [
        ("rd", RegKind::U64),
        ("rl", RegKind::S64),
        ("rs", RegKind::B16),
        ("ru", RegKind::U32),
        ("fd", RegKind::F64),
        ("r", RegKind::S32),
        ("f", RegKind::F32),
        ("p", RegKind::Pred),
    ] {
        if n.starts_with(prefix) {
            return reg_opencl_ty(kind);
        }
    }
    "int"
}

