//! Kernel IR → HIP C++, for AMD devices.
//!
//! The second rendering target. `cratonvm_jit_cuda` owns the Java
//! bytecode front end and renders PTX; this crate renders the same
//! instruction list ([`cratonvm_jit_cuda::kir`]) as HIP C++ for
//! `hiprtc` to compile. There is exactly one front end, one analyzer
//! and one set of admission rules — a second would be a third layer
//! that has to agree with the other two by hand, which
//! `docs/gpu/lowering-architecture.md` is largely a catalogue of the
//! cost of.
//!
//! # Refusal is the default
//!
//! [`Instr::Raw`] holds a line of PTX text that has not been converted
//! to a structured instruction yet, and this renderer **refuses** it
//! rather than attempting a translation. That is deliberate and it is
//! the crate's main safety property: a guessed translation of an
//! unrecognised mnemonic does not crash, does not trip the deopt flag
//! and does not fall back to the CPU — it returns a plausible wrong
//! answer, which is this subsystem's characteristic failure mode.
//!
//! So the set of kernels this can render is exactly the set whose every
//! instruction is structured, it grows as emission sites are converted
//! in `jit-cuda`, and a kernel outside it is reported by name and runs
//! on the CPU.
//!
//! # Floating point
//!
//! Nothing in the emitted source may invite contraction. The host side
//! passes `-ffp-contract=off` to hiprtc, and this renderer emits
//! `#pragma clang fp contract(off)` as well: the flag guards against a
//! caller dropping it and the pragma guards against the default
//! changing. clang's HIP toolchain defaults to
//! `fast-honor-pragmas`, which fuses `a*b + c` into a single-rounded
//! FMA where JLS §15.17.1/§15.18.2 require the product rounded to
//! `float` first. `Emitter::binop_f32` in `jit-cuda` records the same
//! defect being found and fixed on the PTX side.
//!
//! # Declare up front, then only assign
//!
//! Every register is declared, uninitialised, in one block at the top
//! of the kernel. This is not style: in C++ a `goto` that jumps into
//! the scope of a variable with an initializer, bypassing it, is
//! ill-formed — clang rejects it with "cannot jump from this goto
//! statement to its label ... crosses initialization". The emitter's
//! control flow branches both ways across the whole body, so declaring
//! at point of use would be a hard error on the first branching kernel.
//! The PTX side already declares its registers up front for its own
//! reasons, so the IR hands this over for free.

use cratonvm_jit_cuda::emitter::{PtxKernel, PtxModule, PtxParamKind, RegKind};
use cratonvm_jit_cuda::kir::{BinOp, Cmp, Imm, Instr, Operand, ParamRef, SpecialReg, Ty};
use thiserror::Error;

pub mod target;

pub use target::{wavefront_for_arch, HipTarget};

#[derive(Debug, Error)]
pub enum HipRenderError {
    /// An instruction that has no structured form yet.
    ///
    /// Carries the PTX text so the message names what is missing rather
    /// than only that something is. The fix is always the same: convert
    /// that emission site in `jit-cuda`.
    #[error("kernel `{kernel}` contains PTX with no HIP form yet: {text}")]
    Unstructured { kernel: String, text: String },

    /// An instruction that is structured but cannot be expressed on
    /// this target, or not on this device.
    #[error("kernel `{kernel}` cannot be lowered for {arch}: {why}")]
    Unsupported {
        kernel: String,
        arch: String,
        why: String,
    },
}

/// A kernel rendered for one `gfx` architecture.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HipModule {
    /// The HIP C++ source, for `hiprtc`.
    pub source: String,
    /// `hipDeviceProp_t::gcnArchName` verbatim, for `--offload-arch=`.
    pub offload_arch: String,
    /// The entry-point names in `source`, in module order.
    pub kernel_names: Vec<String>,
}

/// Render `module` as HIP C++ for `target`.
pub fn render_module(module: &PtxModule, target: &HipTarget) -> Result<HipModule, HipRenderError> {
    let mut source = String::with_capacity(4096);
    source.push_str(&format!(
        "// Generated by CratonVM for --offload-arch={} (wavefront {})\n",
        target.gcn_arch_name, target.wavefront_size
    ));
    // Belt and braces with the host's `-ffp-contract=off`; see the
    // module docs for why one is not enough.
    source.push_str("#pragma clang fp contract(off)\n\n");
    let mut kernel_names = Vec::with_capacity(module.kernels.len());
    for k in &module.kernels {
        render_kernel(k, target, &mut source)?;
        kernel_names.push(k.name.clone());
        source.push('\n');
    }
    Ok(HipModule {
        source,
        offload_arch: target.gcn_arch_name.clone(),
        kernel_names,
    })
}

/// A register's C++ identifier.
///
/// Two changes from the PTX name, both forced:
///
/// 1. `%` is not a legal C++ identifier character.
/// 2. Dropping it alone is not enough. PTX tells a predicate register
///    `%p1` apart from a scalar kernel parameter `p1` by the sigil, and
///    C++ has no sigil — so `%p1` and `p1` become the same name and the
///    kernel fails to compile with "redefinition of formal parameter".
///    Only the predicate class collides today, but prefixing every
///    class is what makes that structural rather than a coincidence of
///    which letters the pools happen to use.
///
/// `v` is safe because every kernel parameter is named by
/// `lowering::build_param_list`, and none of `p<N>`, `p<N>_ptr`,
/// `p<N>_len`, `failure_flag` or `tid_base` starts with it.
fn reg(name: &str) -> String {
    format!("v{}", name.trim_start_matches('%'))
}

/// The C++ declaration type for a register class.
///
/// `RegKind::U64` becomes `char*`, not an integer. Every 64-bit
/// register this emitter produces holds an address — a parameter base
/// or an element address — and a byte pointer is what makes
/// `ElementAddr`'s scaled offset express itself without knowing the
/// element type. The load and store cast to the width they want.
fn reg_cpp_ty(kind: RegKind) -> &'static str {
    match kind {
        RegKind::U32 => "unsigned int",
        RegKind::U64 => "char*",
        RegKind::S32 => "int",
        RegKind::S64 => "long long",
        RegKind::F32 => "float",
        RegKind::F64 => "double",
        RegKind::Pred => "bool",
        RegKind::B16 => "unsigned short",
    }
}

/// Whether a register name belongs to a floating-point class.
///
/// Read off the name's prefix, which is how the IR carries register
/// identity during the migration. Used to refuse a float bit-cast: a
/// same-width integer reinterpret is a plain C++ cast, but
/// `float`↔`unsigned int` is not, and rendering one as the other would
/// silently reinterpret a bit pattern as a number.
fn is_float_reg(name: &str) -> bool {
    let n = name.trim_start_matches('%');
    n.starts_with("fd") || n.starts_with('f')
}

fn render_kernel(
    k: &PtxKernel,
    target: &HipTarget,
    out: &mut String,
) -> Result<(), HipRenderError> {
    // `extern "C"` is mandatory, not stylistic. A `__global__` function
    // with C++ linkage gets a mangled symbol, and the host resolves the
    // entry point by name through `hipModuleGetFunction` -- so without
    // it the load fails with "kernel not found" on a kernel that is
    // plainly there.
    out.push_str(&format!("extern \"C\" __global__ void {}(\n", k.name));
    for (i, p) in k.params.iter().enumerate() {
        let comma = if i + 1 == k.params.len() { "" } else { "," };
        let ty = match p.kind {
            // Every pointer parameter is `void*`. The element type is
            // recovered at each access from the load/store width, which
            // means this renderer needs no map from parameter index to
            // Java element type -- one less thing to keep in agreement.
            PtxParamKind::U64Ptr => "void*",
            PtxParamKind::S32 => "int",
            PtxParamKind::S64 => "long long",
            PtxParamKind::F32 => "float",
            PtxParamKind::F64 => "double",
        };
        out.push_str(&format!("    {ty} {}{comma}\n", p.name));
    }
    out.push_str(") {\n");

    // Declared up front and only assigned afterwards -- see the module
    // docs for why `goto` makes this mandatory rather than tidy.
    for d in &k.reg_decls {
        if d.count == 0 {
            continue;
        }
        let ty = reg_cpp_ty(d.kind);
        // `*` binds to the DECLARATOR in C++, not to the type:
        // `char* a, b;` declares `b` as a plain `char`. A pointer class
        // therefore repeats the star on every name -- `char *rd0, *rd1`
        // -- which is the only spelling that means what it looks like.
        // The first version of this renderer got this wrong and emitted
        // kernels in which every 64-bit register but the first was a
        // single byte.
        let (base, star) = match ty.strip_suffix('*') {
            Some(base) => (base, "*"),
            None => (ty, ""),
        };
        let names: Vec<String> = (0..d.count)
            .map(|i| format!("{star}v{}{i}", reg_kind_prefix(d.kind)))
            .collect();
        out.push_str(&format!("    {base} {};\n", names.join(", ")));
    }
    out.push('\n');

    for instr in k.code.code() {
        render_instr(instr, k, target, out)?;
    }
    out.push_str("}\n");
    Ok(())
}

/// The register-name prefix for a class.
///
/// A duplicate of `RegKind::prefix` in `jit-cuda`, which is private.
/// Kept in agreement by `reg_prefixes_match_the_emitters`, which
/// renders a kernel and checks every declared name against the names
/// the instructions use -- a copied table that nothing compares is the
/// failure this workspace has the most of.
fn reg_kind_prefix(kind: RegKind) -> &'static str {
    match kind {
        RegKind::U32 => "ru",
        RegKind::U64 => "rd",
        RegKind::S32 => "r",
        RegKind::S64 => "rl",
        RegKind::F32 => "f",
        RegKind::F64 => "fd",
        RegKind::Pred => "p",
        RegKind::B16 => "rs",
    }
}

fn operand(o: &Operand) -> String {
    match o {
        Operand::Reg(r) => reg(r).to_string(),
        Operand::Imm(i) => match i {
            Imm::Int(v) => format!("{v}"),
            Imm::Hex(h) => h.clone(),
        },
    }
}

fn render_instr(
    instr: &Instr,
    k: &PtxKernel,
    target: &HipTarget,
    out: &mut String,
) -> Result<(), HipRenderError> {
    let unsupported = |why: &str| HipRenderError::Unsupported {
        kernel: k.name.clone(),
        arch: target.gcn_arch_name.clone(),
        why: why.to_string(),
    };
    match instr {
        Instr::Raw(text) => {
            return Err(HipRenderError::Unstructured {
                kernel: k.name.clone(),
                text: text.trim().to_string(),
            })
        }
        Instr::ReadSpecial { dst, which } => {
            out.push_str(&format!("    {} = {};\n", reg(dst), which.cpp()));
        }
        Instr::Label(name) => {
            // The trailing `;` is required: before C++23 a labeled
            // statement needs a statement, and `L_done: }` is
            // ill-formed. Every label here is immediately before either
            // a `return` or the closing brace.
            out.push_str(&format!("{name}: ;\n"));
        }
        Instr::Bra { target: t, pred } => match pred {
            None => out.push_str(&format!("    goto {t};\n")),
            Some(p) => {
                let bang = if p.negated { "!" } else { "" };
                out.push_str(&format!("    if ({bang}{}) goto {t};\n", reg(&p.reg)));
            }
        },
        Instr::Ret => out.push_str("    return;\n"),
        Instr::LdParam { dst, ty, param } => {
            let name = param.name();
            match param {
                ParamRef::ArrayPtr(_) | ParamRef::FailureFlag => {
                    out.push_str(&format!("    {} = (char*){name};\n", reg(dst)));
                }
                _ => {
                    out.push_str(&format!("    {} = ({}){name};\n", reg(dst), ty.cpp()));
                }
            }
        }
        Instr::MovImm { dst, ty, imm } => {
            out.push_str(&format!(
                "    {} = ({}){};\n",
                reg(dst),
                ty.cpp(),
                match imm {
                    Imm::Int(v) => format!("{v}"),
                    Imm::Hex(h) => h.clone(),
                }
            ));
        }
        Instr::Bitcast { dst, src, width } => {
            // A same-width INTEGER reinterpret is a plain cast. A float
            // one is not -- `(unsigned int)f` converts the value, it
            // does not reinterpret the bits -- and rendering it as a
            // cast would produce a kernel that compiles, runs, and is
            // wrong. Refuse; `__builtin_bit_cast` is the right answer
            // and is a separate change with its own test.
            if is_float_reg(dst) || is_float_reg(src) {
                return Err(unsupported(
                    "a floating-point bit-cast needs __builtin_bit_cast, not a value cast",
                ));
            }
            // The width is carried for the PTX spelling (`mov.b32` /
            // `mov.b64`); here the destination register's own class is
            // the type to cast to, and the two always agree because a
            // reinterpret does not change width.
            debug_assert!(
                *width == 32 || *width == 64,
                "unexpected bitcast width {width}"
            );
            out.push_str(&format!(
                "    {} = ({}){};\n",
                reg(dst),
                cpp_ty_of_reg(dst),
                reg(src)
            ));
        }
        Instr::Mov { dst, ty, src } => {
            out.push_str(&format!("    {} = ({}){};\n", reg(dst), ty.cpp(), reg(src)));
        }
        Instr::Bin { op, ty, dst, a, b } => {
            // Both operands are cast to the OPERATION's type, which is
            // what makes signedness explicit: PTX lets `add.s32` read
            // registers declared `.u32`, and C++ would otherwise apply
            // its own promotion rules to the same pair.
            out.push_str(&format!(
                "    {} = ({})(({}){} {} ({}){});\n",
                reg(dst),
                cpp_ty_of_reg(dst),
                ty.cpp(),
                operand(a),
                op.cpp(),
                ty.cpp(),
                operand(b)
            ));
        }
        Instr::MadLo { ty, dst, a, b, c } => {
            // Rendered as an explicit multiply and add, NOT as `fma`.
            // For an integer type the two are identical; the point is
            // that nothing here may become a fused float operation, and
            // `-ffp-contract=off` plus the pragma keep the compiler from
            // making one.
            if matches!(ty, Ty::F32 | Ty::F64) {
                return Err(unsupported(
                    "a floating-point multiply-add must not be rendered as one expression; \
                     Java rounds the product before the add",
                ));
            }
            out.push_str(&format!(
                "    {} = ({})(({}){} * ({}){} + ({}){});\n",
                reg(dst),
                cpp_ty_of_reg(dst),
                ty.cpp(),
                reg(a),
                ty.cpp(),
                reg(b),
                ty.cpp(),
                reg(c)
            ));
        }
        Instr::ElementAddr {
            dst,
            base,
            index,
            elem_size,
            ..
        } => {
            // `(long long)` on the index is what `.wide` does, and is
            // not optional: without it a large index overflows in 32
            // bits exactly where PTX would not.
            out.push_str(&format!(
                "    {} = {} + (long long){} * {};\n",
                reg(dst),
                reg(base),
                reg(index),
                elem_size
            ));
        }
        Instr::LdGlobal { dst, ty, addr } => {
            out.push_str(&format!(
                "    {} = ({})*({}*){};\n",
                reg(dst),
                cpp_ty_of_reg(dst),
                ty.cpp(),
                reg(addr)
            ));
        }
        Instr::StGlobal { ty, addr, value } => {
            out.push_str(&format!(
                "    *({}*){} = ({}){};\n",
                ty.cpp(),
                reg(addr),
                ty.cpp(),
                operand(value)
            ));
        }
        Instr::Setp { cmp, ty, dst, a, b } => {
            out.push_str(&format!(
                "    {} = (({}){} {} ({}){});\n",
                reg(dst),
                ty.cpp(),
                operand(a),
                cmp.cpp(),
                ty.cpp(),
                operand(b)
            ));
        }
    }
    Ok(())
}

/// The declared C++ type of a register, from its name prefix.
///
/// The IR carries register identity as the PTX name during the
/// migration, and the name's prefix IS its class — `%rd` is 64-bit,
/// `%p` is a predicate. Reading it back here avoids threading a
/// register table through every instruction.
fn cpp_ty_of_reg(name: &str) -> &'static str {
    let n = name.trim_start_matches('%');
    // Longest prefix first: `rd`/`rl`/`rs` before `r`, `fd` before `f`.
    for (prefix, kind) in [
        ("rd", RegKind::U64),
        ("rl", RegKind::S64),
        ("rs", RegKind::B16),
        ("ru", RegKind::U32),
        ("fd", RegKind::F64),
        ("r", RegKind::S32),
        ("f", RegKind::F32),
        ("p", RegKind::Pred),
    ] {
        if n.starts_with(prefix) {
            return reg_cpp_ty(kind);
        }
    }
    "int"
}
