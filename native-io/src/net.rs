/// `accept(FileDescriptor fd, FileDescriptor newfd, InetSocketAddress[] isaa)
///    -> int`
///
/// Blocks on `listener.accept()`, allocates a new fd for the returned stream,
/// stores the peer port into `isaa[0]` (if the array was provided and has a
/// synthetic layout), and returns the new fd.
fn net_accept(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    // C26: `args[1]` (the new FileDescriptor object) is intentionally
    // ignored. The pre-fix code wrote the peer port into its `handle`
    // slot, which silently broke `net_fd_from_descriptor`'s fallback
    // path; see the comment below the accept() call. The new fd id is
    // returned via the Int return value instead.
    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("accept: FileDescriptor has no fd id"))?;
    dbgnet!("accept fd={fd:#x} (blocking)");

    // AUDIT 2026-05-17: take the map read-lock briefly to clone the
    // per-listener `Arc<Mutex<_>>`, drop the map lock, then perform the
    // blocking accept(). Holding the global map lock across accept()
    // would serialize all Net operations process-wide for the duration
    // of the listen.
    let listener_handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Listener(l)) => Arc::clone(l),
            Some(_) => return Err(ioex("accept: fd is not a listener")),
            None => return Err(ioex("accept: unknown fd")),
        }
    };

    // The newfd FileDescriptor (args[1]) and isaa array (args[2]) are written
    // AFTER the blocking region below; re-sync them through
    // `end_blocking_region_refs` so a GC completing while this thread was
    // parked in accept() cannot leave them as vacated pre-move addresses.
    let mut largs = args.to_vec();
    let (stream, peer) = {
        let listener = listener_handle.lock();
        // Bracket the unbounded blocking accept() in a GC-blocking region so a
        // stop-the-world GC requested while this thread is parked in accept()
        // does not deadlock `wait_for_all` (the acceptor reaches no interpreter
        // safepoint). See the matching comment in socket_channel::ssc_accept.
        // The loop is close-aware: close(fd) marks the registry entry Closed,
        // which wakes us promptly even though this Arc keeps the OS listener
        // alive until accept returns.
        ctx.begin_blocking_region();
        let res = net_accept_close_aware(&listener, fd);
        ctx.end_blocking_region_refs(&mut largs);
        res.map_err(|e| net_err("accept", e))?
    };
    let _ = stream.set_nonblocking(false);

    let new_fd = register_handle(NetSocketHandle::Stream(Arc::new(stream)));
    dbgnet!("accept fd={fd:#x} -> newfd={new_fd:#x} peer={peer}");

    // NIO-SERVER-SOCKET: mirror the JDK `Net.accept` native contract for the
    // real `NioSocketImpl.accept` path (route 1):
    //   1. Write the accepted socket's fd into the caller-supplied `newfd`
    //      FileDescriptor — `NioSocketImpl.accept` then does
    //      `Net.localAddress(newfd)` and `nsi.fd = newfd`. Without this the
    //      accepted Socket has an unbound fd and read/write fail.
    //   2. Fill `isaa[0]` with a *real* `InetSocketAddress(peerAddr, peerPort)`
    //      so `isaa[0].getAddress()` / `getPort()` return the right types
    //      (the old synthetic 2-field object made `getAddress()` return a
    //      String → `NoSuchMethodError: String.getAddress()`).
    //   3. Return 1 (IOStatus: one connection accepted), not the fd id.
    if let Some(Value::Object(Some(newfd_obj))) = largs.get(1).copied() {
        ctx.set_field_by_name(newfd_obj, "fd", Value::Int(new_fd));
    }

    if let Some(Value::Object(Some(arr))) = largs.get(2).copied() {
        if ctx.array_length(arr) >= 1 {
            let peer_ip = peer.ip().to_string();
            let peer_port = peer.port() as i32;
            // Pin the array AND the freshly-allocated host string across the
            // re-entrant InetSocketAddress construction (which runs real Java
            // bytecode — the constructor calls InetAddress.getByName(), which
            // can allocate and trigger GC). `host` has no other root holding
            // it between creation and being read out of the args slice by the
            // constructor invocation, so without a pin a GC in that window can
            // reclaim/move it out from under the call, leaving the interpreter
            // reading a null/stale reference for the hostname argument (seen
            // as `obj_arg` failing on args[1] inside the InetSocketAddress
            // (Ljava/lang/String;I)V native with "null object argument").
            let arr_pin = ctx.pin_native_root(arr);
            let host = ctx.create_string(&peer_ip);
            let host_pin = ctx.pin_native_root(host);
            let host = ctx.read_native_pin(host_pin, host);
            let isa = ctx.new_object_initialized(
                "java/net/InetSocketAddress",
                "(Ljava/lang/String;I)V",
                &[Value::Object(Some(host)), Value::Int(peer_port)],
            )?;
            let arr = ctx.read_native_pin(arr_pin, arr);
            if let Some(Value::Object(Some(isa_obj))) = isa {
                ctx.set_array_element(arr, 0, Value::Object(Some(isa_obj)));
            }
            ctx.unpin_native_roots(arr_pin);
            ctx.unpin_native_roots(host_pin);
        }
    }

    Ok(Some(Value::Int(1)))
}

/// `connect0(boolean preferIPv6, FileDescriptor fd, InetAddress remote,
///           int remotePort) -> int`
///
/// Blocks on `TcpStream::connect(remote:port)`. On `ConnectionRefused`
/// throws `ConnectException`.
fn net_connect0(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    // args[0] = preferIPv6 (advisory)
    let fd_obj = obj_arg(args, 1)?;
    let remote = match args.get(2) {
        Some(Value::Object(o)) => *o,
        _ => None,
    };
    let port = int_arg(args, 3);

    let addr_text = read_inet_address_text(ctx, remote);
    let conn_addr = join_host_port(&addr_text, port);

    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("connect0: FileDescriptor has no fd id"))?;
    dbgnet!("connect0 fd={fd:#x} addr={conn_addr}");

    // Task #16: SSRF hardening. Apply the outbound-host policy + configured
    // connect timeout (default 30 s) before dialing. Without this, guest
    // code calling `sun/nio/ch/Net.connect0` could reach cloud-metadata
    // endpoints (e.g. AWS IMDS at 169.254.169.254) or pin the VM thread
    // on a black-hole target for the OS-default TCP timeout (~2 min).
    ctx.begin_blocking_region();
    let policy_res = crate::outbound_policy::policy_connect(&conn_addr);
    ctx.end_blocking_region();
    let stream = match policy_res {
        Ok(s) => s,
        Err(crate::outbound_policy::PolicyConnectError::Denied(reason)) => {
            return Err(ioex(format!("connect denied by outbound policy: {reason}")));
        }
        Err(crate::outbound_policy::PolicyConnectError::Io(e)) => {
            return Err(net_err(&conn_addr, e));
        }
    };

    // Apply a `configureBlocking(fd, false)` that was requested while this
    // fd was still `Unbound` — see `net_pending_nonblocking`. Without this,
    // `NioSocketImpl.connect(timeout)`'s pre-connect non-blocking flip is
    // silently lost and the connection comes up in blocking mode, so
    // `net_read0` never returns `IOStatus.UNAVAILABLE` and the JDK's
    // SO_TIMEOUT read protocol never engages.
    if let Some(nonblocking) = net_pending_nonblocking().write().remove(&fd) {
        dbgnet!("connect0 fd={fd:#x} applying deferred nonblocking={nonblocking}");
        stream
            .set_nonblocking(nonblocking)
            .map_err(|error| net_err("connect0", error))?;
    }

    net_sockets()
        .write()
        .insert(fd, NetSocketHandle::Stream(Arc::new(stream)));

    // Return 1 to indicate connection completed (matching JDK IOStatus).
    Ok(Some(Value::Int(1)))
}

/// `shutdown(FileDescriptor fd, int how) -> void`
/// how: 0 = SHUT_RD, 1 = SHUT_WR, 2 = SHUT_RDWR
fn net_shutdown(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let how = int_arg(args, 1);
    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("shutdown: FileDescriptor has no fd id"))?;
    let dir = match how {
        0 => std::net::Shutdown::Read,
        1 => std::net::Shutdown::Write,
        _ => std::net::Shutdown::Both,
    };
    // AUDIT 2026-05-17: clone the per-stream Arc under the map read-lock,
    // then drop the map lock before issuing the shutdown syscall.
    let stream_handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(s)) => Some(Arc::clone(s)),
            _ => None,
        }
    };
    if let Some(s) = stream_handle {
        let _ = s.shutdown(dir);
    }
    Ok(None)
}

