/// A socket registered with `sun.nio.ch.Net`. The enum tracks the lifecycle
/// so `bind0` knows to upgrade an `Unbound` → `Listener`, and `close`
/// drops the OS resource regardless of state.
///
/// Drop is automatic on removal from the map; Rust's `std::net::TcpListener`
/// / `TcpStream` close their underlying file descriptor on drop.
///
/// AUDIT 2026-05-17: listeners are wrapped in `Arc<Mutex<_>>` for close-aware
/// accept coordination. Streams are plain `Arc<TcpStream>` so a blocking read
/// on one Java thread does not exclude a write on the same socket from another
/// Java thread.
pub enum NetSocketHandle {
    /// Freshly created via `socket0` but not yet bound / connected.
    Unbound,
    /// Bound + listening (post `bind0`).
    Listener(Arc<Mutex<TcpListener>>),
    /// Active stream (connected via `connect0` or accepted).
    Stream(Arc<TcpStream>),
    /// Marked closed but still in the map so `close(fd)` is idempotent.
    Closed,
}

/// Process-wide registry of live TCP sockets opened through `sun/nio/ch/Net`.
/// Keyed by the "fd" integer returned to Java code. Using a separate map from
/// the `FileDescriptorTable` lets us distinguish Net-owned sockets (which
/// support bind / listen / accept state transitions) from regular file fds.
fn net_sockets() -> &'static RwLock<FxHashMap<i32, NetSocketHandle>> {
    static REG: OnceLock<RwLock<FxHashMap<i32, NetSocketHandle>>> = OnceLock::new();
    REG.get_or_init(|| RwLock::new(FxHashMap::default()))
}

/// Per-fd blocking mode as last requested through `IOUtil.configureBlocking`.
///
/// Two consumers:
///
/// 1. *Deferred application.* The request can arrive while the fd is still
///    `Unbound` (no live OS socket to apply it to): `NioSocketImpl.connect(
///    timeout)` calls `IOUtil.configureBlocking(fd, false)` BEFORE
///    `Net.connect0` — the fd is deliberately flipped non-blocking ahead of the
///    connect attempt, then `connect0`/`Net.poll` drive the timed-connect
///    protocol. `net_connect0` used to always hand back a fresh,
///    default-blocking `TcpStream`, silently dropping that request: every later
///    `read0` on the connection then did a genuine blocking OS `read()` instead
///    of returning `IOStatus.UNAVAILABLE`, so `NioSocketImpl.timedRead`'s
///    configured `SO_TIMEOUT` never fired and the read blocked until the peer
///    closed. `net_connect0` / `net_bind0` apply it once the socket exists.
///
/// 2. *Mode query.* [`net_accept`] must know whether the caller wants the JDK's
///    non-blocking accept contract (return `IOStatus.UNAVAILABLE`) or a genuine
///    blocking accept. Entries are therefore RETAINED after being applied —
///    they are the record of the mode, not a one-shot to-do item — and dropped
///    only when the fd is closed ([`close_net_fd`]).
fn net_pending_nonblocking() -> &'static RwLock<FxHashMap<i32, bool>> {
    static PENDING: OnceLock<RwLock<FxHashMap<i32, bool>>> = OnceLock::new();
    PENDING.get_or_init(|| RwLock::new(FxHashMap::default()))
}

/// Whether `IOUtil.configureBlocking(fd, false)` is in effect for this fd.
fn net_fd_is_nonblocking(fd: i32) -> bool {
    net_pending_nonblocking()
        .read()
        .get(&fd)
        .copied()
        .unwrap_or(false)
}

/// Per-socket option store (SO_REUSEADDR / SO_KEEPALIVE / TCP_NODELAY / etc.).
/// Rust's `std::net` exposes a subset directly — for options it doesn't
/// expose (SO_LINGER on TcpListener, IP_TOS, …) we remember the value so
/// `getIntOption0` returns what `setIntOption0` last set.
fn net_opts() -> &'static RwLock<FxHashMap<(i32, i32, i32), i32>> {
    static OPTS: OnceLock<RwLock<FxHashMap<(i32, i32, i32), i32>>> = OnceLock::new();
    OPTS.get_or_init(|| RwLock::new(FxHashMap::default()))
}

fn next_net_fd() -> i32 {
    // Start high so there's no collision with the `FileDescriptorTable`
    // counter. Actual fds in the JDK are independent from our Rust-side
    // integers — we just need them to be unique positive values.
    static NEXT: AtomicI32 = AtomicI32::new(0x4000_0000);
    NEXT.fetch_add(1, Ordering::SeqCst)
}

/// Register a handle in the map. Returns the fresh fd id.
fn register_handle(h: NetSocketHandle) -> i32 {
    let id = next_net_fd();
    net_sockets().write().insert(id, h);
    id
}

/// Transfer an accepted `sun.nio.ch.Net` stream to a protocol layer that will
/// own all subsequent I/O (currently the rustls-backed SSLSocket bridge).
///
/// The Java `Socket` remains logically closed after this handoff: its original
/// registry entry is replaced with `Closed`, while the returned `TcpStream`
/// owns a duplicated OS handle when another transient Arc still exists.
pub fn take_stream_for_tls(fd: i32) -> Result<TcpStream, String> {
    let stream = {
        let mut map = net_sockets().write();
        match map.insert(fd, NetSocketHandle::Closed) {
            Some(NetSocketHandle::Stream(stream)) => stream,
            Some(other) => {
                map.insert(fd, other);
                return Err(format!("Net fd {fd:#x} is not an accepted stream"));
            }
            None => return Err(format!("Net fd {fd:#x} is not registered")),
        }
    };
    Arc::try_unwrap(stream)
        .or_else(|shared| shared.try_clone())
        .map_err(|e| format!("clone Net fd {fd:#x} for TLS: {e}"))
}

fn close_net_fd(fd: i32) {
    let old = {
        let mut map = net_sockets().write();
        map.insert(fd, NetSocketHandle::Closed)
    };
    net_pending_nonblocking().write().remove(&fd);
    if io_flags().dbg_net {
        let kind = match &old {
            Some(NetSocketHandle::Unbound) => "unbound",
            Some(NetSocketHandle::Listener(_)) => "listener",
            Some(NetSocketHandle::Stream(_)) => "stream",
            Some(NetSocketHandle::Closed) => "closed",
            None => "missing",
        };
        eprintln!("[NET] close fd={fd:#x} old={kind}");
    }
    if let Some(NetSocketHandle::Stream(stream)) = old {
        let _ = stream.shutdown(Shutdown::Both);
    }
}

fn close_net_fd_descriptor(ctx: &mut dyn NativeContext, fd_obj: ObjectRef, clear_fields: bool) {
    if let Some(fd) = net_fd_from_descriptor(ctx, fd_obj) {
        close_net_fd(fd);
    }
    if clear_fields {
        ctx.set_field_by_name(fd_obj, "fd", Value::Int(-1));
        ctx.set_field_by_name(fd_obj, "handle", Value::Long(-1));
    }
}

const NET_ACCEPT_CLOSE_POLL: Duration = Duration::from_millis(10);

fn net_listener_still_registered(fd: i32) -> bool {
    matches!(
        net_sockets().read().get(&fd),
        Some(NetSocketHandle::Listener(_))
    )
}

/// The error a blocked/parked accept reports once its `ServerSocket` is closed.
/// `net_err` renders it as `java.net.SocketException`, matching HotSpot's
/// blocked-accept-on-close.
fn net_accept_closed_err() -> std::io::Error {
    std::io::Error::new(ErrorKind::Interrupted, "server socket closed")
}

fn net_accept_close_aware(
    listener: &TcpListener,
    fd: i32,
) -> std::io::Result<(TcpStream, SocketAddr)> {
    listener.set_nonblocking(true)?;
    loop {
        match listener.accept() {
            Ok(pair) => return Ok(pair),
            Err(e) if e.kind() == ErrorKind::WouldBlock => {
                if !net_listener_still_registered(fd) {
                    return Err(net_accept_closed_err());
                }
                std::thread::sleep(NET_ACCEPT_CLOSE_POLL);
            }
            Err(e) => return Err(e),
        }
    }
}

/// Convert a `std::io::Error` into the closest matching JDK IOException subtype.
/// `ConnectException` and `SocketTimeoutException` have real typed `RuntimeError`
/// variants and MUST be thrown as those concrete types — real code catches them
/// specifically (e.g. ES `RestClientMultipleHostsIntegTests.testNodeSelector`
/// does `catch (ConnectException e)` around a connect to a stopped host; a bare
/// IOException whose message merely mentions the class name escapes that catch).
/// The remaining kinds have no typed variant yet, so we fall back to the
/// message-prefix convention also used by `net_phase_e.rs` for `java.net.Socket`
/// / `ServerSocket`.
fn net_err(ctx: &str, e: std::io::Error) -> MethodCallFailed {
    match e.kind() {
        ErrorKind::ConnectionRefused => {
            return RuntimeError::ConnectException {
                message: format!("{ctx}: {e}"),
            }
            .into();
        }
        ErrorKind::TimedOut | ErrorKind::WouldBlock => {
            return RuntimeError::SocketTimeoutException {
                message: format!("{ctx}: {e}"),
            }
            .into();
        }
        ErrorKind::AddrInUse => {
            return RuntimeError::BindException {
                message: format!("Address already in use: {ctx}: {e}"),
            }
            .into();
        }
        ErrorKind::AddrNotAvailable => {
            return RuntimeError::BindException {
                message: format!("Cannot assign requested address: {ctx}: {e}"),
            }
            .into();
        }
        ErrorKind::PermissionDenied => {
            return RuntimeError::BindException {
                message: format!("Permission denied: {ctx}: {e}"),
            }
            .into();
        }
        _ => {}
    }
    let msg = match e.kind() {
        ErrorKind::ConnectionReset => format!("SocketException: Connection reset: {ctx}: {e}"),
        ErrorKind::ConnectionAborted => format!("SocketException: Connection aborted: {ctx}: {e}"),
        ErrorKind::NotConnected => format!("SocketException: Not connected: {ctx}: {e}"),
        _ => format!("SocketException: {ctx}: {e}"),
    };
    RuntimeError::IOException { message: msg }.into()
}

fn ioex(msg: impl Into<String>) -> MethodCallFailed {
    RuntimeError::IOException {
        message: msg.into(),
    }
    .into()
}

/// Temporary diagnostic gate: `CRATONVM_DBG_NET=1` prints each Net native as
/// it fires, to localize where the blocking ServerSocket/Socket path breaks.
macro_rules! dbgnet {
    ($($arg:tt)*) => {
        if io_flags().dbg_net {
            eprintln!("[NET] {}", format!($($arg)*));
        }
    };
}

/// Upper bound on a single read0/write0 transfer. The JDK's NIO socket
/// paths chunk I/O well below this; any `len` larger than this from Java
/// is treated as corrupt input rather than honored. 1 GiB is comfortably
/// above any legitimate DirectByteBuffer-backed socket transfer.
const NET_MAX_TRANSFER: i64 = 1 << 30;

/// Validate the `(address, len)` pair handed to `read0` / `write0` before
/// it is used as the target/source of a raw `ptr::copy_nonoverlapping`.
///
/// RESIDUAL TRUST: this crate has no reachable registry of live native
/// buffer addresses+sizes (the DirectByteBuffer/Unsafe allocation tables
/// in `direct_buffer.rs` are module-private and the Unsafe table is
/// consumed destructively on free), so we cannot prove `address` points
/// inside a live allocation. We do the strongest bounded check available:
/// reject a null/negative address and a non-positive or absurdly large
/// `len`. A caller passing a valid-but-undersized buffer is still trusted.
fn validate_native_range(ctx: &str, address: i64, len: i32) -> Result<usize, MethodCallFailed> {
    if address <= 0 {
        return Err(ioex(format!("{ctx}: null or invalid native address")));
    }
    if len <= 0 {
        return Err(ioex(format!("{ctx}: non-positive length {len}")));
    }
    if (len as i64) > NET_MAX_TRANSFER {
        return Err(ioex(format!(
            "{ctx}: length {len} exceeds maximum transfer size"
        )));
    }
    Ok(len as usize)
}

/// Extract an int from a `FileDescriptor` object. The `fd` field holds the
/// Net-allocated id. Falls back to the Windows `handle` long field if `fd`
/// is not populated. Returns `None` if the FileDescriptor is null or both
/// fields are empty.
fn net_fd_from_descriptor(ctx: &mut dyn NativeContext, fd_obj: ObjectRef) -> Option<i32> {
    match ctx.get_field_by_name(fd_obj, "fd") {
        Value::Int(v) if v != 0 && v != -1 => return Some(v),
        _ => {}
    }
    match ctx.get_field_by_name(fd_obj, "handle") {
        Value::Long(v) if v != 0 && v != -1 && v <= i32::MAX as i64 && v >= i32::MIN as i64 => {
            return Some(v as i32);
        }
        _ => {}
    }
    None
}

fn obj_arg(args: &[Value], idx: usize) -> Result<ObjectRef, MethodCallFailed> {
    match args.get(idx) {
        Some(Value::Object(Some(o))) => Ok(*o),
        _ => Err(ioex("sun/nio/ch/Net: null object argument")),
    }
}

fn int_arg(args: &[Value], idx: usize) -> i32 {
    match args.get(idx) {
        Some(Value::Int(v)) => *v,
        _ => 0,
    }
}

fn bool_arg(args: &[Value], idx: usize) -> bool {
    matches!(args.get(idx), Some(Value::Int(v)) if *v != 0)
}

/// Read a string-valued address field from an `InetAddress` object. The
/// synthetic layout (`alloc_inet_address` in `net_phase_e.rs`) stores the
/// numeric IP text at field 1 (`IA_ADDR`) and the hostname at field 0.
/// Returns `0.0.0.0` for null / unknown layouts so `bind0` with
/// `ANY_LOCAL_ADDR` works.
fn read_inet_address_text(ctx: &mut dyn NativeContext, ia: Option<ObjectRef>) -> String {
    let Some(o) = ia else {
        return "0.0.0.0".to_string();
    };
    // NIO-SERVER-SOCKET (IPv6): real-JDK `Inet6Address` keeps its 16-byte
    // address in a SEPARATE holder `this.holder6`
    // (`Inet6Address$Inet6AddressHolder`) with a `byte[16] ipaddress` field
    // (+ `int scope_id`). The IPv4 `holder.address` int is ~0 for a v6 address,
    // so without reading holder6 first a v6 InetAddress falls through to the
    // text fallback below and bind0/connect0 target the wildcard. Read holder6
    // before the IPv4 holder so genuine v6 addresses resolve correctly.
    if let Value::Object(Some(holder6)) = ctx.get_field_by_name(o, "holder6") {
        if let Value::Object(Some(arr)) = ctx.get_field_by_name(holder6, "ipaddress") {
            if ctx.array_length(arr) >= 16 {
                let mut bytes = [0u8; 16];
                if ctx.read_byte_array_into(arr, 0, &mut bytes) == 16 {
                    let v6 = std::net::Ipv6Addr::from(bytes);
                    // Link-local addresses need a %scope suffix to bind/connect
                    // on Windows; scope_id == 0 means "no scope" (loopback,
                    // global) and is omitted.
                    let scoped = match ctx.get_field_by_name(holder6, "scope_id") {
                        Value::Int(s) if s != 0 => format!("{v6}%{s}"),
                        _ => v6.to_string(),
                    };
                    dbgnet!("read_inet_address_text v6 -> {scoped}");
                    return scoped;
                }
            }
        }
    }
    // NIO-SERVER-SOCKET: real-JDK `Inet4Address` stores the IPv4 address as an
    // int in `this.holder.address` (host byte order — 127.0.0.1 == 0x7F000001),
    // NOT as a text field. When `java.net.Socket` runs real bytecode (route 1)
    // the `InetAddress` reaching `bind0`/`connect0` is the real object, so read
    // the holder first; without this, connect0 saw 0.0.0.0 and never reached
    // the listener. Synthetic InetAddress objects have no `holder` field, so
    // this is skipped and the text-field path below runs.
    if let Value::Object(Some(holder)) = ctx.get_field_by_name(o, "holder") {
        if let Value::Int(a) = ctx.get_field_by_name(holder, "address") {
            if a != 0 {
                return format!(
                    "{}.{}.{}.{}",
                    (a >> 24) & 0xff,
                    (a >> 16) & 0xff,
                    (a >> 8) & 0xff,
                    a & 0xff
                );
            }
        }
    }
    // Preferred: field 1 is the canonical numeric IP text.
    if let Value::Object(Some(s)) = ctx.get_field(o, 1) {
        if let Some(text) = ctx.read_string(s) {
            if !text.is_empty() {
                return text;
            }
        }
    }
    // Fallback: field 0 (hostname). For literal IPs the hostname string is
    // already the address.
    if let Value::Object(Some(s)) = ctx.get_field(o, 0) {
        if let Some(text) = ctx.read_string(s) {
            if !text.is_empty() {
                return text;
            }
        }
    }
    // Final fallback: wildcard.
    "0.0.0.0".to_string()
}

/// Join an address text and port into a Rust `ToSocketAddrs` string. IPv6
/// literals MUST be bracketed (`[::1]:port`) — std's `SocketAddr` parser
/// rejects `::1:port` (it reads the whole thing as a v6 address with no port).
/// A bare IPv4/hostname is joined with a plain colon. An already-bracketed
/// host is passed through unchanged.
fn join_host_port(addr_text: &str, port: i32) -> String {
    if addr_text.contains(':') && !addr_text.starts_with('[') {
        format!("[{addr_text}]:{port}")
    } else {
        format!("{addr_text}:{port}")
    }
}

// ---------- socket lifecycle ----------

/// `socket0(boolean preferIPv6, boolean stream, boolean reuseAddr,
///          boolean fastLoopback) -> int`
///
/// Returns a fresh fd id. The OS socket is not created yet — actual binding
/// happens in `bind0`, actual connection happens in `connect0`. This matches
/// how the JDK uses `socket()` syscalls (create → bind/listen or connect).
fn net_socket0(_ctx: &mut dyn NativeContext, _args: &[Value]) -> MethodCallResult {
    let fd = register_handle(NetSocketHandle::Unbound);
    dbgnet!("socket0 -> fd={fd:#x}");
    Ok(Some(Value::Int(fd)))
}

/// `bind0(FileDescriptor fd, boolean preferIPv6, boolean useExclBind,
///        InetAddress addr, int port) -> void`
///
/// Looks up the fd, binds a `TcpListener` to `addr:port`, and swaps the
/// handle from `Unbound` → `Listener`. On `AddrInUse` throws
/// `BindException`.
fn net_bind0(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    // args[1] = preferIPv6, args[2] = useExclBind — advisory only, we always
    // bind dual-stack via Rust std.
    let inet_addr = match args.get(3) {
        Some(Value::Object(o)) => *o,
        _ => None,
    };
    let port = int_arg(args, 4);

    let addr_text = read_inet_address_text(ctx, inet_addr);
    let bind_addr = join_host_port(&addr_text, port);

    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("bind0: FileDescriptor has no fd id"))?;
    dbgnet!("bind0 fd={fd:#x} addr={bind_addr}");

    // The JDK semantics allow bind0 on a Net fd even without a prior socket0
    // (the JDK's SocketChannelImpl creates sockets via its own path). If the
    // fd is not in our map, insert one up-front.
    {
        let mut map = net_sockets().write();
        map.entry(fd).or_insert(NetSocketHandle::Unbound);
    }

    // Bind exactly one address. Letting `TcpListener::bind` walk the whole
    // resolution list turns "port already in use" into a silent bind to some
    // other address of the same name — see `socket_channel::single_bind_addr`
    // for the Tribes auto-bind loop that breaks on.
    let target = crate::socket_channel::single_bind_addr(&addr_text, port.clamp(0, 65535) as u16)
        .map_err(|e| net_err(&bind_addr, e))?;
    let listener = TcpListener::bind(target).map_err(|e| net_err(&bind_addr, e))?;

    // C26 fix: do NOT write the resolved port into FileDescriptor.handle —
    // `handle` is the fd-id sentinel that `net_fd_from_descriptor` falls back
    // to (see lines 262-266). Overwriting it with the port value broke later
    // lookups into `net_sockets`. The local port is reachable via
    // `local_addr()` on the underlying TcpListener (see `net_local_port`
    // at lines 691-716), so the JDK's `localPort` shortcut still works
    // without us touching the FileDescriptor here. Mirrors the connect0
    // path (lines 446-469), which similarly does not write back the local
    // port.

    // Mirror `net_connect0`: a `configureBlocking(fd, false)` requested
    // while this fd was still `Unbound` (e.g. `ServerSocketChannel.open();
    // configureBlocking(false); bind(...)`) must carry over to the freshly
    // bound listener, or `accept0`'s WouldBlock/`Net.poll` protocol never
    // engages.
    if let Some(nonblocking) = net_pending_nonblocking().read().get(&fd).copied() {
        dbgnet!("bind0 fd={fd:#x} applying deferred nonblocking={nonblocking}");
        listener
            .set_nonblocking(nonblocking)
            .map_err(|e| net_err(&bind_addr, e))?;
    }

    let bound_port = listener.local_addr().map(|a| a.port()).unwrap_or(0);
    net_sockets().write().insert(
        fd,
        NetSocketHandle::Listener(Arc::new(Mutex::new(listener))),
    );
    dbgnet!("bind0 OK fd={fd:#x} bound_port={bound_port}");
    Ok(None)
}

