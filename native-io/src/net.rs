// `sun.nio.ch.*Impl` variants), and those are dead registrations on this JDK
// rather than bridges — split them out before claiming the whole function.
/// Register the `sun/nio/ch/Net` TCP-native surface. Safe to call more than
/// once — later registrations override earlier ones at the same signature.
pub fn register_sun_nio_ch_net(r: &mut NativeMethodRegistry) {
    let __prev_cat = r.current_category();
    r.set_category(cratonvm_native_api::NativeKind::Bridge);
    let net = "sun/nio/ch/Net";

    // Lifecycle
    r.register(net, "socket0", "(ZZZZ)I", net_socket0);
    // Some JDK builds drop the fastLoopback parameter.
    r.register(net, "socket0", "(ZZZ)I", net_socket0);
    r.register(
        net,
        "bind0",
        "(Ljava/io/FileDescriptor;ZZLjava/net/InetAddress;I)V",
        net_bind0,
    );
    r.register(net, "listen", "(Ljava/io/FileDescriptor;I)V", net_listen);
    r.register(
        net,
        "accept",
        "(Ljava/io/FileDescriptor;Ljava/io/FileDescriptor;[Ljava/net/InetSocketAddress;)I",
        net_accept,
    );
    r.register(
        net,
        "connect0",
        "(ZLjava/io/FileDescriptor;Ljava/net/InetAddress;I)I",
        net_connect0,
    );
    r.register(
        net,
        "shutdown",
        "(Ljava/io/FileDescriptor;I)V",
        net_shutdown,
    );
    r.register(net, "close", "(Ljava/io/FileDescriptor;)V", net_close);

    // I/O delegates (also mirror on ServerSocketChannelImpl / SocketChannelImpl
    // in case JDK dispatch reaches them directly).
    r.register(net, "read0", "(Ljava/io/FileDescriptor;JI)I", net_read0);
    r.register(net, "write0", "(Ljava/io/FileDescriptor;JI)I", net_write0);
    // DF04: bytes-readable query (ioctl FIONREAD). NioSocketImpl.available()
    // → Socket.getInputStream().available() dispatches here.
    r.register(
        net,
        "available",
        "(Ljava/io/FileDescriptor;)I",
        net_available,
    );
    // NIO-SERVER-SOCKET: the blocking `NioSocketImpl` read/write path goes
    // through `sun/nio/ch/SocketDispatcher.read0/write0` (nd.read/nd.write),
    // NOT `Net.read0`. Wire those to the same handlers so a real
    // java.net.Socket round-trips bytes through our `TcpStream`. `close0`
    // takes a raw int fd (the dispatcher's NativeDispatcher.close path).
    for cls in [
        "sun/nio/ch/SocketChannelImpl",
        "sun/nio/ch/ServerSocketChannelImpl",
        "sun/nio/ch/SocketDispatcher",
    ] {
        r.register(cls, "read0", "(Ljava/io/FileDescriptor;JI)I", net_read0);
        r.register(cls, "write0", "(Ljava/io/FileDescriptor;JI)I", net_write0);
    }
    r.register(
        "sun/nio/ch/SocketDispatcher",
        "close0",
        "(I)V",
        |_ctx, args| {
            if let Some(Value::Int(fd)) = args.first().copied() {
                close_net_fd(fd);
            }
            Ok(None)
        },
    );
    r.register(
        "sun/nio/ch/SocketDispatcher",
        "close",
        "(Ljava/io/FileDescriptor;)V",
        |ctx, args| {
            let fd_obj = obj_arg(args, 1)?;
            close_net_fd_descriptor(ctx, fd_obj, true);
            Ok(None)
        },
    );
    r.register(
        "sun/nio/ch/SocketDispatcher",
        "invalidateAndClose",
        "(Ljava/io/FileDescriptor;)V",
        |ctx, args| {
            let fd_obj = obj_arg(args, 0)?;
            close_net_fd_descriptor(ctx, fd_obj, true);
            Ok(None)
        },
    );
    r.register(
        "sun/nio/ch/NativeDispatcher",
        "preClose",
        "(Ljava/io/FileDescriptor;JJ)V",
        |ctx, args| {
            let fd_obj = obj_arg(args, 1)?;
            close_net_fd_descriptor(ctx, fd_obj, false);
            Ok(None)
        },
    );
    // `sun/nio/ch/UnixDispatcher.close0`/`preClose0(FileDescriptor)` — real
    // JDK 25's actual native surface for tearing down a NIO socket fd
    // (confirmed via javap: `UnixDispatcher` declares both as private
    // static natives; `SocketDispatcher extends UnixDispatcher` and does
    // NOT redeclare them, so the `invokestatic` target lexically inside
    // `UnixDispatcher.close()`/`implPreClose()` is `UnixDispatcher` itself,
    // not `SocketDispatcher`). These were entirely unregistered — unlike
    // the `(I)V`-descriptor stub above (a different, synthetic-bytecode
    // shape), so real bytecode never resolved either — which threw
    // `UnsatisfiedLinkError: sun/nio/ch/UnixDispatcher.preClose0` from
    // `ServerSocket.close()` (via `NioSocketImpl.close()` ->
    // `NativeDispatcher.preClose`). Companion gap to the `FileKey.init`
    // fix, see
    // fixed-suite-bugs/tls-ocsp-clientcert-validation-not-enforced-FIXED.md.
    r.register(
        "sun/nio/ch/UnixDispatcher",
        "close0",
        "(Ljava/io/FileDescriptor;)V",
        net_close,
    );
    // `preClose0` exists to unblock concurrent socket I/O before the final
    // close runs. Wake any blocked read/write by shutting down the old stream
    // handle, but leave Java's FileDescriptor fields intact for close0.
    r.register(
        "sun/nio/ch/UnixDispatcher",
        "preClose0",
        "(Ljava/io/FileDescriptor;)V",
        |ctx, args| {
            let fd_obj = obj_arg(args, 0)?;
            close_net_fd_descriptor(ctx, fd_obj, false);
            Ok(None)
        },
    );

    // Options
    r.register(
        net,
        "setIntOption0",
        "(Ljava/io/FileDescriptor;ZIIIZ)V",
        net_set_int_option0,
    );
    r.register(
        net,
        "getIntOption0",
        "(Ljava/io/FileDescriptor;ZII)I",
        net_get_int_option0,
    );

    // Address queries
    r.register(
        net,
        "localInetAddress",
        "(Ljava/io/FileDescriptor;)Ljava/net/InetAddress;",
        net_local_inet_address,
    );
    r.register(
        net,
        "localPort",
        "(Ljava/io/FileDescriptor;)I",
        net_local_port,
    );
    r.register(
        net,
        "remoteInetAddress",
        "(Ljava/io/FileDescriptor;)Ljava/net/InetAddress;",
        net_remote_inet_address,
    );
    r.register(
        net,
        "remotePort",
        "(Ljava/io/FileDescriptor;)I",
        net_remote_port,
    );

    // Capability flags
    r.register(net, "isIPv6Available0", "()Z", net_is_ipv6_available);
    r.register(
        net,
        "isReusePortAvailable0",
        "()Z",
        net_is_reuse_port_available,
    );
    r.register(
        net,
        "canIPv6SocketJoinIPv4Group0",
        "()Z",
        net_can_ipv6_join_ipv4_group,
    );
    r.register(
        net,
        "isExclusiveBindAvailable",
        "()I",
        net_is_exclusive_bind_available,
    );
    // initIDs() — the JDK calls this once in <clinit> to populate cached field
    // offsets; for us it's a no-op since we use name-based field lookup.
    r.register(net, "initIDs", "()V", |_c, _a| Ok(None));

    // `NioSocketImpl` flips the OS fd to non-blocking when it enforces a
    // Java-level SO_TIMEOUT. `net_read0` then returns IOStatus.UNAVAILABLE and
    // `Net.poll` handles the timed wait. This must alter the real stream; a
    // no-op makes read0 block until peer close and incorrectly report EOF.
    r.register(
        "sun/nio/ch/IOUtil",
        "configureBlocking",
        "(Ljava/io/FileDescriptor;Z)V",
        |ctx, args| {
            let fd_obj = obj_arg(args, 0)?;
            let blocking = args.get(1).and_then(|value| value.as_int()).unwrap_or(0) != 0;
            let Some(fd) = net_fd_from_descriptor(ctx, fd_obj) else {
                dbgnet!("configureBlocking: FileDescriptor has no fd id (blocking={blocking})");
                return Ok(None);
            };
            // Record the request regardless of the fd's current registry
            // state. If the fd is still `Unbound` (pre-`connect0`) this is
            // the ONLY record of it — see `net_pending_nonblocking`.
            net_pending_nonblocking().write().insert(fd, !blocking);
            let map = net_sockets().read();
            match map.get(&fd) {
                Some(NetSocketHandle::Stream(stream)) => {
                    dbgnet!("configureBlocking fd={fd:#x} kind=stream blocking={blocking}");
                    stream
                        .set_nonblocking(!blocking)
                        .map_err(|error| net_err("configureBlocking", error))?
                }
                Some(NetSocketHandle::Listener(listener)) => {
                    dbgnet!("configureBlocking fd={fd:#x} kind=listener blocking={blocking}");
                    listener
                        .lock()
                        .set_nonblocking(!blocking)
                        .map_err(|error| net_err("configureBlocking", error))?
                }
                other => {
                    let kind = match other {
                        Some(NetSocketHandle::Unbound) => "unbound",
                        Some(NetSocketHandle::Closed) => "closed",
                        None => "MISSING",
                        _ => unreachable!(),
                    };
                    dbgnet!(
                        "configureBlocking fd={fd:#x} kind={kind} blocking={blocking} deferred"
                    );
                }
            }
            Ok(None)
        },
    );
    r.register(net, "poll", "(Ljava/io/FileDescriptor;IJ)I", net_poll);

    // NIO-SERVER-SOCKET: `jdk/net/WindowsSocketOptions` natives. Without these,
    // `jdk.net.ExtendedSocketOptions.<clinit>` throws UnsatisfiedLinkError on
    // `keepAliveOptionsSupported0`, which is swallowed — leaving
    // `sun.nio.ch.Net.EXTENDED_OPTIONS` null. `NioSocketImpl.close()` then calls
    // `Net.getSocketOption(fd, SO_LINGER)` → `EXTENDED_OPTIONS.isOptionSupported(..)`
    // → NPE, so a real java.net.Socket cannot be closed cleanly. Report "no
    // extended keepalive options" (false) so the clinit succeeds and the
    // keepalive getters/setters below are never exercised.
    {
        let wso = "jdk/net/WindowsSocketOptions";
        // Windows 10 1703+ exposes TCP_KEEPIDLE/TCP_KEEPCNT/TCP_KEEPINTVL.
        // The handlers below use Winsock directly for the two live TCP handle
        // registries and FileDescriptorTable-owned DatagramSockets, keeping
        // the capability probe and each getter/setter aligned with the actual
        // socket on which Java requested the option.
        r.register(wso, "keepAliveOptionsSupported0", "()Z", |_c, _a| {
            Ok(Some(Value::Int(i32::from(ext_opt_keepalive_supported()))))
        });
        // IP_DONTFRAGMENT is NOT gated by a native probe — `ipDontFragmentSupported()`
        // is plain Java returning true — so unlike the keepalive family below these
        // two really are reachable from `DatagramSocket.setOption(IP_DONTFRAGMENT, ..)`.
        // They used to accept the request and drop it on the floor.
        r.register(wso, "getIpDontFragment0", "(IZ)Z", |ctx, args| {
            #[cfg(target_os = "windows")]
            { return Ok(Some(Value::Int(i32::from(win_ext_opt_get(ctx, args, ExtOpt::DontFragment)? != 0)))); }
            #[cfg(not(target_os = "windows"))]
            { let _ = (ctx, args); Err(ext_opt_unsupported("IP_DONTFRAGMENT")) }
        });
        r.register(wso, "setIpDontFragment0", "(IZZ)V", |ctx, args| {
            #[cfg(target_os = "windows")]
            { win_ext_opt_set(ctx, args, ExtOpt::DontFragment)?; return Ok(None); }
            #[cfg(not(target_os = "windows"))]
            { let _ = (ctx, args); Err(ext_opt_unsupported("IP_DONTFRAGMENT")) }
        });
        r.register(wso, "getTcpKeepAliveProbes0", "(I)I", windows_keepalive_get_probes);
        r.register(wso, "getTcpKeepAliveTime0", "(I)I", windows_keepalive_get_time);
        r.register(wso, "getTcpKeepAliveIntvl0", "(I)I", windows_keepalive_get_intvl);
        r.register(wso, "setTcpKeepAliveProbes0", "(II)V", windows_keepalive_set_probes);
        r.register(wso, "setTcpKeepAliveTime0", "(II)V", windows_keepalive_set_time);
        r.register(wso, "setTcpKeepAliveIntvl0", "(II)V", windows_keepalive_set_intvl);
    }

    // Linux analogue of the `WindowsSocketOptions` block above (HIB-linux
    // SQL-Server-driver regression, 2026-07-03): the JDK picks
    // `jdk.net.LinuxSocketOptions` over `WindowsSocketOptions` on Linux, so
    // only stubbing the Windows class left `ExtendedSocketOptions.<clinit>`
    // without a native for `LinuxSocketOptions.quickAckSupported0()` there —
    // an `UnsatisfiedLinkError` (uncaught, since it's an Error) that aborts
    // `<clinit>` and marks the class permanently erroneous. mssql-jdbc's
    // `SQLServerDriver.<clinit>` transitively touches `ExtendedSocketOptions`
    // (Linux-specific TCP_QUICKACK tuning), so this surfaced as
    // `NoClassDefFoundError: SQLServerDriver` on every later reference,
    // silently masking the original `UnsatisfiedLinkError` per JVMS 5.5.
    // IMPLEMENTED (wave 4), not stubbed: every option in this block exists on
    // Linux, and the handle id the JDK passes is the key into the registry that
    // holds the live socket — see the `ExtendedSocketOptions` note above
    // `ext_opt_sys`. The `*Supported0` probes now ask the running kernel the
    // same way the real JNI bodies do (throwaway socket + setsockopt/getsockopt),
    // so `<clinit>` still succeeds on a kernel that lacks an option, and the
    // getters/setters below are only reachable when the probe said yes.
    //
    // SHADOWING NOTE: `native-builtins/src/lib.rs` used to register a
    // byte-for-byte twin of this block from
    // `register_essential_natives_with_shims`; that copy was deleted in wave 3,
    // so this is the only registration of the family.
    {
        let lso = "jdk/net/LinuxSocketOptions";
        r.register(lso, "keepAliveOptionsSupported0", "()Z", |_c, _a| {
            Ok(Some(Value::Int(i32::from(ext_opt_keepalive_supported()))))
        });
        r.register(lso, "quickAckSupported0", "()Z", |_c, _a| {
            Ok(Some(Value::Int(i32::from(ext_opt_supported(
                ExtOpt::QuickAck,
                true,
            )))))
        });
        r.register(lso, "incomingNapiIdSupported0", "()Z", |_c, _a| {
            Ok(Some(Value::Int(i32::from(ext_opt_supported(
                ExtOpt::IncomingNapiId,
                false,
            )))))
        });
        // IP_DONTFRAGMENT is NOT gated by a native probe
        // (`ipDontFragmentSupported()` is plain Java returning true), so these
        // two are genuinely reachable — and they are now IMPLEMENTED rather than
        // refused. The earlier "the native is handed no address family"
        // justification was factually wrong: the JDK signatures are
        // `getIpDontFragment0(int fd, boolean isIPv6)` and
        // `setIpDontFragment0(int fd, boolean optval, boolean isIPv6)`, so
        // `IP_MTU_DISCOVER` (v4) / `IPV6_MTU_DISCOVER` (v6) is selectable —
        // which is exactly what `LinuxSocketOptions.c` does. The Windows twin
        // above has had a real implementation since the same round.
        r.register(lso, "getIpDontFragment0", "(IZ)Z", |_c, a| {
            Ok(Some(Value::Int(i32::from(linux_dont_fragment_get(a)?))))
        });
        r.register(lso, "setIpDontFragment0", "(IZZ)V", |_c, a| {
            linux_dont_fragment_set(a)?;
            Ok(None)
        });
        r.register(lso, "getQuickAck0", "(I)Z", |_c, a| {
            Ok(Some(Value::Int(i32::from(
                ext_opt_get(a, ExtOpt::QuickAck)? != 0,
            ))))
        });
        r.register(lso, "setQuickAck0", "(IZ)V", |_c, a| {
            ext_opt_set(a, ExtOpt::QuickAck)?;
            Ok(None)
        });
        // `-1` stays the answer for a socket with no peer credentials, because
        // it is this native's OWN documented failure sentinel, not a
        // placeholder: `ExtendedSocketOptions.getSoPeerCred` decodes the long as
        // (uid<<32)|gid and turns a -1 uid/gid into `SocketException("Not a unix
        // domain socket")` — which is exactly right for the TCP sockets that
        // make up almost every caller. What changed is that a real AF_UNIX
        // socket now gets its real SO_PEERCRED instead of the sentinel.
        r.register(lso, "getSoPeerCred0", "(I)J", |_c, a| {
            Ok(Some(Value::Long(ext_opt_peer_cred(a))))
        });
        r.register(lso, "getIncomingNapiId0", "(I)I", |_c, a| {
            Ok(Some(Value::Int(ext_opt_get(a, ExtOpt::IncomingNapiId)?)))
        });
        r.register(lso, "getTcpKeepAliveProbes0", "(I)I", |_c, a| {
            Ok(Some(Value::Int(ext_opt_get(a, ExtOpt::KeepAliveProbes)?)))
        });
        r.register(lso, "getTcpKeepAliveTime0", "(I)I", |_c, a| {
            Ok(Some(Value::Int(ext_opt_get(a, ExtOpt::KeepAliveTime)?)))
        });
        r.register(lso, "getTcpKeepAliveIntvl0", "(I)I", |_c, a| {
            Ok(Some(Value::Int(ext_opt_get(a, ExtOpt::KeepAliveIntvl)?)))
        });
        r.register(lso, "setTcpKeepAliveProbes0", "(II)V", |_c, a| {
            ext_opt_set(a, ExtOpt::KeepAliveProbes)?;
            Ok(None)
        });
        r.register(lso, "setTcpKeepAliveTime0", "(II)V", |_c, a| {
            ext_opt_set(a, ExtOpt::KeepAliveTime)?;
            Ok(None)
        });
        r.register(lso, "setTcpKeepAliveIntvl0", "(II)V", |_c, a| {
            ext_opt_set(a, ExtOpt::KeepAliveIntvl)?;
            Ok(None)
        });
    }

    // NIO-SERVER-SOCKET: `IOUtil.newFD(int)` calls `setfdVal(fd, value)` to
    // stash the OS fd integer into `FileDescriptor.fd`. JDK-25 implements this
    // as a native; without it the real `NioSocketImpl.create()` path throws
    // `UnsatisfiedLinkError` right after `Net.socket0`. We write the value into
    // the descriptor's `fd` field (slot 0), matching `IOUtil.fdVal`'s reader
    // and `net_fd_from_descriptor`.
    r.register(
        "sun/nio/ch/IOUtil",
        "setfdVal",
        "(Ljava/io/FileDescriptor;I)V",
        |ctx, args| {
            let fd_obj = obj_arg(args, 0)?;
            let val = int_arg(args, 1);
            ctx.set_field_by_name(fd_obj, "fd", Value::Int(val));
            Ok(None)
        },
    );
    // KEEP: the `poll*Value()` family is specified to return the platform's
    // POLLIN/POLLOUT/POLLERR/POLLHUP/POLLNVAL/POLLCONN bit constants — the real
    // JNI implementations return exactly these compile-time values too. A
    // constant here is the whole method, not a placeholder; `NET_POLL*` are the
    // platform-correct values `net_poll` itself compares against.
    r.register(net, "pollinValue", "()S", |_c, _a| {
        Ok(Some(Value::Int(NET_POLLIN)))
    });
    r.register(net, "polloutValue", "()S", |_c, _a| {
        Ok(Some(Value::Int(NET_POLLOUT)))
    });
    r.register(net, "pollerrValue", "()S", |_c, _a| {
        Ok(Some(Value::Int(NET_POLLERR)))
    });
    r.register(net, "pollhupValue", "()S", |_c, _a| {
        Ok(Some(Value::Int(NET_POLLHUP)))
    });
    r.register(net, "pollnvalValue", "()S", |_c, _a| {
        Ok(Some(Value::Int(NET_POLLNVAL)))
    });
    r.register(net, "pollconnValue", "()S", |_c, _a| {
        Ok(Some(Value::Int(NET_POLLCONN)))
    });
    r.set_category(__prev_cat);
}

// Helper used in tests — expose a way to peek at the map without going through
// the Java-visible API. Not pub(crate) because test_support is cfg(test)-only.
#[cfg(test)]
pub(crate) fn _test_handle_count() -> usize {
    net_sockets().read().len()
}

#[cfg(test)]
pub(crate) fn _test_peek_kind(fd: i32) -> &'static str {
    let map = net_sockets().read();
    match map.get(&fd) {
        Some(NetSocketHandle::Unbound) => "unbound",
        Some(NetSocketHandle::Listener(_)) => "listener",
        Some(NetSocketHandle::Stream(_)) => "stream",
        Some(NetSocketHandle::Closed) => "closed",
        None => "missing",
    }
}

/// Convenience wrapper used by some call paths that want to hand us a
/// prebuilt `TcpListener`. Exposed primarily for JDK-internal tooling that
/// opens listeners out-of-band (not required by any current test but cheap
/// to provide).
pub fn register_prebuilt_listener(l: TcpListener) -> i32 {
    register_handle(NetSocketHandle::Listener(Arc::new(Mutex::new(l))))
}

/// Resolve an "address:port" string into a `SocketAddr`. Used by tests and
/// any path that needs to hand `bind0` a pre-resolved socket address.
pub fn parse_socket_addr(text: &str) -> Option<SocketAddr> {
    text.parse().ok()
}

