//! T16.5 + T19.5 net support.
//!
//! T16.5 (pre-existing): `java.net.MulticastSocket` factory overrides with
//! null-tolerant argument handling. Supersedes the `phases_late` registrations
//! that NPE when tests call instance methods with zero-arg sentinel patterns.
//!
//! T19.5 (new): `sun.nio.ch.Net` — the private JDK NIO facade that
//! `ServerSocketChannelImpl` / `SocketChannelImpl` dispatch through. Without
//! these natives, no HTTP listener ever binds. Implements the socket0 /
//! bind0 / listen / accept / connect0 / read0 / write0 / shutdown / close
//! surface plus getIntOption0/setIntOption0 and localPort/localInetAddress
//! queries.
//!
//! Layouts:
//!   MulticastSocket = 5 fields (port=0, closed=1, timeout=2, fd_id=3, ttl=4)

use cratonvm_native_api::{NativeContext, NativeMethodRegistry};
use cratonvm_types::error::{MethodCallFailed, MethodCallResult, RuntimeError};
use cratonvm_types::{ObjectRef, Value};
use parking_lot::{Mutex, RwLock};
use std::io::{ErrorKind, Read, Write};
use std::net::{Shutdown, SocketAddr, TcpListener, TcpStream};
use std::sync::atomic::{AtomicI32, Ordering};
use std::sync::Arc;
use std::sync::OnceLock;
use std::time::Duration;

// Net socket-id and (fd, level, opt) keys are all internal monotonic / small
// integer tuples generated by the VM. FxHashMap avoids SipHash overhead on
// the hot getIntOption0/setIntOption0 path (Netty pings these constantly
// during channel setup). Matches native-api's T10.9.B migration.
use crate::io_flags;
use rustc_hash::FxHashMap;

// ---------------------------------------------------------------------------
// Socket byte capture (debug). When CRATONVM_SOCKET_CAPTURE=<prefix> is set,
// every byte read/written via net_read0/net_write0 is appended to a raw
// per-fd, per-direction file: `<prefix>.r.<fd>` (bytes the VM READ, i.e. the
// daemon→worker stream) and `<prefix>.w.<fd>` (bytes the VM WROTE). The raw
// read stream can then be replayed through ObjectInputStream in isolation to
// deterministically reproduce a deserialization desync without the full
// Gradle/Hibernate stack. A textual index (`<prefix>.idx`) records op order
// with direction/fd/length so the interleave can be reconstructed.
// ---------------------------------------------------------------------------

fn socket_capture_prefix() -> Option<&'static str> {
    crate::io_flags().socket_capture_prefix.as_deref()
}

pub(crate) fn socket_capture(dir: char, fd: i32, data: &[u8]) {
    let Some(prefix) = socket_capture_prefix() else {
        return;
    };
    if data.is_empty() {
        return;
    }
    use std::io::Write as _;
    // Serialize across the VM's concurrent socket reader/writer threads so the
    // per-fd raw streams and the index never interleave mid-record.
    static CAP_LOCK: Mutex<()> = Mutex::new(());
    let _g = CAP_LOCK.lock();
    // Raw per-fd, per-direction stream (concatenated, replayable).
    let raw_path = format!("{prefix}.{dir}.{fd}");
    if let Ok(mut f) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&raw_path)
    {
        let _ = f.write_all(data);
    }
    // Textual index of op order (direction/fd/length + first 16 bytes hex).
    let idx_path = format!("{prefix}.idx");
    if let Ok(mut f) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&idx_path)
    {
        let head: String = data.iter().take(16).map(|b| format!("{b:02x}")).collect();
        let _ = writeln!(f, "{dir} fd={fd} len={} {head}", data.len());
    }
}

// ---------------------------------------------------------------------------
// T16.5 — java.net.MulticastSocket overrides (pre-existing)
// ---------------------------------------------------------------------------

/// Last value each `MulticastSocket.setOption` call was given, keyed by
/// `(fd, option name)`. Backs `getOption` for the options the std `UdpSocket`
/// API exposes no getter for (SO_SNDBUF / SO_RCVBUF / SO_REUSEADDR); live reads
/// off the socket take precedence where they exist. Keys are plain integers and
/// strings, so this table holds no heap references and needs no GC root.
fn ms_option_cache() -> &'static Mutex<FxHashMap<(i32, String), i32>> {
    static T: OnceLock<Mutex<FxHashMap<(i32, String), i32>>> = OnceLock::new();
    T.get_or_init(|| Mutex::new(FxHashMap::default()))
}

/// Box a socket-option value as the type its `SocketOption<T>` declares.
/// `getOption` is generic (`<T> T`), so a raw `Value::Int` returned for an
/// object-typed method coerces to null and the caller NPEs on the unbox.
fn ms_box_option(ctx: &mut dyn NativeContext, opt_name: &str, raw: i32) -> MethodCallResult {
    if matches!(
        opt_name,
        "SO_BROADCAST" | "SO_REUSEADDR" | "SO_REUSEPORT" | "IP_MULTICAST_LOOP"
    ) {
        ctx.invoke(
            "java/lang/Boolean",
            "valueOf",
            "(Z)Ljava/lang/Boolean;",
            &[Value::Int(if raw != 0 { 1 } else { 0 })],
        )
    } else {
        ctx.invoke(
            "java/lang/Integer",
            "valueOf",
            "(I)Ljava/lang/Integer;",
            &[Value::Int(raw)],
        )
    }
}

/// Register MulticastSocket overrides. Called after the phase-72 registrations
/// so this wins for the signatures we implement. Other (non-overridden) methods
/// continue to be served by the phase-72 impls.
pub fn register_multicast_socket_overrides(r: &mut NativeMethodRegistry) {
    let __prev_cat = r.current_category();
    r.set_category(cratonvm_native_api::NativeKind::Bridge);
    let ms = "java/net/MulticastSocket";

    // `<init>(I port)` — populate the five fields; auto-bind to 0.0.0.0:<port>.
    // Null-tolerant: if `this` is null (e.g. a test passes Object(None) as the
    // first arg), just return Ok(None) — nothing to populate.
    r.register(ms, "<init>", "(I)V", |ctx, args| {
        let this = match args.first() {
            Some(Value::Object(Some(o))) => *o,
            _ => return Ok(None),
        };
        let port = args.get(1).and_then(|v| v.as_int()).unwrap_or(0);
        let bind_addr = format!("0.0.0.0:{port}");
        // MulticastSocket sets SO_REUSEADDR before bind (JDK semantics) so
        // multiple receivers / repeated bind cycles can share the group port.
        let fd_id = ctx
            .fd_table()
            .open_udp_reuse(Some(&bind_addr))
            .map_err(|e| RuntimeError::IOException {
                message: format!("MulticastSocket bind failed: {e}"),
            })?;
        let nfields = ctx.object_num_fields(this);
        if nfields >= 5 {
            ctx.set_field(this, 0, Value::Int(port));
            ctx.set_field(this, 1, Value::Int(0)); // closed=0
            ctx.set_field(this, 2, Value::Int(0)); // timeout
            ctx.set_field(this, 3, Value::Int(fd_id as i32));
            ctx.set_field(this, 4, Value::Int(1)); // default TTL
        } else if nfields >= 4 {
            ctx.set_field(this, 0, Value::Int(port));
            ctx.set_field(this, 1, Value::Int(0));
            ctx.set_field(this, 2, Value::Int(0));
            ctx.set_field(this, 3, Value::Int(fd_id as i32));
        } else {
            // Fewer fields than expected — still close the fd we opened to
            // avoid leaks; downstream methods will see an invalid fd.
            let _ = ctx.fd_table().close(fd_id);
        }
        Ok(None)
    });

    // `<init>()` — no-arg ctor. Same logic as `<init>(I)` but with port=0.
    r.register(ms, "<init>", "()V", |ctx, args| {
        let this = match args.first() {
            Some(Value::Object(Some(o))) => *o,
            _ => return Ok(None),
        };
        let fd_id = ctx
            .fd_table()
            .open_udp_reuse(Some("0.0.0.0:0"))
            .map_err(|e| RuntimeError::IOException {
                message: format!("MulticastSocket bind failed: {e}"),
            })?;
        let nfields = ctx.object_num_fields(this);
        if nfields >= 5 {
            ctx.set_field(this, 0, Value::Int(0));
            ctx.set_field(this, 1, Value::Int(0));
            ctx.set_field(this, 2, Value::Int(0));
            ctx.set_field(this, 3, Value::Int(fd_id as i32));
            ctx.set_field(this, 4, Value::Int(1));
        } else {
            let _ = ctx.fd_table().close(fd_id);
        }
        Ok(None)
    });

    // `getTimeToLive()` — null-tolerant: if called with `&[]` or `Object(None)`,
    // return the default TTL of 1 (matches JDK constructor default).
    r.register(ms, "getTimeToLive", "()I", |ctx, args| match args.first() {
        Some(Value::Object(Some(o))) if ctx.object_num_fields(*o) >= 5 => {
            Ok(Some(ctx.get_field(*o, 4)))
        }
        _ => Ok(Some(Value::Int(1))),
    });

    // `close()` — null-tolerant.
    r.register(ms, "close", "()V", |ctx, args| {
        let this = match args.first() {
            Some(Value::Object(Some(o))) => *o,
            _ => return Ok(None),
        };
        let nfields = ctx.object_num_fields(this);
        if nfields >= 4 {
            let fd_id = ctx.get_field(this, 3).as_int().unwrap_or(-1);
            if fd_id >= 0 {
                let _ = ctx.fd_table().close(fd_id as u32);
            }
        }
        if nfields >= 2 {
            ctx.set_field(this, 1, Value::Int(1)); // closed=1
        }
        if nfields >= 4 {
            ctx.set_field(this, 3, Value::Int(-1));
        }
        Ok(None)
    });

    // --- DatagramSocket-surface methods that route through the real-JDK
    // `delegate` (JDK 14+ rewrote DatagramSocket/MulticastSocket as thin
    // wrappers over a lazily-created `DatagramSocketImpl` delegate). Our socket
    // is fd_table-backed and never populates that delegate, so the inherited
    // bytecode throws `InternalError("Should not get here")`. These natives are
    // force-selected over the bytecode (see
    // `interpreter.rs::force_native_over_real_jdk_bytecode`) and operate on the
    // 5-field layout (port/closed/timeout/fd/ttl). DatagramPacket fields are
    // read/written through the real accessors (getData/getLength/…), which work
    // on the real-JDK packet regardless of its private field layout.

    // setOption(SocketOption, Object) -> DatagramSocket. Apply the options we
    // model best-effort; accept the rest as a no-op. Returns `this`.
    r.register(
        ms,
        "setOption",
        "(Ljava/net/SocketOption;Ljava/lang/Object;)Ljava/net/DatagramSocket;",
        |ctx, args| {
            let this = match args.first() {
                Some(Value::Object(Some(o))) => *o,
                _ => return Ok(None),
            };
            let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
            let opt_name = match args.get(1) {
                Some(Value::Object(Some(o))) => {
                    match ctx.invoke_virtual(*o, "name", "()Ljava/lang/String;", &[]) {
                        Ok(Some(Value::Object(Some(s)))) => ctx.read_string(s).unwrap_or_default(),
                        _ => String::new(),
                    }
                }
                _ => String::new(),
            };
            if fd >= 0 {
                // Integer/Boolean both box their scalar at field 0 (real-JDK
                // `value`); read it directly to avoid a second upcall.
                let ival = match args.get(2) {
                    Some(Value::Object(Some(b))) => ctx.get_field(*b, 0).as_int(),
                    Some(Value::Int(n)) => Some(*n),
                    _ => None,
                };
                match opt_name.as_str() {
                    "SO_REUSEADDR" => {
                        let _ = ctx
                            .fd_table()
                            .udp_set_reuse_address(fd as u32, ival.unwrap_or(0) != 0);
                    }
                    "SO_SNDBUF" => {
                        if let Some(n) = ival {
                            let _ = ctx
                                .fd_table()
                                .udp_set_send_buffer_size(fd as u32, n.max(0) as usize);
                        }
                    }
                    "SO_RCVBUF" => {
                        if let Some(n) = ival {
                            let _ = ctx
                                .fd_table()
                                .udp_set_recv_buffer_size(fd as u32, n.max(0) as usize);
                        }
                    }
                    "IP_MULTICAST_TTL" => {
                        if let Some(n) = ival {
                            let _ = ctx.fd_table().udp_set_ttl(fd as u32, n.max(0) as u32);
                        }
                    }
                    "SO_BROADCAST" => {
                        let _ = ctx
                            .fd_table()
                            .udp_set_broadcast(fd as u32, ival.unwrap_or(0) != 0);
                    }
                    // IP_MULTICAST_LOOP / IP_MULTICAST_IF / IP_TOS / …: no-op.
                    _ => {}
                }
                if !opt_name.is_empty() {
                    // Mirror the request so `getOption` can answer the options
                    // the std socket API gives us no getter for (SO_SNDBUF /
                    // SO_RCVBUF / SO_REUSEADDR). Without this the pair could
                    // never agree.
                    ms_option_cache()
                        .lock()
                        .insert((fd, opt_name.clone()), ival.unwrap_or(0));
                }
            }
            Ok(Some(Value::Object(Some(this))))
        },
    );
    // getOption returned a constant null while `setOption` above really applied
    // SO_REUSEADDR / SO_SNDBUF / SO_RCVBUF / IP_MULTICAST_TTL to the fd — so the
    // socket accepted an option and then denied having it. Null is also not a
    // legal answer here: `getOption` is declared `<T> T`, so every caller
    // unboxes the result and gets an NPE rather than a wrong value. (This
    // registration wins in BOTH run modes: it is registered after phase 72, and
    // `interpreter.rs::force_native_over_real_jdk_bytecode` lists
    // MulticastSocket.getOption so it also beats the real JDK bytecode.)
    //
    // Read what the live socket can tell us, fall back to what `setOption` was
    // told, and raise the exception the JDK spec names for an option this
    // surface does not model instead of answering null.
    r.register(
        ms,
        "getOption",
        "(Ljava/net/SocketOption;)Ljava/lang/Object;",
        |ctx, args| {
            let this = match args.first() {
                Some(Value::Object(Some(o))) => *o,
                _ => return Ok(Some(Value::Object(None))),
            };
            let opt_name = match args.get(1) {
                Some(Value::Object(Some(o))) => {
                    match ctx.invoke_virtual(*o, "name", "()Ljava/lang/String;", &[]) {
                        Ok(Some(Value::Object(Some(s)))) => ctx.read_string(s).unwrap_or_default(),
                        _ => String::new(),
                    }
                }
                _ => String::new(),
            };
            let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
            // Live reads first — these are the socket's actual state, so they
            // stay right even if something set the option behind our back.
            let live = if fd >= 0 {
                match opt_name.as_str() {
                    "SO_BROADCAST" => ctx
                        .fd_table()
                        .udp_try_clone(fd as u32)
                        .ok()
                        .and_then(|s| s.broadcast().ok())
                        .map(i32::from),
                    "IP_MULTICAST_LOOP" => ctx
                        .fd_table()
                        .udp_try_clone(fd as u32)
                        .ok()
                        .and_then(|s| s.multicast_loop_v4().ok())
                        .map(i32::from),
                    // The 5-field layout mirrors the multicast TTL in slot 4
                    // (written by `setTimeToLive`/`setOption`), and the JDK
                    // default for a fresh MulticastSocket is 1.
                    "IP_MULTICAST_TTL" => Some(if ctx.object_num_fields(this) >= 5 {
                        ctx.get_field(this, 4).as_int().unwrap_or(1)
                    } else {
                        1
                    }),
                    _ => None,
                }
            } else {
                None
            };
            let cached = live.or_else(|| {
                if fd < 0 {
                    return None;
                }
                ms_option_cache()
                    .lock()
                    .get(&(fd, opt_name.clone()))
                    .copied()
            });
            let raw = match cached {
                Some(v) => v,
                // Never set and not live-readable: answer the JDK default for
                // the options this surface models, and refuse the rest.
                None => match opt_name.as_str() {
                    "SO_BROADCAST" | "SO_REUSEADDR" | "IP_MULTICAST_LOOP" => 0,
                    "SO_SNDBUF" | "SO_RCVBUF" => 0,
                    "IP_MULTICAST_TTL" => 1,
                    _ => {
                        return Err(RuntimeError::UnsupportedOperationException {
                            message: format!("MulticastSocket option not supported: {opt_name}"),
                        }
                        .into())
                    }
                },
            };
            ms_box_option(ctx, &opt_name, raw)
        },
    );

    // setSoTimeout / setTimeToLive — store on the object and apply to the fd.
    r.register(ms, "setSoTimeout", "(I)V", |ctx, args| {
        let this = match args.first() {
            Some(Value::Object(Some(o))) => *o,
            _ => return Ok(None),
        };
        let t = args.get(1).and_then(|v| v.as_int()).unwrap_or(0);
        ctx.set_field(this, 2, Value::Int(t));
        let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
        if fd >= 0 {
            let to = if t > 0 {
                Some(Duration::from_millis(t as u64))
            } else {
                None
            };
            let _ = ctx.fd_table().udp_set_read_timeout(fd as u32, to);
        }
        Ok(None)
    });
    r.register(ms, "getSoTimeout", "()I", |ctx, args| match args.first() {
        Some(Value::Object(Some(o))) => Ok(Some(ctx.get_field(*o, 2))),
        _ => Ok(Some(Value::Int(0))),
    });
    r.register(ms, "setTimeToLive", "(I)V", |ctx, args| {
        let this = match args.first() {
            Some(Value::Object(Some(o))) => *o,
            _ => return Ok(None),
        };
        let ttl = args.get(1).and_then(|v| v.as_int()).unwrap_or(1);
        let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
        if fd >= 0 {
            let _ = ctx.fd_table().udp_set_ttl(fd as u32, ttl.max(0) as u32);
        }
        if ctx.object_num_fields(this) >= 5 {
            ctx.set_field(this, 4, Value::Int(ttl));
        }
        Ok(None)
    });

    // joinGroup / leaveGroup (modern SocketAddress overload). Best-effort: a
    // host without a multicast-capable interface must not fail channel startup
    // (Tribes re-throws join failures), so swallow errors here.
    r.register(
        ms,
        "joinGroup",
        "(Ljava/net/SocketAddress;Ljava/net/NetworkInterface;)V",
        |ctx, args| {
            let this = match args.first() {
                Some(Value::Object(Some(o))) => *o,
                _ => return Ok(None),
            };
            let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
            if fd >= 0 {
                if let Some(Value::Object(Some(sa))) = args.get(1).copied() {
                    if let Some(ip) = ms_sockaddr_ipv4(ctx, sa) {
                        let _ = ctx.fd_table().udp_join_multicast_v4(
                            fd as u32,
                            &ip,
                            &std::net::Ipv4Addr::UNSPECIFIED,
                        );
                    }
                }
            }
            Ok(None)
        },
    );
    r.register(
        ms,
        "leaveGroup",
        "(Ljava/net/SocketAddress;Ljava/net/NetworkInterface;)V",
        |ctx, args| {
            let this = match args.first() {
                Some(Value::Object(Some(o))) => *o,
                _ => return Ok(None),
            };
            let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
            if fd >= 0 {
                if let Some(Value::Object(Some(sa))) = args.get(1).copied() {
                    if let Some(ip) = ms_sockaddr_ipv4(ctx, sa) {
                        let _ = ctx.fd_table().udp_leave_multicast_v4(
                            fd as u32,
                            &ip,
                            &std::net::Ipv4Addr::UNSPECIFIED,
                        );
                    }
                }
            }
            Ok(None)
        },
    );

    // send(DatagramPacket) — best-effort UDP send. Reads the packet through the
    // real accessors. Errors are swallowed so a routine multicast-send failure
    // does not abort channel startup (`McastServiceImpl.start` sends one packet
    // inline before spawning the sender thread).
    r.register(ms, "send", "(Ljava/net/DatagramPacket;)V", |ctx, args| {
        let this = match args.first() {
            Some(Value::Object(Some(o))) => *o,
            _ => return Ok(None),
        };
        let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
        if fd < 0 || ctx.get_field(this, 1).as_int().unwrap_or(0) != 0 {
            return Err(RuntimeError::IOException {
                message: "Socket closed".into(),
            }
            .into());
        }
        let pkt = match args.get(1) {
            Some(Value::Object(Some(p))) => *p,
            _ => return Ok(None),
        };
        // Every ms_iv_* accessor below runs Java bytecode (GC-capable), so
        // pin pkt and re-read it before each dispatch; fetch the data array
        // LAST so its address is post-GC-fresh for the bulk copy.
        let pkt_pin = ctx.pin_native_root(pkt);
        let addr = ms_iv_obj(ctx, pkt, "getAddress", "()Ljava/net/InetAddress;");
        let host = addr.and_then(|ia| ms_inet_host(ctx, ia));
        let pkt = ctx.read_native_pin(pkt_pin, pkt);
        let off = ms_iv_i32(ctx, pkt, "getOffset", "()I").unwrap_or(0).max(0) as usize;
        let pkt = ctx.read_native_pin(pkt_pin, pkt);
        let len = ms_iv_i32(ctx, pkt, "getLength", "()I").unwrap_or(0).max(0) as usize;
        let pkt = ctx.read_native_pin(pkt_pin, pkt);
        let port = ms_iv_i32(ctx, pkt, "getPort", "()I").unwrap_or(0);
        let pkt = ctx.read_native_pin(pkt_pin, pkt);
        let arr = ms_iv_obj(ctx, pkt, "getData", "()[B");
        if let (Some(arr), Some(host)) = (arr, host) {
            let alen = ctx.array_length(arr);
            let mut buf = vec![0u8; len];
            let n = (off + len).min(alen).saturating_sub(off);
            let _ = ctx.read_byte_array_into(arr, off, &mut buf[..n]);
            // Bracket the sendto in the GC-blocking protocol (it can park on
            // a full local socket buffer); no heap refs are used afterwards.
            ctx.begin_blocking_region();
            let _ = ctx
                .fd_table()
                .udp_send(fd as u32, &buf, &format!("{host}:{port}"));
            ctx.end_blocking_region();
        }
        ctx.unpin_native_roots(pkt_pin);
        Ok(None)
    });

    // receive(DatagramPacket) — fills the packet's backing buffer + length.
    // A read timeout surfaces as a real `java.net.SocketTimeoutException`
    // (see `udp_recv_error`) so callers that loop on it — Tribes'
    // `McastServiceImpl.receive` catches exactly that type and ignores it —
    // continue cleanly; every other recv error stays a plain IOException,
    // which is what the JDK does and what those callers' recovery paths
    // expect to see.
    r.register(
        ms,
        "receive",
        "(Ljava/net/DatagramPacket;)V",
        |ctx, args| {
            let this = match args.first() {
                Some(Value::Object(Some(o))) => *o,
                _ => return Ok(None),
            };
            let fd = ctx.get_field(this, 3).as_int().unwrap_or(-1);
            if fd < 0 || ctx.get_field(this, 1).as_int().unwrap_or(0) != 0 {
                return Err(RuntimeError::IOException {
                    message: "Socket closed".into(),
                }
                .into());
            }
            let timeout = ctx.get_field(this, 2).as_int().unwrap_or(0);
            if timeout > 0 {
                let _ = ctx
                    .fd_table()
                    .udp_set_read_timeout(fd as u32, Some(Duration::from_millis(timeout as u64)));
            }
            let pkt = match args.get(1) {
                Some(Value::Object(Some(p))) => *p,
                _ => return Ok(None),
            };
            // getData runs Java bytecode (GC-capable): pin pkt so every use
            // after a potential collection sees the post-GC address.
            let pkt_pin = ctx.pin_native_root(pkt);
            let arr = match ms_iv_obj(ctx, pkt, "getData", "()[B") {
                Some(a) => a,
                None => {
                    ctx.unpin_native_roots(pkt_pin);
                    return Err(RuntimeError::IOException {
                        message: "DatagramPacket has no buffer".into(),
                    }
                    .into());
                }
            };
            let pkt = ctx.read_native_pin(pkt_pin, pkt);
            let arr_pin = ctx.pin_native_root(arr);
            let cap = ctx.array_length(arr);
            let mut buf = vec![0u8; cap.max(1)];
            // GC-blocking audit (gc-blocked-thread-frame-stale-thread-mirror,
            // proper-fix item 2): this recv parks in the OS for up to
            // soTimeout — or indefinitely when no timeout is set. Without the
            // blocking-region bracket every cross-thread STW GC must wait for
            // the receiver to tick out of the syscall (Tribes' McastService
            // receiver stalled every collection by ~soTimeout, and a
            // timeout-less receive wedges `wait_for_all` outright). The pins
            // above are part of the deposited snapshot, so the socket/packet
            // graph stays rooted and remappable while the thread is parked.
            ctx.begin_blocking_region();
            let recv_result = ctx.fd_table().udp_recv(fd as u32, &mut buf);
            ctx.end_blocking_region();
            let pkt = ctx.read_native_pin(pkt_pin, pkt);
            let arr = ctx.read_native_pin(arr_pin, arr);
            match recv_result {
                Ok((n, src)) => {
                    let copy = n.min(cap);
                    ctx.write_byte_array_from(arr, 0, &buf[..copy]);
                    let _ =
                        ctx.invoke_virtual(pkt, "setLength", "(I)V", &[Value::Int(copy as i32)]);
                    // setLength ran bytecode: re-read pkt before the next
                    // dispatch on it.
                    let pkt = ctx.read_native_pin(pkt_pin, pkt);
                    if let Some(c) = src.rfind(':') {
                        if let Ok(p) = src[c + 1..].parse::<i32>() {
                            let _ = ctx.invoke_virtual(pkt, "setPort", "(I)V", &[Value::Int(p)]);
                        }
                    }
                    ctx.unpin_native_roots(pkt_pin);
                    Ok(None)
                }
                Err(e) => {
                    ctx.unpin_native_roots(pkt_pin);
                    Err(udp_recv_error(e))
                }
            }
        },
    );

    r.set_category(__prev_cat);
}

/// Classify a UDP `recv` failure into the Java exception the JDK would raise.
///
/// A datagram socket with `SO_TIMEOUT` set reports an expired read as
/// `WSAETIMEDOUT` on Windows (`ErrorKind::TimedOut`) and `EAGAIN`/
/// `EWOULDBLOCK` on Unix (`ErrorKind::WouldBlock`); the JDK turns both into
/// `java.net.SocketTimeoutException`. Returning a bare `java.io.IOException`
/// instead makes every `catch (SocketTimeoutException)` miss, which is not a
/// cosmetic difference for polling receivers: Tomcat Tribes'
/// `McastServiceImpl.ReceiverThread` treats anything else as a receive
/// **failure** — it logs, sleeps 500 ms (so the membership socket is only
/// listening half the time), skips the `checkExpired()` at the end of
/// `receive()`, and after `recoveryCounter` (10) such "errors" hands the
/// service to `RecoveryThread`, which stops and restarts membership
/// altogether. Since the poll timeout is the *normal* exit of every idle
/// receive, that turned steady-state membership into a stop/start churn and
/// members never converged.
pub(crate) fn udp_recv_error(e: std::io::Error) -> MethodCallFailed {
    if matches!(e.kind(), ErrorKind::TimedOut | ErrorKind::WouldBlock) {
        return RuntimeError::SocketTimeoutException {
            message: "Receive timed out".into(),
        }
        .into();
    }
    RuntimeError::IOException {
        message: format!("UDP recv: {e}"),
    }
    .into()
}

