// ---------- Read availability (FIONREAD) ----------
//
// `sun.nio.ch.Net.available(FileDescriptor)` reports how many bytes can be read
// without blocking — the `ioctl FIONREAD` / `ioctlsocket(FIONREAD)` equivalent.
// `NioSocketImpl.available()` (i.e. `Socket.getInputStream().available()`) calls
// it, and many Tomcat server tests do (DF04). `std::net::TcpStream` exposes no
// such query, so we issue the syscall directly: `ioctlsocket` via raw
// `#[link(name = "Ws2_32")]` FFI on Windows (matching the WSAPoll pattern in
// nio_selector.rs — no extra crate), `libc::ioctl` on Unix.

#[cfg(windows)]
#[link(name = "Ws2_32")]
extern "system" {
    // int ioctlsocket(SOCKET s, long cmd, u_long *argp);
    //   SOCKET = UINT_PTR (usize), long = c_long (i32 on Win64), u_long = u32.
    fn ioctlsocket(s: usize, cmd: i32, argp: *mut u32) -> i32;
}

/// FIONREAD on a raw OS socket handle. `None` on error / unsupported.
#[cfg(windows)]
fn fionread(raw: std::os::windows::io::RawSocket) -> Option<i32> {
    // FIONREAD = _IOR('f', 127, u_long) = 0x4004667F on Windows.
    const FIONREAD: i32 = 0x4004_667F;
    let mut n: u32 = 0;
    // SAFETY: `raw` is a live SOCKET owned by a TcpStream we currently hold;
    // `n` is a valid out-pointer for the u_long result.
    let rc = unsafe { ioctlsocket(raw as usize, FIONREAD, &mut n) };
    if rc == 0 {
        Some(n.min(i32::MAX as u32) as i32)
    } else {
        None
    }
}

#[cfg(unix)]
fn fionread(raw: std::os::unix::io::RawFd) -> Option<i32> {
    let mut n: libc::c_int = 0;
    // SAFETY: `raw` is a live fd owned by a TcpStream we currently hold;
    // `n` is a valid out-pointer for the int result.
    let rc = unsafe { libc::ioctl(raw, libc::FIONREAD, &mut n) };
    if rc == 0 {
        Some((n as i32).max(0))
    } else {
        None
    }
}

/// Bytes readable without blocking on a `TcpStream` (the FIONREAD count), or
/// `None` on error. Shared with `socket_channel::tcp_stream_available`.
pub(crate) fn socket_available_stream(s: &TcpStream) -> Option<i32> {
    #[cfg(windows)]
    {
        use std::os::windows::io::AsRawSocket;
        fionread(s.as_raw_socket())
    }
    #[cfg(unix)]
    {
        use std::os::unix::io::AsRawFd;
        fionread(s.as_raw_fd())
    }
    #[cfg(not(any(windows, unix)))]
    {
        let _ = s;
        None
    }
}

// ---------- I/O ----------

// Per-thread reusable scratch buffer for the read0/write0 syscall staging
// area. A tight socket read/write loop calls these natives back-to-back; the
// previous `vec![0u8; len]` allocated AND zeroed a fresh heap buffer on every
// single call (see native-io-review.md, net.rs read0/write0 finding). Because
// each native is fully synchronous (the staged bytes are consumed before the
// call returns) the buffer is never aliased across calls, so a thread-local
// `Vec` reused across calls is sound and removes the per-op malloc + memset.
//
// The closure receives a mutable slice of EXACTLY `len` bytes. Growing the
// buffer zero-extends only the freshly added tail (amortized), so steady-state
// loops at a stable length pay zero allocation and zero zeroing. Callers must
// treat the slice contents as undefined on entry: read0 overwrites only the
// `[..n]` prefix it actually fills and reads back only that prefix; write0
// fully overwrites the whole slice before reading it. Neither observes stale
// tail bytes left by a prior call.
thread_local! {
    static IO_SCRATCH: std::cell::RefCell<Vec<u8>> =
        const { std::cell::RefCell::new(Vec::new()) };
}

/// Run `f` with a thread-local scratch slice of exactly `len` bytes, avoiding a
/// per-call heap allocation on the hot socket I/O path. The slice's initial
/// contents are unspecified (may contain bytes from a previous call); `f` must
/// not rely on them. The buffer only ever grows (zero-filling the new tail).
fn with_io_scratch<R>(len: usize, f: impl FnOnce(&mut [u8]) -> R) -> R {
    IO_SCRATCH.with(|cell| {
        let mut buf = cell.borrow_mut();
        if buf.len() < len {
            // `resize` zeroes only the newly added tail; existing capacity is
            // left as-is (its bytes are not observed — see module note above).
            buf.resize(len, 0);
        }
        f(&mut buf[..len])
    })
}

/// `CRATONVM_DBG_READ0LAT=1` — accumulate `net_read0`'s per-call cost by stage
/// and print a running mean every 4096 calls.
///
/// A mean rather than a single sample because the thing being chased is FIXED
/// overhead: one call tells you nothing about a cost that only matters because
/// it is paid tens of thousands of times, and a byte-at-a-time protocol parser
/// pays it per byte.
fn read0_lat_enabled() -> bool {
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *ON.get_or_init(|| cratonvm_types::flags::runtime_var_os("CRATONVM_DBG_READ0LAT").is_some())
}

static READ0_LAT: [std::sync::atomic::AtomicU64; 6] = [
    std::sync::atomic::AtomicU64::new(0),
    std::sync::atomic::AtomicU64::new(0),
    std::sync::atomic::AtomicU64::new(0),
    std::sync::atomic::AtomicU64::new(0),
    std::sync::atomic::AtomicU64::new(0),
    std::sync::atomic::AtomicU64::new(0),
];

fn read0_lat_record(fd_ns: u128, lookup_ns: u128, begin_ns: u128, recv_ns: u128, end_ns: u128) {
    use std::sync::atomic::Ordering::Relaxed;
    let add = |i: usize, v: u128| {
        READ0_LAT[i].fetch_add(v as u64, Relaxed);
    };
    add(0, fd_ns);
    add(1, lookup_ns);
    add(2, begin_ns);
    add(3, recv_ns);
    add(4, end_ns);
    let n = READ0_LAT[5].fetch_add(1, Relaxed) + 1;
    if n % 4096 == 0 {
        let g = |i: usize| READ0_LAT[i].load(Relaxed) / n;
        eprintln!(
            "[read0lat] n={n} mean ns: fd_field={} registry={} begin_region={} recv={} \
             end_region={} total={}",
            g(0),
            g(1),
            g(2),
            g(3),
            g(4),
            g(0) + g(1) + g(2) + g(3) + g(4)
        );
    }
}

/// How long a parked blocking `read0` waits inside one poll before re-asking
/// the registry whether its socket was closed under it.
///
/// This is a liveness bound, not a latency cost: the poll returns the instant
/// the socket becomes readable, so ordinary traffic is never delayed by it. It
/// only bounds how long a reader stays parked after another thread closes the
/// socket. Same role as [`NET_ACCEPT_CLOSE_POLL`] on the accept side.
const NET_READ_CLOSE_POLL_MS: i32 = 25;

/// The error a parked `read0` reports once its socket has been closed from
/// another thread.
///
/// [`net_err`] has no `Interrupted` arm, so this reaches its default
/// `SocketException: …` rendering. `NioSocketImpl.endRead` then replaces it
/// with `SocketException("Socket closed")` regardless, because the close
/// already moved the impl to `ST_CLOSING` — and that is exactly what HotSpot
/// produces for a blocked read whose socket is closed.
fn net_read_closed_err() -> std::io::Error {
    std::io::Error::new(ErrorKind::Interrupted, "socket closed")
}

/// Is `fd` still a live stream? [`close_net_fd`] replaces the entry with
/// `NetSocketHandle::Closed`, so this flips exactly when Java closed it.
fn net_stream_still_registered(fd: i32) -> bool {
    matches!(
        net_sockets().read().get(&fd),
        Some(NetSocketHandle::Stream(_))
    )
}

/// One `recv`, reissued for as long as it reports EINTR. See the AUDIT
/// 2026-07-26 note in [`net_read0`] for why EINTR must never escape to Java.
fn read_retry_eintr(stream: &TcpStream, buf: &mut [u8]) -> std::io::Result<usize> {
    // The std impl is `impl Read for &TcpStream`, so this reads through a
    // shared stream without excluding a peer writer on the same fd.
    let mut r = stream;
    loop {
        match r.read(buf) {
            Err(e) if crate::eintr::is_eintr(&e) => continue,
            other => return other,
        }
    }
}

/// A blocking `read0` that observes an asynchronous `close()`.
///
/// # Why the plain blocking read could not
///
/// `Socket.close()` on another thread reaches [`close_net_fd`], which marks the
/// registry slot `Closed` and issues `shutdown(Both)` — but it does **not**
/// close the OS handle, because this reader is holding an `Arc` clone of the
/// very `TcpStream` the map dropped. HotSpot's answer to the same situation is
/// `closesocket()` underneath the blocked `recv` (Windows) or `dup2` of a
/// pre-closed descriptor plus a signal (Unix, `NativeDispatcher.preClose`).
/// Neither is expressible over an `Arc<TcpStream>` without closing a handle
/// another thread is mid-syscall on, which is a use-after-close the moment the
/// OS recycles the number.
///
/// `shutdown` is not a substitute. On Linux `SHUT_RD` does wake a parked `recv`
/// with EOF, which is why this defect reads as Windows-only; Winsock does not —
/// only `closesocket` aborts a pending blocking call — so
/// `RJdkNet.soTimeoutAndAsyncClose`'s reader stayed parked until the test's own
/// timeout and reported "the blocked reader never woke up".
///
/// So park in `poll` instead of in `recv`, and re-ask the registry every
/// [`NET_READ_CLOSE_POLL_MS`]. That is the close-aware shape
/// [`net_accept_close_aware`] has carried on the accept side since 2026-05-17;
/// it costs one extra syscall on a read that would have blocked anyway, and
/// none of the registry lock is held across it.
fn net_read_close_aware(fd: i32, stream: &TcpStream, buf: &mut [u8]) -> std::io::Result<usize> {
    loop {
        let ready = match poll_stream_readable(stream, NET_READ_CLOSE_POLL_MS) {
            Some(result) => result?,
            // No poll primitive on this target: the pre-2026-08-07 blocking
            // read, which cannot see the close but at least still transfers.
            None => return read_retry_eintr(stream, buf),
        };
        // Ask AFTER the poll, so a close that lands while we are parked is seen
        // on the very next pass, and a close that raced the poll's readiness
        // still wins — HotSpot fails a read that a concurrent `close()` beat,
        // it does not hand back bytes on a socket Java has already closed.
        if !net_stream_still_registered(fd) {
            return Err(net_read_closed_err());
        }
        if !ready {
            continue;
        }
        // `WouldBlock` is deliberately propagated rather than re-parked: this
        // arm is only reachable when the OS fd is non-blocking despite the
        // recorded mode saying otherwise, and `net_read0` turns it into the
        // JDK's `IOStatus.UNAVAILABLE` (-2) sentinel that `NioSocketImpl`
        // answers with its own `Net.poll` + retry. Swallowing it here would
        // take that decision away from the caller's deadline.
        return read_retry_eintr(stream, buf);
    }
}

/// `read0(FileDescriptor fd, long address, int len) -> int`
///
/// Reads up to `len` bytes from the stream into the raw memory at `address`.
/// Returns bytes read, or -1 on EOF.
fn net_read0(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let addr = match args.get(1) {
        Some(Value::Long(v)) => *v,
        _ => 0,
    };
    let len = int_arg(args, 2);
    let len_usize = validate_native_range("read0", addr, len)?;
    if len_usize == 0 {
        return Ok(Some(Value::Int(0)));
    }
    // `CRATONVM_DBG_READ0LAT=1` -- where a socket read's FIXED per-call cost
    // goes. Measured 2026-08-06 with the payload already in the receive buffer
    // (no blocking, no wakeup, pure call cost): a single-byte
    // `InputStream.read()` costs ~55 us on CratonVM against ~1.5 us on HotSpot
    // (~35x), while BULK reads are comparable on both. That shape says fixed
    // overhead per call; this splits it across the four candidates -- the
    // FileDescriptor field read, the registry lookup, the blocking-region
    // brackets, and the recv itself -- instead of guessing which.
    let r0_t0 = read0_lat_enabled().then(std::time::Instant::now);
    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("read0: FileDescriptor has no fd id"))?;
    let r0_fd = r0_t0.map(|_| std::time::Instant::now());
    dbgnet!("read0 fd={fd:#x} len={len} addr={addr:#x}");

    // AUDIT 2026-05-17: clone the per-stream Arc out of the map under a
    // brief read-lock, drop the map lock, then perform the blocking read
    // on the per-socket Mutex. Otherwise the global map lock serializes
    // every Net I/O op against the longest-running read on any socket.
    let stream_handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(s)) => Arc::clone(s),
            _ => return Err(ioex("read0: fd not a stream")),
        }
    };
    let r0_lookup = r0_t0.map(|_| std::time::Instant::now());
    // Stage into a reusable per-thread scratch buffer (no per-call alloc/zero).
    with_io_scratch(len_usize, |buf| {
        let read_result = {
            // A blocking read can park in the OS indefinitely (waiting for the
            // peer to send / close). Bracket it in a GC-blocking region so a
            // stop-the-world GC requested meanwhile doesn't deadlock
            // `wait_for_all` waiting for this thread to reach a safepoint. See
            // socket_channel::ssc_accept for the full rationale.
            //
            // ...but ONLY when the read can actually park. A NON-BLOCKING fd's
            // `recv` returns `WouldBlock` immediately instead of waiting, so it
            // can never hold up a stop-the-world — and the region is not free:
            // `begin_blocking_region` retires the TLAB and calls
            // `deposit_root_snapshot()`, which publishes this thread's whole
            // Java root set, while `end_blocking_region` re-syncs refs against
            // any GC that ran. Measured 2026-08-06 with
            // `CRATONVM_DBG_READ0LAT=1`, means over 24 576 calls:
            //
            //   fd_field 91ns | registry 59ns | begin_region 9006ns
            //   | recv 819ns | end_region 6892ns | total 16867ns
            //
            // i.e. the brackets are ~94% of the call, ~20x the recv they guard.
            // That is the whole of the ~35x single-byte-read gap against
            // HotSpot, and it is paid PER BYTE by any byte-at-a-time protocol
            // parser. It is also paid on the JDK's own timed-read path:
            // `NioSocketImpl.timedRead` flips the fd non-blocking and polls
            // separately (in `Net.poll`, which keeps its region), so every
            // `Socket.setSoTimeout(..)` reader was paying a full root snapshot
            // per read for a call that cannot block.
            //
            // Safety rests on the mode, not on timing: there is no race where a
            // non-blocking fd starts parking. If the mode is unknown, assume
            // blocking and keep the region.
            let can_park = !net_fd_is_nonblocking(fd);
            if can_park {
                ctx.begin_blocking_region();
            }
            let r0_begin = r0_t0.map(|_| std::time::Instant::now());
            // AUDIT 2026-07-26 (native-io-audit): retry EINTR. A signal
            // delivered while parked in the kernel (SIGCHLD from a
            // `process.rs`-spawned child without SA_RESTART, a profiler or
            // JVMTI signal) surfaces as `ErrorKind::Interrupted` having
            // consumed ZERO bytes. `net_err` has no `Interrupted` arm, so it
            // used to become `SocketException: read0: Interrupted system
            // call` — a random, unreproducible mid-request connection abort
            // under load. `socket_channel::try_read_nb` already retries with
            // the same rationale ("EINTR consumes no bytes"); this is the
            // `NioSocketImpl` path (plain `Socket.getInputStream().read()`)
            // that was missed. Some Linux wrappers preserve it only as raw
            // errno 4. That retry now lives in `read_retry_eintr`.
            //
            // ASYNCHRONOUS CLOSE (2026-08-07): a bare blocking `recv` here is
            // also why a reader parked in `Socket.getInputStream().read()`
            // never noticed `Socket.close()` on another thread — the closing
            // thread cannot take the OS handle away while this thread holds an
            // `Arc` clone of it. `net_read_close_aware` parks in `poll` and
            // re-checks the registry instead; see its doc comment.
            let res = if can_park {
                net_read_close_aware(fd, &stream_handle, buf)
            } else {
                read_retry_eintr(&stream_handle, buf)
            };
            let r0_recv = r0_t0.map(|_| std::time::Instant::now());
            if can_park {
                ctx.end_blocking_region();
            }
            if let (Some(t0), Some(fdt), Some(look), Some(beg), Some(recv)) =
                (r0_t0, r0_fd, r0_lookup, r0_begin, r0_recv)
            {
                let end = std::time::Instant::now();
                read0_lat_record(
                    (fdt - t0).as_nanos(),
                    (look - fdt).as_nanos(),
                    (beg - look).as_nanos(),
                    (recv - beg).as_nanos(),
                    (end - recv).as_nanos(),
                );
            }
            res
        };
        // `NioSocketImpl.timedRead` puts the fd into non-blocking mode, then
        // expects the native dispatcher to return the JDK IOStatus.UNAVAILABLE
        // sentinel (-2). It parks until data is available or its Java-level
        // deadline expires. Blocking here instead delays the timeout until the
        // peer closes, which turns an idle socket into a false EOF.
        let n = match read_result {
            Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                return Ok(Some(Value::Int(-2)));
            }
            result => result.map_err(|error| net_err("read0", error))?,
        };
        if n == 0 {
            return Ok(Some(Value::Int(-1)));
        }
        socket_capture('r', fd, &buf[..n]);
        // Store the bytes into the caller's native buffer. `addr` may be a real
        // OS pointer OR an `Unsafe.allocateMemory` arena handle (DirectByteBuffer
        // from `Util.getTemporaryDirectBuffer`) — route through the context so an
        // arena handle lands in the off-heap store instead of being dereferenced
        // raw (which SIGSEGVs on the synthetic 2^36-based handle).
        if !ctx.copy_to_native_memory(addr, &buf[..n]) {
            return Err(ioex(format!(
                "read0: invalid destination address {addr:#x}"
            )));
        }
        Ok(Some(Value::Int(n as i32)))
    })
}

/// `Net.poll(FileDescriptor fd, int events, long timeoutMillis) -> int`.
///
/// JDK 25's `NioSocketImpl` uses this after a non-blocking I/O operation
/// reports `IOStatus.UNAVAILABLE`. The event mask is significant: timed reads
/// park on `POLLIN`, while a non-blocking write parks on `POLLOUT`. The old
/// `TcpStream::peek` loop only detected incoming bytes, so a client whose
/// output buffer filled waited for a *response* instead of writable capacity;
/// Tomcat then hit its 20-second request timeout and aborted the connection.
///
/// Use the OS poll primitive directly. Besides handling read and write
/// readiness faithfully, this leaves the stream's persistent blocking mode
/// untouched, which matters because the JDK toggles it around timed connects
/// and reads.
///
/// LISTENER fds go through here too: `NioSocketImpl.timedAccept` parks on
/// `Net.poll(fd, POLLIN, remainingMillis)` between its `Net.accept` attempts.
/// Answering `0` immediately for anything that is not a Stream (the old
/// behaviour) turned that park into a busy-spin that burned a core for the
/// whole SO_TIMEOUT.
/// `sun/nio/ch/IOUtil.configureBlocking(FileDescriptor, boolean)`
///
/// `NioSocketImpl` flips the OS fd to non-blocking when it enforces a
/// Java-level SO_TIMEOUT. `net_read0` then returns IOStatus.UNAVAILABLE and
/// `Net.poll` handles the timed wait. This must alter the real socket; a no-op
/// makes read0 block until peer close and incorrectly report EOF.
///
/// # DEADLOCK (2026-08-05) — the OTHER half of the cycle `net_poll` closed
///
/// The listener arm used to run `listener.lock().set_nonblocking(..)` with the
/// registry read guard still alive, which is the lock order
///
/// ```text
///     registry-read  ->  listener-mutex
/// ```
///
/// while `net_accept` takes the opposite one: it holds `listener_handle.lock()`
/// across `net_listener_still_registered`, for the whole of a blocking accept.
/// Two orders is a cycle, and `parking_lot`'s fair `RwLock` is what closes it —
/// once any writer is queued (`register_handle` from a `socket0`, `remove_fd`
/// from a close) new readers block, so the accept thread's nested read waits, it
/// never releases the listener mutex, this thread never gets that mutex, and the
/// read guard it is still holding never drops. All three park at 0% CPU, which
/// is the signature of the retired `bounded-socket-operations-hang-about-one-run
/// -in-five` record. Reachable from any `ServerSocketChannel.configureBlocking`
/// next to an accept.
///
/// The fix is this file's own convention, stated at a dozen other sites as
/// "clone the Arc under a brief read-lock, drop the map lock, then do the work".
/// Every handle variant is an `Arc`, so hoisting the clone out costs one
/// refcount bump and removes the order entirely.
fn net_configure_blocking(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let blocking = args.get(1).and_then(|value| value.as_int()).unwrap_or(0) != 0;
    let Some(fd) = net_fd_from_descriptor(ctx, fd_obj) else {
        dbgnet!("configureBlocking: FileDescriptor has no fd id (blocking={blocking})");
        return Ok(None);
    };
    // Record the request regardless of the fd's current registry state. If the
    // fd is still `Unbound` (pre-`connect0`) this is the ONLY record of it —
    // see `net_pending_nonblocking`.
    net_pending_nonblocking().write().insert(fd, !blocking);
    enum ConfigureTarget {
        Stream(Arc<TcpStream>),
        Listener(Arc<Mutex<TcpListener>>),
        Deferred(&'static str),
    }
    let target = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(stream)) => ConfigureTarget::Stream(Arc::clone(stream)),
            Some(NetSocketHandle::Listener(listener)) => {
                ConfigureTarget::Listener(Arc::clone(listener))
            }
            Some(NetSocketHandle::Unbound) => ConfigureTarget::Deferred("unbound"),
            Some(NetSocketHandle::Closed) => ConfigureTarget::Deferred("closed"),
            None => ConfigureTarget::Deferred("MISSING"),
        }
    };
    match target {
        ConfigureTarget::Stream(stream) => {
            dbgnet!("configureBlocking fd={fd:#x} kind=stream blocking={blocking}");
            stream
                .set_nonblocking(!blocking)
                .map_err(|error| net_err("configureBlocking", error))?
        }
        ConfigureTarget::Listener(listener) => {
            dbgnet!("configureBlocking fd={fd:#x} kind=listener blocking={blocking}");
            listener
                .lock()
                .set_nonblocking(!blocking)
                .map_err(|error| net_err("configureBlocking", error))?
        }
        ConfigureTarget::Deferred(kind) => {
            dbgnet!("configureBlocking fd={fd:#x} kind={kind} blocking={blocking} deferred");
        }
    }
    Ok(None)
}

fn net_poll(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let events = int_arg(args, 1);
    let timeout_millis = match args.get(2) {
        Some(Value::Long(value)) => *value,
        Some(Value::Int(value)) => *value as i64,
        _ => 0,
    };
    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("poll: FileDescriptor has no fd id"))?;
    // DEADLOCK (2026-08-05): the listener arm used to `return
    // net_poll_listener(..)` from INSIDE this block. A `return` evaluates its
    // expression before the block's locals are dropped, so the entire listener
    // poll — up to the caller's full SO_TIMEOUT — ran while this thread still
    // held a READ guard on the registry, and `net_poll_listener`'s loop calls
    // `net_listener_still_registered`, which takes that SAME read lock again.
    //
    // `parking_lot::RwLock` is fair: once a writer is queued, new readers
    // block. So a `socket0` on another Java thread (`register_handle`, a
    // `write()`) arriving between the outer read and the nested one wedges all
    // three — the writer waits for the outer reader, the outer reader waits on
    // its own nested read, and nothing can release. Measured on
    // `probes/JdkOnlyCensusLoadProbe`: 2 hangs in 40 runs, every thread parked
    // at 0% CPU, `gdb` showing `lock_exclusive` under `register_handle` against
    // `lock_shared_slow` under `net_listener_still_registered`.
    //
    // Note what this is NOT: `net_poll_listener` was already careful to hold
    // the LISTENER mutex only for a bounded slice ("never across an unbounded
    // wait"). The registry guard it inherited from its caller was the one
    // nobody was looking at.
    //
    // The guard's scope now ends before any call that can re-enter the
    // registry. Cloning the handle first is cheap: every variant is an `Arc`
    // or a unit.
    //
    // FOUND TWICE, INDEPENDENTLY, THE SAME DAY, with the same mechanism and the
    // same fix. The other diagnosis came from the VM's own watchdog rather than
    // gdb — `--stack-dump-on-timeout=45` inside `timeout 90`, 6 hangs in 25
    // runs, all six frame dumps identical (accept thread last in `Net.poll`,
    // main thread last in `Net.socket0`) — and it carries the A/B this comment
    // does not: 12 interleaved waves of 10 concurrent probes, **44/120 hangs
    // before, 0/120 after**. It also establishes that THIS FIX ALONE IS NOT
    // SUFFICIENT: with only the guard release, the same harness still scored
    // 10/60. What reaches zero is this plus the EINTR arm in `net_poll_raw`
    // below, which landed separately on 2026-08-02 for an unrelated symptom.
    // See the retired `bounded-socket-operations-hang-about-one-run-in-five`
    // record, which also closes the second half of the cycle in
    // `net_configure_blocking`.
    let target = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(stream)) => Some(PollTarget::Stream(Arc::clone(stream))),
            Some(NetSocketHandle::Listener(listener)) => {
                Some(PollTarget::Listener(Arc::clone(listener)))
            }
            _ => None,
        }
    };
    let stream = match target {
        Some(PollTarget::Listener(listener)) => {
            return net_poll_listener(ctx, &listener, fd, events, timeout_millis)
        }
        Some(PollTarget::Stream(stream)) => stream,
        None => return Ok(Some(Value::Int(0))),
    };
    let timeout = if timeout_millis < 0 {
        -1
    } else {
        timeout_millis.min(i64::from(i32::MAX)) as i32
    };
    ctx.begin_blocking_region();
    let result = net_poll_stream_close_aware(fd, &stream, events, timeout)
        .map(|ready| Some(Value::Int(if ready { 1 } else { 0 })))
        .map_err(|error| net_err("poll", error));
    ctx.end_blocking_region();
    result
}

/// What `net_poll` found for an fd, cloned OUT of the registry so the read
/// guard can be dropped before the poll runs. See the deadlock note in
/// `net_poll`: holding the registry guard across the poll is what wedged the
/// VM, because the poll loop re-reads the registry.
enum PollTarget {
    Listener(Arc<Mutex<TcpListener>>),
    Stream(Arc<TcpStream>),
}

/// Longest single OS poll a STREAM wait is allowed to sit in before it re-asks
/// the registry whether its socket was closed under it. Same role, and the same
/// 25 ms, as [`NET_READ_CLOSE_POLL_MS`] on the blocking-read side.
const NET_STREAM_POLL_SLICE_MS: i32 = 25;

/// `Net.poll` on a connected stream, made observant of an asynchronous
/// `Socket.close()`.
///
/// # The half of asynchronous close that the `read0` fix could not reach
///
/// `net_read_close_aware` (2026-08-07) fixed the reader that parks in
/// `SocketDispatcher.read0`. But `NioSocketImpl` only parks there when the OS fd
/// is in BLOCKING mode, and a single call decides that for the whole life of the
/// socket: `implConnect` runs `configureNonBlockingIfNeeded(fd, millis > 0)`, so
/// a connect with a timeout latches `nonBlocking = true` permanently
/// (`endConnect` never restores it). Every later untimed `read()` on that socket
/// therefore takes the OTHER branch of `implRead`:
///
/// ```text
///   n = tryRead(..)                 // read0 -> WouldBlock -> IOStatus.UNAVAILABLE
///   while (okayToRetry(n) && isOpen()) {
///       park(fd, Net.POLLIN);       // <- Net.poll(fd, POLLIN, -1): HERE, not in read0
///       n = tryRead(..);
///   }
/// ```
///
/// Measured on HotSpot 25.0.3 by dumping the parked reader's stack: a socket
/// built with `new Socket(host, port)` parks in `SocketDispatcher.read0`, while
/// one built with `new Socket()` + `connect(addr, 10000)` parks in `Net.poll`.
/// That is the entire difference between `RJdkNet` (passing) and
/// `RChannelInterrupt` (a reader still blocked 15 s after `close()`), and it is
/// why covering only `read0` looked like a complete fix.
///
/// The wakeup mechanism is the registry, not the OS. `close()` on the other
/// thread reaches `NativeDispatcher.preClose` — NOT `close0`, because
/// `NioSocketImpl.close` defers the real close while `readerThread != 0` — which
/// marks this fd `Closed` in [`net_sockets`] but cannot take the OS handle away
/// while this thread holds an `Arc` clone of the same `TcpStream`. Winsock only
/// aborts a pending `WSAPoll` on `closesocket`; the `shutdown(Both)` that
/// `close_net_fd` issues does not. So slice the wait and re-ask the registry,
/// exactly as [`net_poll_listener`] and [`net_accept_close_aware`] already do.
///
/// Answering "ready" on deregistration (rather than "timed out") is the listener
/// arm's convention and is what makes the outcome faithful: the caller's next
/// `tryRead` finds the fd is no longer a stream and raises the concrete error,
/// which `NioSocketImpl.endRead` renders as `SocketException("Socket closed")` —
/// the exact exception HotSpot produces, measured 3/3 at ~410 ms for a close
/// issued 400 ms after the read parked.
///
/// # Races
///
/// The registry check is at the TOP of the loop, before the first poll, so a
/// close that lands between `tryRead`'s `UNAVAILABLE` and this park is caught
/// with no wait at all — the pre-park case a check-only-after-the-poll shape
/// would delay by a full slice. A close that lands while parked is caught on the
/// next pass, within [`NET_STREAM_POLL_SLICE_MS`]. A close that landed even
/// earlier never reaches here: `net_poll`'s registry lookup finds `Closed` and
/// returns immediately, and `implRead` calls `tryRead` again regardless of the
/// poll's answer, so that path raises the same error rather than spinning.
///
/// Cost on a healthy socket is zero: the poll still returns the instant the
/// stream is readable/writable, so no byte is delayed. Only a wait that would
/// have blocked anyway pays extra syscalls, at 40/s — the rate a blocking reader
/// on the same socket already pays inside `net_read_close_aware`.
fn net_poll_stream_close_aware(
    fd: i32,
    stream: &TcpStream,
    events: i32,
    timeout: i32,
) -> std::io::Result<bool> {
    // A zero timeout is a readiness PROBE, not a wait. Issue it once and answer
    // what the OS says; running it through the deadline loop below would make
    // the first `remaining.is_zero()` fire before any poll and report "not
    // ready" for a socket that is.
    if timeout == 0 {
        return net_poll_stream(stream, events, 0);
    }
    // poll(2) convention: negative waits forever, positive is a bound.
    let deadline =
        (timeout > 0).then(|| std::time::Instant::now() + Duration::from_millis(timeout as u64));
    loop {
        if !net_stream_still_registered(fd) {
            return Ok(true);
        }
        let slice = match deadline {
            Some(deadline) => {
                let remaining = deadline.saturating_duration_since(std::time::Instant::now());
                if remaining.is_zero() {
                    return Ok(false);
                }
                (remaining.as_millis() as i64).min(i64::from(NET_STREAM_POLL_SLICE_MS)) as i32
            }
            None => NET_STREAM_POLL_SLICE_MS,
        };
        match net_poll_stream(stream, events, slice) {
            Ok(true) => return Ok(true),
            // Not ready yet — and on Unix also the EINTR arm of `net_poll_raw`,
            // which reports "not ready" on purpose so the caller's deadline is
            // recomputed instead of the whole wait restarting. This loop is that
            // caller now, and it recomputes from `deadline` on every pass.
            Ok(false) => {}
            Err(error) => return Err(error),
        }
    }
}

/// Longest single OS poll a listener wait is allowed to sit in. A
/// `ServerSocket.close()` does not close the OS listener out from under a
/// parked `Net.poll` (the registry entry is marked `Closed` while this Arc
/// keeps the handle alive — see `net_accept_close_aware`), so slice the wait
/// and re-check registration, exactly as the blocking accept loop does.
const NET_LISTENER_POLL_SLICE_MS: i32 = 50;

/// `Net.poll` for a listener fd: wait for an incoming connection.
///
/// Returns 1 (ready) both when a connection is pending and when the
/// `ServerSocket` was closed underneath us — in the latter case the JDK's
/// following `Net.accept` reports the close as a `SocketException`, which is
/// what a blocked `accept()` must see.
fn net_poll_listener(
    ctx: &mut dyn NativeContext,
    listener: &Mutex<TcpListener>,
    fd: i32,
    events: i32,
    timeout_millis: i64,
) -> MethodCallResult {
    // poll(2) convention, matching the stream path: negative waits forever,
    // 0 returns immediately, positive is a bound.
    let deadline = (timeout_millis >= 0)
        .then(|| std::time::Instant::now() + Duration::from_millis(timeout_millis as u64));
    ctx.begin_blocking_region();
    let result = loop {
        if !net_listener_still_registered(fd) {
            break Ok(true);
        }
        let slice = match deadline {
            Some(deadline) => {
                let remaining = deadline.saturating_duration_since(std::time::Instant::now());
                if remaining.is_zero() {
                    break Ok(false);
                }
                (remaining.as_millis() as i64).min(i64::from(NET_LISTENER_POLL_SLICE_MS)) as i32
            }
            None => NET_LISTENER_POLL_SLICE_MS,
        };
        // Hold the listener lock only for the bounded poll — never across an
        // unbounded wait, which would block a concurrent close/accept.
        let polled = {
            let guard = listener.lock();
            net_poll_raw(net_raw_handle_of_listener(&guard), events, slice)
        };
        match polled {
            Ok(true) => break Ok(true),
            Ok(false) => {}
            Err(e) => break Err(e),
        }
    };
    ctx.end_blocking_region();
    match result {
        Ok(ready) => Ok(Some(Value::Int(i32::from(ready)))),
        Err(error) => Err(net_err("poll", error)),
    }
}

