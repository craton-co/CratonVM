    /// The half `t19_5_close_unblocks_blocking_stream_read` above does NOT
    /// cover, and the one `RJdkNet.soTimeoutAndAsyncClose` asserts: that test
    /// registers the CLIENT and then asserts the SERVER's read wakes, i.e. it
