//! T16.5 + T19.5 net support.
//!
//! T16.5 (pre-existing): `java.net.MulticastSocket` factory overrides with
//! null-tolerant argument handling. Supersedes the `phases_late` registrations
//! that NPE when tests call instance methods with zero-arg sentinel patterns.
//!
//! T19.5 (new): `sun.nio.ch.Net` — the private JDK NIO facade that
//! `ServerSocketChannelImpl` / `SocketChannelImpl` dispatch through. Without
//! these natives, no HTTP listener ever binds. Implements the socket0 /
//! bind0 / listen / accept / connect0 / read0 / write0 / shutdown / close
//! surface plus getIntOption0/setIntOption0 and localPort/localInetAddress
//! queries.
//!
//! Layouts:
//!   MulticastSocket = 5 fields (port=0, closed=1, timeout=2, fd_id=3, ttl=4)

use cratonvm_native_api::{NativeContext, NativeMethodRegistry};
use cratonvm_types::error::{MethodCallFailed, MethodCallResult, RuntimeError};
use cratonvm_types::{ObjectRef, Value};
use parking_lot::{Mutex, RwLock};
use std::io::{ErrorKind, Read, Write};
use std::net::{Shutdown, SocketAddr, TcpListener, TcpStream};
use std::sync::atomic::{AtomicI32, Ordering};
use std::sync::Arc;
use std::sync::OnceLock;
use std::time::Duration;

// Net socket-id and (fd, level, opt) keys are all internal monotonic / small
// integer tuples generated by the VM. FxHashMap avoids SipHash overhead on
// the hot getIntOption0/setIntOption0 path (Netty pings these constantly
// during channel setup). Matches native-api's T10.9.B migration.
use rustc_hash::FxHashMap;

// ---------------------------------------------------------------------------
// Socket byte capture (debug). When CRATONVM_SOCKET_CAPTURE=<prefix> is set,
// every byte read/written via net_read0/net_write0 is appended to a raw
// per-fd, per-direction file: `<prefix>.r.<fd>` (bytes the VM READ, i.e. the
// daemon→worker stream) and `<prefix>.w.<fd>` (bytes the VM WROTE). The raw
// read stream can then be replayed through ObjectInputStream in isolation to
// deterministically reproduce a deserialization desync without the full
// Gradle/Hibernate stack. A textual index (`<prefix>.idx`) records op order
// with direction/fd/length so the interleave can be reconstructed.
// ---------------------------------------------------------------------------

fn socket_capture_prefix() -> Option<&'static str> {
    static PREFIX: OnceLock<Option<String>> = OnceLock::new();
    PREFIX
        .get_or_init(|| {
            std::env::var("CRATONVM_SOCKET_CAPTURE")
                .ok()
                .filter(|s| !s.is_empty())
        })
        .as_deref()
}

pub(crate) fn socket_capture(dir: char, fd: i32, data: &[u8]) {
    let Some(prefix) = socket_capture_prefix() else {
        return;
    };
    if data.is_empty() {
        return;
    }
    use std::io::Write as _;
    // Serialize across the VM's concurrent socket reader/writer threads so the
    // per-fd raw streams and the index never interleave mid-record.
    static CAP_LOCK: Mutex<()> = Mutex::new(());
    let _g = CAP_LOCK.lock();
    // Raw per-fd, per-direction stream (concatenated, replayable).
    let raw_path = format!("{prefix}.{dir}.{fd}");
    if let Ok(mut f) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&raw_path)
    {
        let _ = f.write_all(data);
    }
    // Textual index of op order (direction/fd/length + first 16 bytes hex).
    let idx_path = format!("{prefix}.idx");
    if let Ok(mut f) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&idx_path)
    {
        let head: String = data.iter().take(16).map(|b| format!("{b:02x}")).collect();
        let _ = writeln!(f, "{dir} fd={fd} len={} {head}", data.len());
    }
}

