// ---------- Read availability (FIONREAD) ----------
//
// `sun.nio.ch.Net.available(FileDescriptor)` reports how many bytes can be read
// without blocking — the `ioctl FIONREAD` / `ioctlsocket(FIONREAD)` equivalent.
// `NioSocketImpl.available()` (i.e. `Socket.getInputStream().available()`) calls
// it, and many Tomcat server tests do (DF04). `std::net::TcpStream` exposes no
// such query, so we issue the syscall directly: `ioctlsocket` via raw
// `#[link(name = "Ws2_32")]` FFI on Windows (matching the WSAPoll pattern in
// nio_selector.rs — no extra crate), `libc::ioctl` on Unix.

#[cfg(windows)]
#[link(name = "Ws2_32")]
extern "system" {
    // int ioctlsocket(SOCKET s, long cmd, u_long *argp);
    //   SOCKET = UINT_PTR (usize), long = c_long (i32 on Win64), u_long = u32.
    fn ioctlsocket(s: usize, cmd: i32, argp: *mut u32) -> i32;
}

/// FIONREAD on a raw OS socket handle. `None` on error / unsupported.
#[cfg(windows)]
fn fionread(raw: std::os::windows::io::RawSocket) -> Option<i32> {
    // FIONREAD = _IOR('f', 127, u_long) = 0x4004667F on Windows.
    const FIONREAD: i32 = 0x4004_667F;
    let mut n: u32 = 0;
    // SAFETY: `raw` is a live SOCKET owned by a TcpStream we currently hold;
    // `n` is a valid out-pointer for the u_long result.
    let rc = unsafe { ioctlsocket(raw as usize, FIONREAD, &mut n) };
    if rc == 0 {
        Some(n.min(i32::MAX as u32) as i32)
    } else {
        None
    }
}

#[cfg(unix)]
fn fionread(raw: std::os::unix::io::RawFd) -> Option<i32> {
    let mut n: libc::c_int = 0;
    // SAFETY: `raw` is a live fd owned by a TcpStream we currently hold;
    // `n` is a valid out-pointer for the int result.
    let rc = unsafe { libc::ioctl(raw, libc::FIONREAD, &mut n) };
    if rc == 0 {
        Some((n as i32).max(0))
    } else {
        None
    }
}

/// Bytes readable without blocking on a `TcpStream` (the FIONREAD count), or
/// `None` on error. Shared with `socket_channel::tcp_stream_available`.
pub(crate) fn socket_available_stream(s: &TcpStream) -> Option<i32> {
    #[cfg(windows)]
    {
        use std::os::windows::io::AsRawSocket;
        fionread(s.as_raw_socket())
    }
    #[cfg(unix)]
    {
        use std::os::unix::io::AsRawFd;
        fionread(s.as_raw_fd())
    }
    #[cfg(not(any(windows, unix)))]
    {
        let _ = s;
        None
    }
}

// ---------- I/O ----------

// Per-thread reusable scratch buffer for the read0/write0 syscall staging
// area. A tight socket read/write loop calls these natives back-to-back; the
// previous `vec![0u8; len]` allocated AND zeroed a fresh heap buffer on every
// single call (see native-io-review.md, net.rs read0/write0 finding). Because
// each native is fully synchronous (the staged bytes are consumed before the
// call returns) the buffer is never aliased across calls, so a thread-local
// `Vec` reused across calls is sound and removes the per-op malloc + memset.
//
// The closure receives a mutable slice of EXACTLY `len` bytes. Growing the
// buffer zero-extends only the freshly added tail (amortized), so steady-state
// loops at a stable length pay zero allocation and zero zeroing. Callers must
// treat the slice contents as undefined on entry: read0 overwrites only the
// `[..n]` prefix it actually fills and reads back only that prefix; write0
// fully overwrites the whole slice before reading it. Neither observes stale
// tail bytes left by a prior call.
thread_local! {
    static IO_SCRATCH: std::cell::RefCell<Vec<u8>> =
        const { std::cell::RefCell::new(Vec::new()) };
}

/// Run `f` with a thread-local scratch slice of exactly `len` bytes, avoiding a
/// per-call heap allocation on the hot socket I/O path. The slice's initial
/// contents are unspecified (may contain bytes from a previous call); `f` must
/// not rely on them. The buffer only ever grows (zero-filling the new tail).
fn with_io_scratch<R>(len: usize, f: impl FnOnce(&mut [u8]) -> R) -> R {
    IO_SCRATCH.with(|cell| {
        let mut buf = cell.borrow_mut();
        if buf.len() < len {
            // `resize` zeroes only the newly added tail; existing capacity is
            // left as-is (its bytes are not observed — see module note above).
            buf.resize(len, 0);
        }
        f(&mut buf[..len])
    })
}

/// `read0(FileDescriptor fd, long address, int len) -> int`
///
/// Reads up to `len` bytes from the stream into the raw memory at `address`.
/// Returns bytes read, or -1 on EOF.
fn net_read0(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let addr = match args.get(1) {
        Some(Value::Long(v)) => *v,
        _ => 0,
    };
    let len = int_arg(args, 2);
    let len_usize = validate_native_range("read0", addr, len)?;
    if len_usize == 0 {
        return Ok(Some(Value::Int(0)));
    }
    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("read0: FileDescriptor has no fd id"))?;
    dbgnet!("read0 fd={fd:#x} len={len} addr={addr:#x}");

    // AUDIT 2026-05-17: clone the per-stream Arc out of the map under a
    // brief read-lock, drop the map lock, then perform the blocking read
    // on the per-socket Mutex. Otherwise the global map lock serializes
    // every Net I/O op against the longest-running read on any socket.
    let stream_handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(s)) => Arc::clone(s),
            _ => return Err(ioex("read0: fd not a stream")),
        }
    };
    // Stage into a reusable per-thread scratch buffer (no per-call alloc/zero).
    with_io_scratch(len_usize, |buf| {
        let read_result = {
            // The std impl is `impl Read for &TcpStream` so we can read through
            // a shared TcpStream without excluding a peer writer on this fd.
            let mut r = &*stream_handle;
            // A blocking read can park in the OS indefinitely (waiting for the
            // peer to send / close). Bracket it in a GC-blocking region so a
            // stop-the-world GC requested meanwhile doesn't deadlock
            // `wait_for_all` waiting for this thread to reach a safepoint. See
            // socket_channel::ssc_accept for the full rationale.
            ctx.begin_blocking_region();
            // AUDIT 2026-07-26 (native-io-audit): retry EINTR. A signal
            // delivered while parked in the kernel (SIGCHLD from a
            // `process.rs`-spawned child without SA_RESTART, a profiler or
            // JVMTI signal) surfaces as `ErrorKind::Interrupted` having
            // consumed ZERO bytes. `net_err` has no `Interrupted` arm, so it
            // used to become `SocketException: read0: Interrupted system
            // call` — a random, unreproducible mid-request connection abort
            // under load. `socket_channel::try_read_nb` already retries with
            // the same rationale ("EINTR consumes no bytes"); this is the
            // `NioSocketImpl` path (plain `Socket.getInputStream().read()`)
            // that was missed. Some Linux wrappers preserve it only as raw
            // errno 4.
            let res = loop {
                match r.read(buf) {
                    Err(e)
                        if e.kind() == std::io::ErrorKind::Interrupted
                            || e.raw_os_error() == Some(4) =>
                    {
                        continue
                    }
                    other => break other,
                }
            };
            ctx.end_blocking_region();
            res
        };
        // `NioSocketImpl.timedRead` puts the fd into non-blocking mode, then
        // expects the native dispatcher to return the JDK IOStatus.UNAVAILABLE
        // sentinel (-2). It parks until data is available or its Java-level
        // deadline expires. Blocking here instead delays the timeout until the
        // peer closes, which turns an idle socket into a false EOF.
        let n = match read_result {
            Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                return Ok(Some(Value::Int(-2)));
            }
            result => result.map_err(|error| net_err("read0", error))?,
        };
        if n == 0 {
            return Ok(Some(Value::Int(-1)));
        }
        socket_capture('r', fd, &buf[..n]);
        // Store the bytes into the caller's native buffer. `addr` may be a real
        // OS pointer OR an `Unsafe.allocateMemory` arena handle (DirectByteBuffer
        // from `Util.getTemporaryDirectBuffer`) — route through the context so an
        // arena handle lands in the off-heap store instead of being dereferenced
        // raw (which SIGSEGVs on the synthetic 2^36-based handle).
        if !ctx.copy_to_native_memory(addr, &buf[..n]) {
            return Err(ioex(format!(
                "read0: invalid destination address {addr:#x}"
            )));
        }
        Ok(Some(Value::Int(n as i32)))
    })
}

/// `Net.poll(FileDescriptor fd, int events, long timeoutMillis) -> int`.
///
/// JDK 25's `NioSocketImpl` uses this after a non-blocking I/O operation
/// reports `IOStatus.UNAVAILABLE`. The event mask is significant: timed reads
/// park on `POLLIN`, while a non-blocking write parks on `POLLOUT`. The old
/// `TcpStream::peek` loop only detected incoming bytes, so a client whose
/// output buffer filled waited for a *response* instead of writable capacity;
/// Tomcat then hit its 20-second request timeout and aborted the connection.
///
/// Use the OS poll primitive directly. Besides handling read and write
/// readiness faithfully, this leaves the stream's persistent blocking mode
/// untouched, which matters because the JDK toggles it around timed connects
/// and reads.
///
/// LISTENER fds go through here too: `NioSocketImpl.timedAccept` parks on
/// `Net.poll(fd, POLLIN, remainingMillis)` between its `Net.accept` attempts.
/// Answering `0` immediately for anything that is not a Stream (the old
/// behaviour) turned that park into a busy-spin that burned a core for the
/// whole SO_TIMEOUT.
fn net_poll(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let events = int_arg(args, 1);
    let timeout_millis = match args.get(2) {
        Some(Value::Long(value)) => *value,
        Some(Value::Int(value)) => *value as i64,
        _ => 0,
    };
    let fd = net_fd_from_descriptor(ctx, fd_obj)
        .ok_or_else(|| ioex("poll: FileDescriptor has no fd id"))?;
    let stream = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(stream)) => Arc::clone(stream),
            Some(NetSocketHandle::Listener(listener)) => {
                let listener = Arc::clone(listener);
                return net_poll_listener(ctx, &listener, fd, events, timeout_millis);
            }
            _ => return Ok(Some(Value::Int(0))),
        }
    };
    let timeout = if timeout_millis < 0 {
        -1
    } else {
        timeout_millis.min(i64::from(i32::MAX)) as i32
    };
    ctx.begin_blocking_region();
    let result = net_poll_stream(&stream, events, timeout)
        .map(|ready| Some(Value::Int(if ready { 1 } else { 0 })))
        .map_err(|error| net_err("poll", error));
    ctx.end_blocking_region();
    result
}

/// Longest single OS poll a listener wait is allowed to sit in. A
/// `ServerSocket.close()` does not close the OS listener out from under a
/// parked `Net.poll` (the registry entry is marked `Closed` while this Arc
/// keeps the handle alive — see `net_accept_close_aware`), so slice the wait
/// and re-check registration, exactly as the blocking accept loop does.
const NET_LISTENER_POLL_SLICE_MS: i32 = 50;

/// `Net.poll` for a listener fd: wait for an incoming connection.
///
/// Returns 1 (ready) both when a connection is pending and when the
/// `ServerSocket` was closed underneath us — in the latter case the JDK's
/// following `Net.accept` reports the close as a `SocketException`, which is
/// what a blocked `accept()` must see.
fn net_poll_listener(
    ctx: &mut dyn NativeContext,
    listener: &Mutex<TcpListener>,
    fd: i32,
    events: i32,
    timeout_millis: i64,
) -> MethodCallResult {
    // poll(2) convention, matching the stream path: negative waits forever,
    // 0 returns immediately, positive is a bound.
    let deadline = (timeout_millis >= 0)
        .then(|| std::time::Instant::now() + Duration::from_millis(timeout_millis as u64));
    ctx.begin_blocking_region();
    let result = loop {
        if !net_listener_still_registered(fd) {
            break Ok(true);
        }
        let slice = match deadline {
            Some(deadline) => {
                let remaining = deadline.saturating_duration_since(std::time::Instant::now());
                if remaining.is_zero() {
                    break Ok(false);
                }
                (remaining.as_millis() as i64).min(i64::from(NET_LISTENER_POLL_SLICE_MS)) as i32
            }
            None => NET_LISTENER_POLL_SLICE_MS,
        };
        // Hold the listener lock only for the bounded poll — never across an
        // unbounded wait, which would block a concurrent close/accept.
        let polled = {
            let guard = listener.lock();
            net_poll_raw(net_raw_handle_of_listener(&guard), events, slice)
        };
        match polled {
            Ok(true) => break Ok(true),
            Ok(false) => {}
            Err(e) => break Err(e),
        }
    };
    ctx.end_blocking_region();
    match result {
        Ok(ready) => Ok(Some(Value::Int(i32::from(ready)))),
        Err(error) => Err(net_err("poll", error)),
    }
}

