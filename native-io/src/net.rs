/// `localPort(FileDescriptor fd) -> int`
fn net_local_port(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let fd = net_fd_from_descriptor(ctx, fd_obj).unwrap_or(-1);
    // AUDIT 2026-05-17: clone the handle Arc under a brief map read-lock,
    // then drop the map lock before issuing the syscall.
    enum Handle {
        L(Arc<Mutex<TcpListener>>),
        S(Arc<TcpStream>),
        None,
    }
    let handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Listener(l)) => Handle::L(Arc::clone(l)),
            Some(NetSocketHandle::Stream(s)) => Handle::S(Arc::clone(s)),
            _ => Handle::None,
        }
    };
    let port = match handle {
        Handle::L(l) => l.lock().local_addr().map(|a| a.port() as i32).unwrap_or(0),
        Handle::S(s) => s.local_addr().map(|a| a.port() as i32).unwrap_or(0),
        Handle::None => 0,
    };
    dbgnet!("localPort fd={fd:#x} -> {port}");
    Ok(Some(Value::Int(port)))
}

/// `localInetAddress(FileDescriptor fd) -> InetAddress`
fn net_local_inet_address(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let fd = net_fd_from_descriptor(ctx, fd_obj).unwrap_or(-1);
    // AUDIT 2026-05-17: clone handle Arc, drop map lock, then syscall.
    enum Handle {
        L(Arc<Mutex<TcpListener>>),
        S(Arc<TcpStream>),
        None,
    }
    let handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Listener(l)) => Handle::L(Arc::clone(l)),
            Some(NetSocketHandle::Stream(s)) => Handle::S(Arc::clone(s)),
            _ => Handle::None,
        }
    };
    let addr_text = match handle {
        Handle::L(l) => l
            .lock()
            .local_addr()
            .map(|a| a.ip().to_string())
            .unwrap_or_else(|_| "0.0.0.0".to_string()),
        Handle::S(s) => s
            .local_addr()
            .map(|a| a.ip().to_string())
            .unwrap_or_else(|_| "0.0.0.0".to_string()),
        Handle::None => "0.0.0.0".to_string(),
    };
    // A wildcard-bound fd answers with the wildcard it was BOUND with. See
    // `net_bound_wildcard_text`: the dual-stack listener under an unspecified
    // request reports `::` regardless of which wildcard was asked for, and the
    // JDK's contract is that `getInetAddress()` gives back the bind address.
    // Guarded on `is_unspecified` so a specific bind can never be overridden by
    // a stale entry for a recycled fd.
    let addr_text = match addr_text.parse::<std::net::IpAddr>() {
        Ok(ip) if ip.is_unspecified() => net_bound_wildcard_text()
            .read()
            .get(&fd)
            .cloned()
            .unwrap_or(addr_text),
        _ => addr_text,
    };
    net_inet_address_from_literal(ctx, &addr_text)
}

/// Build the `InetAddress` for a socket endpoint whose address we only know as
/// NUMERIC TEXT, by routing through `InetAddress.getByName` rather than filling
/// in instance slots by hand.
///
/// The hand-rolled version allocated the ABSTRACT `java/net/InetAddress` and
/// wrote the literal into slots 0 and 1 — the legacy two-slot layout. Two
/// things were wrong with the result: its class was `InetAddress` rather than
/// the concrete `Inet4Address`/`Inet6Address` an `instanceof` check expects,
/// and it claimed a hostName equal to its own IP, so `Socket.getLocalAddress()`
/// printed `127.0.0.1/127.0.0.1` where HotSpot prints `/127.0.0.1` (an address
/// resolved from a literal has no name to remember).
///
/// `getByName` is the JDK's own answer for a literal and already applies both
/// rules, so this defers to it instead of duplicating them in a crate that
/// cannot reach `native-builtins`. The freshly created String is pinned across
/// the re-entrant call, which runs Java and can therefore collect.
fn net_inet_address_from_literal(ctx: &mut dyn NativeContext, addr_text: &str) -> MethodCallResult {
    let text = ctx.create_string(addr_text);
    let pin = ctx.pin_native_root(text);
    let text = ctx.read_native_pin(pin, text);
    let built = ctx.invoke(
        "java/net/InetAddress",
        "getByName",
        "(Ljava/lang/String;)Ljava/net/InetAddress;",
        &[Value::Object(Some(text))],
    );
    ctx.unpin_native_roots(pin);
    match built {
        Ok(Some(v @ Value::Object(Some(_)))) => Ok(Some(v)),
        _ => Ok(Some(Value::Object(None))),
    }
}

/// `remotePort(FileDescriptor fd) -> int`
fn net_remote_port(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let fd = net_fd_from_descriptor(ctx, fd_obj).unwrap_or(-1);
    // AUDIT 2026-05-17: clone handle Arc, drop map lock, then syscall.
    let stream_handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(s)) => Some(Arc::clone(s)),
            _ => None,
        }
    };
    let port = match stream_handle {
        Some(s) => s.peer_addr().map(|a| a.port() as i32).unwrap_or(0),
        None => 0,
    };
    Ok(Some(Value::Int(port)))
}

/// `remoteInetAddress(FileDescriptor fd) -> InetAddress`
fn net_remote_inet_address(ctx: &mut dyn NativeContext, args: &[Value]) -> MethodCallResult {
    let fd_obj = obj_arg(args, 0)?;
    let fd = net_fd_from_descriptor(ctx, fd_obj).unwrap_or(-1);
    // AUDIT 2026-05-17: clone handle Arc, drop map lock, then syscall.
    let stream_handle = {
        let map = net_sockets().read();
        match map.get(&fd) {
            Some(NetSocketHandle::Stream(s)) => Some(Arc::clone(s)),
            _ => None,
        }
    };
    let addr_text = match stream_handle {
        Some(s) => s
            .peer_addr()
            .map(|a| a.ip().to_string())
            .unwrap_or_else(|_| "0.0.0.0".to_string()),
        None => "0.0.0.0".to_string(),
    };
    net_inet_address_from_literal(ctx, &addr_text)
}

