public class ArithmeticTest {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);

        long x = 1000000000L * 3;
        System.out.println(x);

        double d = 3.14;
        System.out.println(d);

        System.out.println("All arithmetic tests passed!");
    }
}
