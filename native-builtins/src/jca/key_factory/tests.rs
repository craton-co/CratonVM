#[test]
fn compact_keystore_private_key_get_encoded_uses_registry_der() {
    let alias = "key-factory-four-slot-private-key";
    let der = b"test-pkcs8-der".to_vec();
    let store = crate::keystore::LoadedKeyStore {
        entries: [(
            alias.to_string(),
            crate::keystore::KeyStoreEntry {
                alias: alias.to_string(),
                creation_time_ms: 0,
                kind: crate::keystore::EntryKind::PrivateKey {
                    key_der: der.clone(),
                    chain: Vec::new(),
                    protected: None,
                },
            },
        )]
        .into_iter()
        .collect(),
    };
    let store_id = crate::keystore::keystore_register(store);
    let mut ctx = crate::test_utils::MockNativeContext::new();
    let key = try_alloc_concurrent_synthetic(&mut ctx, "java/security/PrivateKey", 4).unwrap();
    let alias_hash = alias.as_bytes().iter().fold(0x811c_9dc5_u32, |hash, byte| {
        (hash ^ u32::from(*byte)).wrapping_mul(0x0100_0193)
    });
    let composite = ((i64::from(store_id) & 0xffff_ffff) << 32) | i64::from(alias_hash);
    ctx.set_field(key, KEY_FIELD_KEYID, Value::Long(composite));

    let encoded = key_get_encoded(&mut ctx, &[Value::Object(Some(key))])
        .expect("compact key getEncoded must succeed")
        .expect("compact key getEncoded must return a byte array");
    let Value::Object(Some(array)) = encoded else {
        panic!("expected byte[] from compact key getEncoded");
    };
    assert_eq!(read_byte_array(&mut ctx, array), der);
}

/// Dispatches `getAlgorithm`/`getEncoded` to the real natives under test,
/// so [`key_equals`] (which calls both virtually, exactly as bytecode
/// would) exercises the production code path rather than a stand-in.
fn key_accessor_hook(
    ctx: &mut crate::test_utils::MockNativeContext,
    receiver: ObjectRef,
    method_name: &str,
    descriptor: &str,
    _args: &[Value],
) -> Option<MethodCallResult> {
    match (method_name, descriptor) {
        ("getAlgorithm", "()Ljava/lang/String;") => {
            Some(key_get_algorithm(ctx, &[Value::Object(Some(receiver))]))
        }
        ("getEncoded", "()[B") => Some(key_get_encoded(ctx, &[Value::Object(Some(receiver))])),
        _ => None,
    }
}

/// KS-2/KS-3: two `KeyStore.getKey()` proxies over the SAME stored entry
/// (a store/reload round trip, or a second `getKey` call) must compare
/// equal — the real `Key.equals` contract is an encoding comparison, not
/// identity. Before `key_equals` was registered this fell back to
/// `Object.equals` and was always `false` for two distinct mirror objects.
#[test]
fn compact_keystore_private_keys_with_the_same_der_are_equal() {
    let alias = "ks2-ks3-round-trip";
    let der = b"test-pkcs8-der-for-equals".to_vec();
    let store = crate::keystore::LoadedKeyStore {
        entries: [(
            alias.to_string(),
            crate::keystore::KeyStoreEntry {
                alias: alias.to_string(),
                creation_time_ms: 0,
                kind: crate::keystore::EntryKind::PrivateKey {
                    key_der: der.clone(),
                    chain: Vec::new(),
                    protected: None,
                },
            },
        )]
        .into_iter()
        .collect(),
    };
    let store_id = crate::keystore::keystore_register(store);
    let mut ctx = crate::test_utils::MockNativeContext::new();
    ctx.set_invoke_virtual_hook(key_accessor_hook);
    let alias_hash = alias.as_bytes().iter().fold(0x811c_9dc5_u32, |hash, byte| {
        (hash ^ u32::from(*byte)).wrapping_mul(0x0100_0193)
    });
    let composite = ((i64::from(store_id) & 0xffff_ffff) << 32) | i64::from(alias_hash);

    // Two SEPARATE proxy objects over the same entry, exactly like two
    // `getKey(alias, pw)` calls (or one before and one after a
    // store/reload round trip) would allocate.
    let key_a =
        try_alloc_concurrent_synthetic(&mut ctx, "java/security/PrivateKey", 4).unwrap();
    ctx.set_field(key_a, KEY_FIELD_KEYID, Value::Long(composite));
    let key_b =
        try_alloc_concurrent_synthetic(&mut ctx, "java/security/PrivateKey", 4).unwrap();
    ctx.set_field(key_b, KEY_FIELD_KEYID, Value::Long(composite));

    let result = key_equals(
        &mut ctx,
        &[Value::Object(Some(key_a)), Value::Object(Some(key_b))],
    )
    .expect("equals must not throw")
    .expect("equals must return a boolean");
    assert_eq!(result, Value::Int(1), "same-DER keys must compare equal");

    // hashCode must agree with that equals verdict.
    let hash_a = key_hash_code(&mut ctx, &[Value::Object(Some(key_a))])
        .unwrap()
        .unwrap();
    let hash_b = key_hash_code(&mut ctx, &[Value::Object(Some(key_b))])
        .unwrap()
        .unwrap();
    assert_eq!(hash_a, hash_b, "equal keys must hash equal");

    // A DIFFERENT entry's key must not compare equal.
    let other_alias = "ks2-ks3-different-entry";
    let other_der = b"a-completely-different-key".to_vec();
    let other_store = crate::keystore::LoadedKeyStore {
        entries: [(
            other_alias.to_string(),
            crate::keystore::KeyStoreEntry {
                alias: other_alias.to_string(),
                creation_time_ms: 0,
                kind: crate::keystore::EntryKind::PrivateKey {
                    key_der: other_der,
                    chain: Vec::new(),
                    protected: None,
                },
            },
        )]
        .into_iter()
        .collect(),
    };
    let other_store_id = crate::keystore::keystore_register(other_store);
    let other_alias_hash = other_alias
        .as_bytes()
        .iter()
        .fold(0x811c_9dc5_u32, |hash, byte| {
            (hash ^ u32::from(*byte)).wrapping_mul(0x0100_0193)
        });
    let other_composite =
        ((i64::from(other_store_id) & 0xffff_ffff) << 32) | i64::from(other_alias_hash);
    let key_c =
        try_alloc_concurrent_synthetic(&mut ctx, "java/security/PrivateKey", 4).unwrap();
    ctx.set_field(key_c, KEY_FIELD_KEYID, Value::Long(other_composite));
    let result = key_equals(
        &mut ctx,
        &[Value::Object(Some(key_a)), Value::Object(Some(key_c))],
    )
    .unwrap()
    .unwrap();
    assert_eq!(
        result,
        Value::Int(0),
        "different-DER keys must not compare equal"
    );

    // Reflexivity: a key always equals itself, even without a working
    // `getEncoded` round trip (the identity fast path).
    let result = key_equals(
        &mut ctx,
        &[Value::Object(Some(key_a)), Value::Object(Some(key_a))],
    )
    .unwrap()
    .unwrap();
    assert_eq!(result, Value::Int(1));
}

#[test]
fn keypairgenerator_preserves_requested_algorithm_name() {
    // `Totally-Bogus` used to be in this list, back when `getInstance`
    // accepted every name. It is now covered by
    // `keypairgenerator_refuses_what_it_cannot_generate` — the generator it
    // used to hand back could not generate anything, so there was no
    // algorithm name worth preserving.
    for requested in ["RSASSA-PSS", "Ed448"] {
        let mut ctx = crate::test_utils::MockNativeContext::new();
        let name = ctx.create_string(requested);
        let kpg = kpg_get_instance(&mut ctx, &[Value::Object(Some(name))])
            .unwrap()
            .unwrap();
        let kpg_ref = match kpg {
            Value::Object(Some(o)) => o,
            other => panic!("expected KeyPairGenerator, got {other:?}"),
        };
        let result = kpg_get_algorithm(&mut ctx, &[Value::Object(Some(kpg_ref))])
            .unwrap()
            .unwrap();
        let actual = match result {
            Value::Object(Some(s)) => ctx.read_string(s).unwrap(),
            other => panic!("expected algorithm String, got {other:?}"),
        };
        assert_eq!(actual, requested);
    }
}

