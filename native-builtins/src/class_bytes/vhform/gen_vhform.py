import os, sys

OUT = sys.argv[1]
os.makedirs(OUT, exist_ok=True)

TYPES = [
    # letter, java type, class stem, numeric (getAndAdd), bitwise
    ("Z", "boolean", "Boolean", False, True),
    ("B", "byte", "Byte", True, True),
    ("C", "char", "Char", True, True),
    ("S", "short", "Short", True, True),
    ("I", "int", "Int", True, True),
    ("J", "long", "Long", True, True),
    ("F", "float", "Float", True, False),
    ("D", "double", "Double", True, False),
    ("L", "Object", "Reference", False, False),
]

READS = ["get", "getVolatile", "getOpaque", "getAcquire"]
WRITES = ["set", "setVolatile", "setOpaque", "setRelease"]
CAS = ["compareAndSet", "weakCompareAndSetPlain", "weakCompareAndSet",
       "weakCompareAndSetAcquire", "weakCompareAndSetRelease"]
CAE = ["compareAndExchange", "compareAndExchangeAcquire", "compareAndExchangeRelease"]
GAS = ["getAndSet", "getAndSetAcquire", "getAndSetRelease"]
GAA = ["getAndAdd", "getAndAddAcquire", "getAndAddRelease"]
BIT = [f"getAndBitwise{op}{o}" for op in ("Or", "And", "Xor") for o in ("", "Acquire", "Release")]

HEADER = """// SPDX-License-Identifier: Apache-2.0
// Copyright 2024-2026 Craton Software Company
//
// GENERATED by gen_vhform.py (interpreter round i6 wave 123, lane L4) (one file
// per variable type, read-only and read-write); edit the generator's rules,
// not one file. Rebuild every class of this directory with
//   javac --release 25 -d <out> cratonvm/internal/VhForm*.java
// (HotSpot 25.0.3's javac) and copy the .class files here.

package cratonvm.internal;

import java.lang.invoke.VarHandle;
"""


def cast(jt):
    return "" if jt == "Object" else f"({jt}) "


def methods(jt, names, shape, coords, coord_args):
    out = []
    for name in names:
        if name in READS:
            params, args, ret = "", "", jt
        elif name in WRITES:
            params, args, ret = f", {jt} value", "value", "void"
        elif name in CAS:
            params, args, ret = f", {jt} expected, {jt} value", "expected, value", "boolean"
        elif name in CAE:
            params, args, ret = f", {jt} expected, {jt} value", "expected, value", jt
        else:
            params, args, ret = f", {jt} value", "value", jt
        all_args = ", ".join(a for a in (coord_args, args) if a)
        call = f"handle.{name}({all_args})"
        if ret == "void":
            body = f"{call};"
        elif ret == "boolean" and name in CAS:
            body = f"return {call};"
        else:
            body = f"return {cast(jt)}{call};"
        out.append(f"    public static {ret} {name}(VarHandle handle{coords}{params}) {{\n        {body}\n    }}\n")
    return out


for letter, jt, stem, numeric, bitwise in TYPES:
    ro = f"VhForm{stem}ReadOnly"
    rw = f"VhForm{stem}"
    # read-only
    body = [HEADER, f"""
/**
 * The read access modes of a CratonVM-minted {jt}-valued field
 * {{@code VarHandle}} ({{@code --compatible}} only, under
 * {{@code CRATONVM_VH_REAL_VARFORM}}): the {{@code implClass}} of the real
 * {{@code java.lang.invoke.VarForm}} such a handle carries, as
 * {{@code VarHandle{stem}s.FieldInstanceReadOnly}} / {{@code FieldStaticReadOnly}}
 * are on HotSpot. {{@code VarForm.resolveMemberName}} finds these methods by the
 * access mode's name and the form's erased type with the {{@code VarHandle}}
 * first; a mode with no method here is unsupported (the JDK's own
 * {{@code isAccessModeSupported}} answer and {{@code getMemberName}}'s
 * {{@code UnsupportedOperationException}}). Each body is one
 * signature-polymorphic call on the handle, which the VM's natives serve.
 * Overloads: {{@code (VarHandle, Object)}} is an instance field,
 * {{@code (VarHandle)}} a static one.
 *
 * <p>Embedded by {{@code native-builtins/src/lang_invoke.rs}}
 * ({{@code VH_REAL_VARFORM_CLASSES}}), defined once per VM. The two static
 * fields hold the shared forms (instance, static), filed by the VM.
 */
public class {ro} {{

    public static Object FORM_INSTANCE;
    public static Object FORM_STATIC;

    {ro}() {{
    }}

"""]
    body += methods(jt, READS, "i", ", Object holder", "holder")
    body += methods(jt, READS, "s", "", "")
    body.append("}\n")
    with open(os.path.join(OUT, ro + ".java"), "wb") as f:
        f.write("".join(body).replace("\r\n", "\n").encode())
    names = WRITES + CAS + CAE + GAS + (GAA if numeric else []) + (BIT if bitwise else [])
    body = [HEADER, f"""
/**
 * The write and atomic access modes of a CratonVM-minted {jt}-valued field
 * {{@code VarHandle}}; the read modes are {{@link {ro}}}'s, inherited, as
 * {{@code VarHandle{stem}s.FieldInstanceReadWrite}} extends
 * {{@code FieldInstanceReadOnly}} on HotSpot. See {{@link {ro}}}.
 */
public final class {rw} extends {ro} {{

    public static Object FORM_INSTANCE;
    public static Object FORM_STATIC;

    private {rw}() {{
    }}

"""]
    body += methods(jt, names, "i", ", Object holder", "holder")
    body += methods(jt, names, "s", "", "")
    body.append("}\n")
    with open(os.path.join(OUT, rw + ".java"), "wb") as f:
        f.write("".join(body).replace("\r\n", "\n").encode())
print("ok")
