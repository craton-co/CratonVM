/// Declare a forwarder row on an Impl: the method has no row in the abstract carrier's lookup chain AT THIS
/// TIME, so the old carrier ran whatever the named public class resolves to, bytecode of `java.net.Socket`
/// and friends or a row some later registrar adds to the chain (`register_io_natives` runs after this
/// module's mirror). `invoke_special` on the public class resolves exactly that, at call time, with the
/// receiver's own class out of the lookup (so it cannot come back to this row).
macro_rules! forward_rows {
    ($r:expr, $imp:expr, $public:expr, $( ($m:literal, $d:literal) ),* $(,)?) => {
        $(
            if $r.resolve_id($imp, $m, $d).is_none() {
                $r.register_with_kind(
                    $imp,
                    $m,
                    $d,
                    |ctx, args| ctx.invoke_special($public, $m, $d, args),
                    NativeKind::SyntheticStub,
                );
            }
        )*
    };
}

